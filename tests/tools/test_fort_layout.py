import math

from tools import fort_layout as fl
from tools import make_fort_kit as kit


def test_the_ring_closes_around_the_gate_with_walls_no_longer_than_a_piece():
    segs, (gx, gy, gh) = fl.ring()
    assert 30 < len(segs) < 50
    for _mx, _my, _h, p, q in segs:
        assert math.dist(p, q) <= fl.WALL + 0.01
    # consecutive segments share a vertex, and the last one ends where the gate opening starts
    for (_a, _b, _c, _p, q), (_d, _e, _f, p, _q) in zip(segs, segs[1:]):
        assert math.dist(q, p) < 0.01
    assert abs(math.dist(segs[-1][4], (gx, gy)) - fl.GATE_GAP / 2) < 0.05
    assert abs(math.dist(segs[0][3], (gx, gy)) - fl.GATE_GAP / 2) < 0.05


def test_a_piece_turned_toward_a_point_opens_its_minus_y_side_that_way():
    heading = fl.toward((0, 0), (10, 0))
    assert round(math.sin(math.radians(heading)), 3) == 1.0 and round(-math.cos(math.radians(heading)), 3) == 0.0
    heading = fl.toward((0, 0), (0, -5))
    assert round(math.cos(math.radians(heading)), 3) == 1.0


def test_the_layout_uses_kit_models_and_keeps_only_listed_upstream_ones_without_a_ground_source():
    table = fl.rows(None)
    ids = set(kit.model_ids().values())
    assert all(r[0] in ids or r[0] in fl.KEEP for r in table)
    assert all(len(r) == 10 and r[3] == fl.DEFAULT_Z for r in table if r[0] in ids)
    assert sum(1 for r in table if r[0] == kit.model_ids()["fort_gate"]) == 1
    assert sum(1 for r in table if r[0] == kit.model_ids()["fort_tower"]) == len(fl.TOWERS)


def test_ground_heights_outside_the_plausible_band_fall_back_and_the_lowest_footprint_point_wins():
    def ground(points):
        return [14.9 if i % 3 == 0 else 12.4 if i % 3 == 1 else None for i in range(len(points))]

    table = fl.rows(ground)
    assert {r[3] for r in table if r[0] == kit.model_ids()["fort_wall4"]} <= {12.4, 14.9, fl.DEFAULT_Z}
    wall = next(r for r in table if r[0] == kit.model_ids()["fort_wall4"])
    assert wall[3] == 12.4


def test_rendered_rows_are_lua_tables_under_the_fort_name():
    text = fl.render([[20301, 1.0, 2.0, 3.0, 0, 0, 90.0, -1, -1, 350.0]])
    assert text.startswith("-- Generated by tools/fort_layout.py; do not edit.")
    assert '["Fort Defiance"] = {' in text and "{ 20301, 1.0, 2.0, 3.0, 0, 0, 90.0, -1, -1, 350.0 }," in text
