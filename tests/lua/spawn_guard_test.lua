local factory = dofile("resources/[scavengesurvive]/lib/modules/spawn_guard.lua")
local guard, player = factory.new(), {}
guard.reset(player, 0)
assert(not guard.ready(player, 0, 0, 0, 0))
assert(not guard.ready(player, 2000, 0, 0, -19), "loading Z drift stays unready")
assert(not guard.ready(player, 60000, 0, 0, -50), "loot needs a valid initial position")
assert(guard.ready(player, 60001, -2664, 280, 4))
assert(guard.ready(player, 60002, 0, 0, 0), "origin is not a permanent exemption")
guard.reset(player, 70000)
assert(not guard.ready(player, 70001, -2664, 280, 4), "every respawn settles first")
assert(guard.ready(player, 71000, -2664, 280, 4))
guard.forget(player)
assert(not guard.ready(player, 72000, -2664, 280, 4), "new lifecycle establishes a fresh position")
local anticheat = factory.new(10000)
anticheat.reset(player, 0)
assert(not anticheat.ready(player, 9999, 0, 0, -19))
assert(anticheat.ready(player, 10000, 0, 0, -19), "anticheat grace must end even at origin")
assert(anticheat.ready(player, 10001, 0, 0, 0))
print("spawn guard regression checks passed")
