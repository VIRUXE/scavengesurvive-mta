local bleeding = dofile("resources/[scavengesurvive]/character/shared/logic/bleeding.lua")
local function rng(values)
    local i = 0
    return function()
        i = i + 1
        return values[((i - 1) % #values) + 1]
    end
end
describe("bleeding visibility", function()
    it("starts showing with chance rate / 0.1", function()
        assert.is_true(bleeding.visible(false, 0.05, false, rng({ 0.49 })))
        assert.is_false(bleeding.visible(false, 0.05, false, rng({ 0.5 })))
    end)
    it("keeps showing with chance rate / 0.1", function()
        assert.is_true(bleeding.visible(true, 0.05, false, rng({ 0.5 })))
        assert.is_false(bleeding.visible(true, 0.05, false, rng({ 0.49 })))
    end)
    it("always shows at a rate of 0.1 or more", function()
        assert.is_true(bleeding.visible(false, 0.1, false, rng({ 0.999 })))
        assert.is_true(bleeding.visible(true, 0.2, false, rng({ 0 })))
    end)
    it("hides when not bleeding, blocked or NaN", function()
        assert.is_false(bleeding.visible(true, 0, false, rng({ 0 })))
        assert.is_false(bleeding.visible(true, 0.5, true, rng({ 0 })))
        assert.is_false(bleeding.visible(false, 0 / 0, false, rng({ 0 })))
    end)
end)
describe("blood pools", function()
    it("land within upstream's -0.2 .. 0.3 m and a random yaw", function()
        local dx, dy, rz = bleeding.poolOffset(rng({ 0, 0.999, 0.5 }))
        assert.is_true(math.abs(dx - 0.3) < 1e-9)
        assert.is_true(math.abs(dy + 0.2) < 1e-9)
        assert.is_true(math.abs(rz - 180) < 1e-9)
    end)
    it("reuse a ring of slots", function()
        assert.equal(2, bleeding.nextSlot(1, 15))
        assert.equal(1, bleeding.nextSlot(15, 15))
        assert.equal(1, bleeding.nextSlot(0, 15))
    end)
end)
