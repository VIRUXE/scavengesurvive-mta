local survival = dofile("resources/[scavengesurvive]/character/shared/logic/survival.lua")
local function rng(values)
    local i = 0
    return function()
        i = i + 1
        return values[((i - 1) % #values) + 1]
    end
end
describe("survival tick", function()
    it("drains food by 0.004 x movement multiplier", function()
        local s = survival.tick({ hp = 100, food = 80, bleed = 0, wounds = 0 }, 1.0, rng({ 0.99 }))
        assert.is_true(math.abs(s.food - 79.996) < 1e-6)
        s = survival.tick({ hp = 100, food = 80, bleed = 0, wounds = 0 }, 2.2, rng({ 0.99 }))
        assert.is_true(math.abs(s.food - (80 - 0.004 * 2.2)) < 1e-6)
    end)
    it("hurts when starving", function()
        local s = survival.tick({ hp = 50, food = 0, bleed = 0, wounds = 0 }, 1.0, rng({ 0.99 }))
        assert.is_true(math.abs(s.hp - (50 - 20 / 30 + 0)) < 1e-6)
    end)
    it("regenerates when not bleeding", function()
        local s = survival.tick({ hp = 50, food = 100, bleed = 0, wounds = 0 }, 1.0, rng({ 0.99 }))
        -- upstream runs food.pwn before bleed.pwn, so regen reads the already-drained food
        assert.is_true(math.abs(s.hp - (50 + 0.001925925 * (100 - 0.004))) < 1e-6)
    end)
    it("bleeds with 70% chance and slows down with wounds", function()
        local s = survival.tick({ hp = 50, food = 100, bleed = 0.2, wounds = 1 }, 1.0, rng({ 0.1, 0.1 }))
        assert.is_true(s.hp < 50)
        assert.is_true(s.bleed < 0.2)
        local t = survival.tick({ hp = 50, food = 100, bleed = 0.2, wounds = 0 }, 1.0, rng({ 0.1, 0.1 }))
        assert.equals(0, t.bleed) -- no wounds => bleeding stops (upstream guard)
    end)
    it("keeps a loaded character bleeding (one wound) so a relog is not a cure", function()
        assert.equals(1, survival.loadWounds(0.2, false))
        assert.equals(1, survival.loadWounds("0.2", false)) -- DECIMAL arrives as a string
        assert.equals(0, survival.loadWounds(0, false))
        assert.equals(0, survival.loadWounds(false, false)) -- NULL arrives as false
        assert.equals(0, survival.loadWounds(survival.NEW.bleed, true))
        local s =
            survival.tick({ hp = 50, food = 100, bleed = 0.2, wounds = survival.loadWounds(0.2) }, 1.0, rng({ 0.1 }))
        assert.is_true(s.bleed > 0)
    end)
    it("reports death at 0 hp", function()
        local s, events = survival.tick({ hp = 0.5, food = 0, bleed = 0, wounds = 0 }, 1.0, rng({ 0.99 }))
        assert.equals(0, s.hp)
        assert.same({ "died" }, events)
    end)
    it("classifies movement", function()
        assert.equals(0.2, survival.movementMultiplier(0, true))
        assert.equals(1.0, survival.movementMultiplier(0, false))
        assert.equals(1.2, survival.movementMultiplier(0.05, false))
        assert.equals(1.8, survival.movementMultiplier(0.11, false))
        assert.equals(2.2, survival.movementMultiplier(0.2, false))
    end)
    it("accumulates and caps knockout duration at 120s with a 1500ms floor", function()
        assert.equals(0, survival.knockoutAdd(0, 1500))
        assert.equals(3000, survival.knockoutAdd(0, 3000))
        assert.equals(8000, survival.knockoutAdd(3000, 5000))
        assert.equals(120000, survival.knockoutAdd(100000, 50000))
    end)
    it("doubles the idle drain with a food infection at movement mult 1", function()
        local state = { hp = 100, food = 80, bleed = 0, wounds = 0, infection = { food = true } }
        local s = survival.tick(state, 1.0, rng({ 0.99 }))
        assert.is_true(math.abs(s.food - (80 - 0.008)) < 1e-9)
    end)
    it("halves regeneration with a wound infection", function()
        local state = { hp = 50, food = 100, bleed = 0, wounds = 0, infection = { wound = true } }
        local s = survival.tick(state, 1.0, rng({ 0.99 }))
        assert.is_true(math.abs(s.hp - (50 + survival.REGEN_PER_FOOD * (100 - 0.004) * 0.5)) < 1e-9)
    end)
    it("heals 0.5 on Morphine when rng < 0.8", function()
        local base = 50 + survival.REGEN_PER_FOOD * (100 - 0.004)
        local state = { hp = 50, food = 100, bleed = 0, wounds = 0, drugs = { Morphine = 1000 } }
        local s = survival.tick(state, 1.0, rng({ 0.79 }))
        assert.is_true(math.abs(s.hp - (base + 0.5)) < 1e-9)
        s = survival.tick(state, 1.0, rng({ 0.8 }))
        assert.is_true(math.abs(s.hp - base) < 1e-9)
    end)
    it("hurts 1 on Air when rng < 0.5", function()
        local base = 50 + survival.REGEN_PER_FOOD * (100 - 0.004)
        local state = { hp = 50, food = 100, bleed = 0, wounds = 0, drugs = { Air = 1000 } }
        local s = survival.tick(state, 1.0, rng({ 0.49 }))
        assert.is_true(math.abs(s.hp - (base - 1)) < 1e-9)
        s = survival.tick(state, 1.0, rng({ 0.5 }))
        assert.is_true(math.abs(s.hp - base) < 1e-9)
    end)
    it("heals 0.01 on Adrenaline exactly once per tick", function()
        local base = 50 + survival.REGEN_PER_FOOD * (100 - 0.004)
        local state = { hp = 50, food = 100, bleed = 0, wounds = 0, drugs = { Adrenaline = 1000 } }
        local noRng = function()
            error("rng must not be called")
        end
        local s = survival.tick(state, 1.0, noRng)
        assert.is_true(math.abs(s.hp - (base + 0.01)) < 1e-9)
    end)
end)
