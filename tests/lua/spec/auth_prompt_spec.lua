local prompt = dofile("resources/[scavengesurvive]/auth/shared/logic/prompt.lua")

describe("auth prompt", function()
    it("picks the upstream dialog keys for each mode and the wrong-password body after a try", function()
        local register = { titleKey = "ACCREGITITL", bodyKey = "ACCREGIBODY", args = { "Bob" } }
        local login = { titleKey = "ACCLOGITITL", bodyKey = "ACCLOGIBODY", args = { "Bob" } }
        local wrong = { titleKey = "ACCLOGITITL", bodyKey = "ACCLOGWROPW", args = { 3 } }
        assert.same(register, prompt.dialog("register", "Bob"))
        assert.same(login, prompt.dialog("login", "Bob"))
        assert.same(wrong, prompt.dialog("login", "Bob", 3))
        assert.same({ "Accept", "Leave" }, prompt.BUTTONS)
    end)
    it("re-shows the login dialog until the fifth wrong password, then the player leaves", function()
        assert.same({ action = "reprompt", mode = "login", attempts = 1 }, prompt.onRefused("BAD_PASSWORD", 1))
        assert.same({ action = "reprompt", mode = "login", attempts = 4 }, prompt.onRefused("BAD_PASSWORD", 4))
        assert.same({ action = "leave" }, prompt.onRefused("BAD_PASSWORD", 5))
        assert.same({ action = "leave" }, prompt.onRefused("TOO_MANY_ATTEMPTS"))
    end)
    it("prints the password rule and re-shows the register dialog for a weak password", function()
        local r = prompt.onRefused("WEAK_PASSWORD")
        assert.same({ action = "reprompt", mode = "register", chatKey = "PASSWORDREQ" }, r)
    end)
    it("decides again when the account state changed, kicks inactive accounts and load errors", function()
        assert.same({ action = "lookup" }, prompt.onRefused("NO_ACCOUNT"))
        assert.same({ action = "lookup" }, prompt.onRefused("EXISTS"))
        assert.same({ action = "kick", reason = "Account inactive" }, prompt.onRefused("INACTIVE"))
        assert.same({ action = "kick", reason = "Account load failed" }, prompt.onRefused("DB_ERROR"))
        assert.same({ action = "none" }, prompt.onRefused("NOT_WHITELISTED"))
    end)
    it("words the grey broadcast like upstream", function()
        assert.equals(" >  Bob left the server without registering.", prompt.leftMessage("Bob", "register"))
        assert.equals(" >  Bob left the server without logging in.", prompt.leftMessage("Bob", "login"))
    end)
    it("counts the welcome button down to Accept", function()
        assert.equals("10", prompt.welcomeButton(10))
        assert.equals("1", prompt.welcomeButton(1))
        assert.equals("Accept", prompt.welcomeButton(0))
        assert.equals(10, prompt.WELCOME_COUNTDOWN)
        assert.matches("/rules", prompt.WELCOME_BODY)
        assert.is_nil(prompt.WELCOME_BODY:find("{"))
    end)
end)
