-- Poses and the aim shout (character/shared/logic/poses.lua, upstream animations.pwn and aim-shout.pwn, #140).
local poses = dofile("resources/[scavengesurvive]/character/shared/logic/poses.lua")

describe("character poses", function()
    it("sits a standing character, gets a sitting one up, toggles the hands", function()
        assert.same({ "sitting", "sitIn" }, { poses.next(nil, "sit") })
        assert.same({ nil, "sitOut" }, { poses.next("sitting", "stand") })
        assert.same({ "handsUp", "handsUp" }, { poses.next(nil, "hands") })
        assert.same({ nil, "clear" }, { poses.next("handsUp", "hands") })
    end)

    it("does nothing for a request that makes no sense in the pose", function()
        assert.same({ "sitting", nil }, { poses.next("sitting", "sit") })
        assert.same({ "sitting", nil }, { poses.next("sitting", "hands") })
        assert.same({ "handsUp", nil }, { poses.next("handsUp", "sit") })
        assert.same({ "handsUp", nil }, { poses.next("handsUp", "stand") })
        assert.same({ nil, nil }, { poses.next(nil, "stand") })
        assert.same({ nil, nil }, { poses.next(nil, "dance") })
    end)

    it("tells a sit from a crouch by how long the key was held", function()
        assert.is_false(poses.crouchWasSit(100))
        assert.is_true(poses.crouchWasSit(250))
        assert.is_true(poses.crouchWasSit(900))
        assert.are.equal(800, poses.SIT_HOLD_MS)
    end)

    it("keeps the shout clean and short and spaces shouts 750 ms apart", function()
        assert.are.equal("Hands up!", poses.cleanShout("  Hands\tup! \n"))
        assert.are.equal("stop", poses.cleanShout("#FF0000stop"))
        assert.are.equal("", poses.cleanShout(nil))
        assert.are.equal(128, #poses.cleanShout(string.rep("a", 200)))
        assert.is_true(poses.canShout(nil, 0))
        assert.is_false(poses.canShout(1000, 1750))
        assert.is_true(poses.canShout(1000, 1751))
    end)

    it("names upstream's animations", function()
        assert.same({ "SUNBATHE", "PARKSIT_M_IN" }, poses.ANIMS.sitIn)
        assert.same({ "BEACH", "PARKSIT_M_LOOP" }, poses.ANIMS.sitLoop)
        assert.same({ "SUNBATHE", "PARKSIT_M_OUT" }, poses.ANIMS.sitOut)
        assert.same({ "ROB_BANK", "SHP_HandsUp_Scr" }, poses.ANIMS.handsUp)
    end)
end)
