local dialog = dofile("resources/[scavengesurvive]/ui/shared/logic/dialog.lua")
local function rows(n, empties)
    local out = {}
    for i = 1, n do
        out[#out + 1] =
            { id = i, label = string.format("[01]Item %d", i), actions = { { id = "take", label = "Equip" } } }
    end
    for _ = 1, empties or 0 do
        out[#out + 1] = { label = "<Empty>", empty = true }
    end
    return out
end
describe("ui dialog", function()
    it("centres the box and measures like the footage (420 x 305 px at 720p)", function()
        local L = dialog.layout(1280, 720, 1.5)
        assert.equals(420, L.box.w)
        assert.is_true(math.abs(L.box.h - 304.5) < 1)
        assert.equals(430, L.box.x)
        assert.equals(18, L.rowH)
        assert.is_true(L.left.x + L.left.w < 640 and L.right.x > 640)
    end)
    it("selects the first selectable row and skips empties", function()
        local st = dialog.new("inv", "Inventory (2/5)", rows(0, 3))
        assert.equals(0, st.selected)
        st = dialog.new("inv", "Inventory (2/5)", rows(2, 3))
        assert.equals(1, st.selected)
        dialog.move(st, 1)
        assert.equals(2, st.selected)
        dialog.move(st, 1) -- next rows are empty: stays
        assert.equals(2, st.selected)
        dialog.move(st, -1)
        assert.equals(1, st.selected)
    end)
    it("scrolls to keep the selection visible and clamps", function()
        local st = dialog.new("c", "Crate (24/48)", rows(30))
        for _ = 1, 20 do
            dialog.move(st, 1)
        end
        assert.equals(21, st.selected)
        assert.equals(21 - dialog.VISIBLE, st.scroll)
        dialog.scrollBy(st, 100)
        assert.equals(30 - dialog.VISIBLE, st.scroll)
        local L = dialog.layout(1280, 720, 1.5)
        assert.equals(dialog.VISIBLE, #dialog.visibleRows(st, L))
        assert.is_not_nil(dialog.thumb(st, L))
        assert.is_nil(dialog.thumb(dialog.new("x", "t", rows(3)), L))
    end)
    it("hit-tests rows and buttons", function()
        local st = dialog.new("inv", "Inventory (2/5)", rows(2, 3))
        local L = dialog.layout(1280, 720, 1.5)
        local v = dialog.visibleRows(st, L)
        assert.same({ "row", 2 }, { dialog.hit(st, L, v[2].x + 2, v[2].y + 2) })
        assert.equals("left", (dialog.hit(st, L, L.left.x + 1, L.left.y + 1)))
        assert.equals("right", (dialog.hit(st, L, L.right.x + 1, L.right.y + 1)))
        assert.equals("scrollDown", (dialog.hit(st, L, L.scrollDown.x + 1, L.scrollDown.y + 1)))
        assert.equals("box", (dialog.hit(st, L, L.box.x + 1, L.box.y + 1)))
        assert.is_nil((dialog.hit(st, L, 1, 1)))
    end)
    it("keeps the selection across an update when it is still selectable", function()
        local st = dialog.new("inv", "t", rows(3))
        dialog.move(st, 1)
        dialog.setRows(st, rows(3))
        assert.equals(2, st.selected)
        dialog.setRows(st, rows(0, 2))
        assert.equals(0, st.selected)
    end)
end)

describe("ui box dialogs (msgbox / input / password)", function()
    it("measures a colour-coded body by lines and longest visible line", function()
        local lines, longest = dialog.bodyMetrics("#FFFFFFHello Bob#FFFFFF, welcome!\n\n#FFFF00Enjoy :)")
        assert.equals(3, lines)
        assert.equals(#"Hello Bob, welcome!", longest)
        assert.same({ 1, 0 }, { dialog.bodyMetrics("") })
    end)
    it("widens the box for long lines within the canvas limits", function()
        assert.equals(280, dialog.boxWidth(10, 4.6))
        assert.equals(600, dialog.boxWidth(500, 4.6))
        assert.is_true(dialog.boxWidth(100, 4.6) > 280 and dialog.boxWidth(100, 4.6) < 600)
    end)
    it("stacks title, body, field and buttons and centres a lone button", function()
        local L = dialog.boxLayout(1280, 720, 1.5, "password", 3, 280, true)
        assert.equals(420, L.box.w)
        assert.is_true(L.body.y > L.title.y)
        assert.is_true(L.field.y >= L.body.y + L.body.h)
        assert.is_true(L.left.y >= L.field.y + L.field.h)
        assert.is_true(L.left.x + L.left.w < 640 and L.right.x > 640)
        assert.is_true(math.abs(L.box.y + L.box.h - (L.left.y + L.left.h) - 7.5) < 0.01)
        local M = dialog.boxLayout(1280, 720, 1.5, "msgbox", 3, 280, false)
        assert.is_nil(M.field)
        assert.is_nil(M.right)
        assert.is_true(math.abs(M.left.x + M.left.w / 2 - 640) < 0.01)
        assert.is_true(M.box.h < L.box.h)
    end)
    it("hit-tests the buttons and the field", function()
        local L = dialog.boxLayout(1280, 720, 1.5, "input", 1, 280, true)
        assert.equals("left", dialog.boxHit(L, L.left.x + 1, L.left.y + 1))
        assert.equals("right", dialog.boxHit(L, L.right.x + 1, L.right.y + 1))
        assert.equals("field", dialog.boxHit(L, L.field.x + 1, L.field.y + 1))
        assert.equals("box", dialog.boxHit(L, L.box.x + 1, L.box.y + 1))
        assert.is_nil(dialog.boxHit(L, 1, 1))
        local M = dialog.boxLayout(1280, 720, 1.5, "msgbox", 1, 280, false)
        assert.equals("box", dialog.boxHit(M, M.left.x + M.left.w + 2, M.left.y + 1))
    end)
    it("edits the field by whole UTF-8 characters and masks passwords", function()
        local text = dialog.typed("", "a")
        text = dialog.typed(text, "\195\167") -- "ç"
        assert.equals("a\195\167", text)
        assert.equals(2, dialog.length(text))
        assert.equals("**", dialog.masked(text))
        assert.equals("a", dialog.backspace(text))
        assert.equals("", dialog.backspace("a"))
        assert.equals("", dialog.backspace(""))
        local full = string.rep("x", dialog.MAX_INPUT)
        assert.equals(full, dialog.typed(full, "y"))
        assert.equals("ab", dialog.typed("a", "b", 2))
        assert.equals("ab", dialog.typed("ab", "c", 2))
    end)
    it("pastes clipboard text without control characters and within the limit", function()
        assert.equals("abhunter42", dialog.pasted("ab", "hunter\r\n4\t2"))
        assert.equals("ab\195\167d", dialog.pasted("ab", "\195\167d\n"))
        assert.equals("abcd", dialog.pasted("ab", "cdef", 4))
        assert.equals("ab", dialog.pasted("ab", nil))
        local full = string.rep("x", dialog.MAX_INPUT)
        assert.equals(full, dialog.pasted(full, "more"))
    end)
end)
