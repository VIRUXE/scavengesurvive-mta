local canvas = dofile("resources/[scavengesurvive]/ui/shared/logic/canvas.lua")
describe("ui canvas", function()
    it("scales uniformly by height and anchors to the edges", function()
        local c = canvas.new(1280, 720)
        assert.equals(1.5, c.s)
        assert.equals(150, canvas.x(c, 100))
        assert.equals(1280 - 22 * 1.5, canvas.x(c, 618, "right"))
        assert.equals(640, canvas.x(c, 320, "center"))
        assert.equals(345 * 1.5, canvas.y(c, 345))
    end)
    it("reproduces the measured line pitch (0.3/1.5 -> 22 px at 720p)", function()
        local c = canvas.new(1280, 720)
        assert.is_true(math.abs(canvas.lineHeight(c, 1.5) - 22) < 0.5)
        assert.is_true(canvas.textScale(c, 1.5, 1) > 1 and canvas.textScale(c, 1.5, 1) < 2)
    end)
    it("maps textdraw fonts to MTA fonts", function()
        assert.equals("default-bold", canvas.font(1))
        assert.equals("bankgothic", canvas.font(2))
        assert.equals("diploma", canvas.font(0))
        assert.equals("pricedown", canvas.font(3))
        assert.equals("default-bold", canvas.font(9))
    end)
    it("condenses Bank Gothic and widens Tahoma at the native aspect", function()
        assert.is_true(canvas.xScale(2, 0.5, 2.0) < 1)
        assert.is_true(canvas.xScale(1, 0.5, 2.0) > 1)
        assert.is_true(canvas.xScale(2, 0.3, 1.5) < canvas.xScale(2, 0.5, 2.0))
    end)
    it("splits SA-MP RGBA integers", function()
        assert.same({ 0x1F, 0xF8, 0x1F, 0xFF }, { canvas.rgba(0x1FF81FFF) })
        assert.same({ 0, 0, 0, 0x55 }, { canvas.rgba(85) })
    end)
    it("insets the progress2 bar and scales the value box", function()
        local b = canvas.progressBar(291, 345, 57.5, 5.19, 0.5)
        assert.equals(291, b.back.x)
        assert.is_true(math.abs(b.fill.x - 292.2) < 1e-9)
        assert.is_true(math.abs(b.value.w - (57.5 - 2.4) / 2) < 1e-9)
        assert.equals(0, canvas.progressBar(0, 0, 10, 4, -1).value.w)
    end)
end)
