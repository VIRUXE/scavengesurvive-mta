-- The body a death leaves (character/shared/logic/bodies.lua, upstream death.pwn CreateGravestone, #139).
local bodies = dofile("resources/[scavengesurvive]/character/shared/logic/bodies.lua")
local wound = dofile("resources/[scavengesurvive]/weapons/shared/logic/wound.lua")

describe("character bodies", function()
    it("writes upstream's coroner line for each cause", function()
        assert.are.equal("They drowned.", bodies.reason("drowned", false))
        assert.are.equal(
            "Most bones are broken, looks like they fell from a great height.",
            bodies.reason("fall", false)
        )
        assert.are.equal("They bled to death.", bodies.reason("bleeding", false))
        assert.are.equal("They suffered massive concussion due to an explosion.", bodies.reason("Explosion", false))
        assert.are.equal("They were beaten to death.", bodies.reason("beaten", true))
        assert.are.equal("They died of blood loss caused by what looks like bullets.", bodies.reason("shot", true))
    end)

    it("falls back to bleeding for a kill and to the unknown line otherwise", function()
        assert.are.equal(bodies.KILLED, bodies.reason("killed", true))
        assert.are.equal(bodies.KILLED, bodies.reason("something", true))
        assert.are.equal(bodies.UNKNOWN, bodies.reason("killed", false))
        assert.are.equal(bodies.UNKNOWN, bodies.reason(nil, false))
        assert.are.equal(bodies.UNKNOWN, bodies.reason("vehicle", false))
    end)

    it("maps the killing weapon to the cause as death.pwn's switch did", function()
        assert.are.equal("beaten", wound.killCause(0))
        assert.are.equal("beaten", wound.killCause(15))
        assert.are.equal("knife", wound.killCause(4))
        assert.are.equal("sword", wound.killCause(8))
        assert.are.equal("chainsaw", wound.killCause(9))
        assert.are.equal("explosion", wound.killCause(16))
        assert.are.equal("explosion", wound.killCause(35))
        assert.are.equal("burned", wound.killCause(37))
        assert.are.equal("shot", wound.killCause(22))
        assert.are.equal("shot", wound.killCause(34))
        assert.are.equal("shot", wound.killCause(38))
        assert.are.equal("sprayed", wound.killCause(41))
        assert.are.equal("camera", wound.killCause(43))
        assert.are.equal("goggles", wound.killCause(44))
        assert.are.equal("killed", wound.killCause(99))
        assert.are.equal("killed", wound.killCause(nil))
    end)

    it("gives the body its name, reason, time and one harvest", function()
        local d = bodies.data("Kaija", "They drowned.", 1700000000)
        assert.same({ name = "Kaija", reason = "They drowned.", at = 1700000000, harvest = 1 }, d)
        assert.are.equal(bodies.UNKNOWN, bodies.data("X", nil, 0).reason)
    end)
end)
