local cooking = dofile("resources/[scavengesurvive]/items/shared/logic/cooking.lua")

local MEAT = { category = "food", categoryData = { canCook = true, canRawInfect = true } }
local BREAD = { category = "food", categoryData = { canCook = false } }
local KNIFE = { category = "weapon", categoryData = {} }

describe("cooking: food state", function()
    it("counts only cookable food that was not cooked as raw", function()
        assert.is_true(cooking.isRaw(MEAT, {}))
        assert.is_true(cooking.isRaw(MEAT, nil))
        assert.is_false(cooking.isRaw(MEAT, { cooked = 1 }))
        assert.is_false(cooking.isRaw(MEAT, { { cooked = 1 } })) -- MTA's wrapped toJSON form
        assert.is_true(cooking.isRaw(MEAT, { cooked = 0 }))
        assert.is_false(cooking.isRaw(BREAD, {}))
        assert.is_false(cooking.isRaw(KNIFE, {}))
    end)
    it("labels cookable food Cooked or Uncooked, other food as it is", function()
        assert.equals("Meat (Uncooked)", cooking.label(MEAT, "Meat", nil))
        assert.equals("Meat (Cooked)", cooking.label(MEAT, "Meat", { cooked = 1 }))
        assert.equals("Bread", cooking.label(BREAD, "Bread", { cooked = 1 }))
    end)
end)

describe("cooking: cooker data", function()
    it("decodes missing fields to nil and a free grill to zeros", function()
        local d = cooking.decode(false)
        assert.is_nil(d.burnsAt)
        assert.same({ 0, 0 }, d.grill)
        d = cooking.decode({ fuel = 3, grill = { 12 }, doneAt = 99 })
        assert.equals(3, d.fuel)
        assert.same({ 12, 0 }, d.grill)
        assert.equals(99, d.doneAt)
    end)
    it("encodes each cooker's fields in a fixed order", function()
        local d = cooking.decode({ burnsAt = 700, food = 5, doneAt = 160 })
        assert.equals('{"burnsAt":700,"food":5,"doneAt":160}', cooking.encode("Campfire", d))
        d.food, d.doneAt = nil, nil
        assert.equals('{"burnsAt":700}', cooking.encode("Campfire", d))
        assert.equals('{"fuel":0,"grill":[0,0]}', cooking.encode("Barbecue", cooking.decode(nil)))
        d = cooking.decode({ fuel = 9, grill = { 4, 7 }, doneAt = 130 })
        assert.equals('{"fuel":9,"grill":[4,7],"doneAt":130}', cooking.encode("Barbecue", d))
    end)
end)

describe("cooking: campfire", function()
    it("burns 10 minutes, in the rain 2 minutes 40 % of the time and otherwise goes out at once", function()
        assert.equals(600, cooking.campfireLife(1, 99))
        assert.equals(120, cooking.campfireLife(8, 39))
        assert.is_nil(cooking.campfireLife(16, 40))
    end)
    it("takes one food for 60 s", function()
        local ok, code, n = cooking.campfireAdd(cooking.decode({ burnsAt = 700 }), 5, 100)
        assert.is_true(ok)
        assert.equals("FIRELITSTAR", code)
        assert.equals(5, n.food)
        assert.equals(160, n.doneAt)
        ok, code = cooking.campfireAdd(n, 6, 101)
        assert.is_false(ok)
        assert.equals("BUSY", code)
    end)
    it("steps: rolls its life first, then cooks, then burns out", function()
        assert.same({ kind = "life" }, cooking.step("Campfire", cooking.decode({}), 0))
        local d = cooking.decode({ burnsAt = 700, food = 5, doneAt = 160 })
        assert.is_nil(cooking.step("Campfire", d, 159))
        assert.same({ 5 }, cooking.busyFoods("Campfire", d))
        local act = cooking.step("Campfire", d, 160)
        assert.equals("cook", act.kind)
        assert.same({ 5 }, act.foods)
        assert.is_nil(act.data.food) -- the campfire takes food again (upstream never cleared cmp_foodItem)
        assert.is_nil(act.data.doneAt)
        assert.equals(700, act.data.burnsAt)
        assert.same({ kind = "burn" }, cooking.step("Campfire", act.data, 700))
    end)
    it("drops three logs within 0.25 of the fire", function()
        local spots = cooking.logSpots(10, 20, 3, function()
            return 1
        end)
        assert.equals(3, #spots)
        assert.same({ x = 10.25, y = 20.25, z = 3, rz = 360 }, spots[1])
    end)
end)

describe("cooking: barbecue", function()
    it("puts food on the first free grill spot, refuses cooked food and a full grill", function()
        local d = cooking.decode({ fuel = 1 })
        local ok, code, n, slot = cooking.bbqAdd(d, 4, false, {})
        assert.is_true(ok)
        assert.equals("BBQFOODADDE", code)
        assert.equals(1, slot)
        n, slot = select(3, cooking.bbqAdd(n, 7, false, { [4] = true }))
        assert.equals(2, slot)
        assert.same({ 4, 7 }, n.grill)
        ok, code = cooking.bbqAdd(n, 8, false, { [4] = true, [7] = true })
        assert.is_false(ok)
        assert.equals("BBQ_FULL", code)
        -- a grill id no longer lying on the grill frees its spot
        slot = select(4, cooking.bbqAdd(n, 8, false, { [7] = true }))
        assert.equals(1, slot)
        ok, code = cooking.bbqAdd(d, 9, true, {})
        assert.is_false(ok)
        assert.equals("BBQALREADYC", code)
    end)
    it("places the grill spots 0.25 either side, 0.818 up", function()
        local x, y, z = cooking.grillSpot(0, 0, 1, 0, 1)
        assert.is_true(math.abs(x - 0.25) < 1e-6 and math.abs(y) < 1e-6 and math.abs(z - 1.818) < 1e-6)
        x = cooking.grillSpot(0, 0, 1, 0, 2)
        assert.is_true(math.abs(x + 0.25) < 1e-6)
    end)
    it("fuels 10 cooks for 0.6 L of petrol, what is left when less", function()
        local ok, code, n, left = cooking.bbqFuel(cooking.decode({ fuel = 2 }), 20)
        assert.is_true(ok)
        assert.equals("BBQADDPETRO", code)
        assert.equals(12, n.fuel)
        assert.is_true(math.abs(left - 19.4) < 1e-6)
        n, left = select(3, cooking.bbqFuel(n, 0.2))
        assert.equals(22, n.fuel)
        assert.equals(0, left)
        ok, code = cooking.bbqFuel(n, 0)
        assert.is_false(ok)
        assert.equals("PETROLEMPTY", code)
    end)
    it("lights only with fuel and not twice, cooks the grill in 30 s for one fuel", function()
        local ok, code = cooking.bbqLight(cooking.decode({ fuel = 0 }), 100)
        assert.is_false(ok)
        assert.equals("BBQFUELEMPT", code)
        local n
        ok, code, n = cooking.bbqLight(cooking.decode({ fuel = 2, grill = { 4, 0 } }), 100)
        assert.is_true(ok)
        assert.equals("BBQLITSTART", code)
        assert.equals(130, n.doneAt)
        assert.same({ 4 }, cooking.busyFoods("Barbecue", n))
        code = select(2, cooking.bbqLight(n, 101))
        assert.equals("BBQ_LIT", code)
        assert.is_nil(cooking.step("Barbecue", n, 129))
        local act = cooking.step("Barbecue", n, 130)
        assert.equals("cook", act.kind)
        assert.same({ 4 }, act.foods)
        assert.equals(1, act.data.fuel)
        assert.is_nil(act.data.doneAt)
        assert.same({ 4, 0 }, act.data.grill) -- the food stays on the grill until taken
        assert.same({}, cooking.busyFoods("Barbecue", act.data))
    end)
end)
