local access = dofile("resources/[scavengesurvive]/auth/shared/logic/access.lua")

describe("auth access gate", function()
    it("matches bans by name, ip or serial and only while active and unexpired", function()
        assert.matches(
            "name = %? OR %(ip IS NOT NULL AND ip = %?%) OR %(serial IS NOT NULL AND serial = %?%)",
            access.BAN_SQL
        )
        assert.matches("active = 1 AND %(expires_at IS NULL OR expires_at > NOW%(%)%)", access.BAN_SQL)
        assert.matches("ORDER BY created_at DESC LIMIT 1", access.BAN_SQL)
    end)
    it("explains a ban in three lines, with Never for permanent bans", function()
        local lines =
            access.banLines({ created = "2026-10-23 09:00", by_name = "Mod", reason = "cheats", expires = false })
        assert.equals(3, #lines)
        assert.matches("since 2026%-10%-23 09:00 by Mod", lines[1])
        assert.equals("Reason: cheats", lines[2])
        assert.equals("Unban: Never", lines[3])
        local timed = access.banLines({ created = "x", by_name = "Mod", reason = "r", expires = "2026-11-01 00:00" })
        assert.equals("Unban: 2026-11-01 00:00", timed[3])
    end)
    it("lets everyone in while the whitelist is off, and listed names or staff while it is on", function()
        assert.is_true(access.whitelistAllows(false, false, 0))
        assert.is_false(access.whitelistAllows(true, false, 0))
        assert.is_true(access.whitelistAllows(true, true, 0))
        assert.is_true(access.whitelistAllows(true, false, 1))
        assert.is_true(access.whitelistAllows(true, false, "3"))
    end)
    it("reads the whitelist switch from the settings row", function()
        assert.is_true(access.whitelistEnabledFromSetting("1"))
        assert.is_true(access.whitelistEnabledFromSetting("on"))
        assert.is_false(access.whitelistEnabledFromSetting("0"))
        assert.is_false(access.whitelistEnabledFromSetting(nil))
    end)
end)
