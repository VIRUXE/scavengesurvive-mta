local access = dofile("resources/[scavengesurvive]/auth/shared/logic/access.lua")

describe("auth access gate", function()
    it("matches bans by name, ip or serial and only while active and unexpired", function()
        assert.matches(
            "name = %? OR %(ip IS NOT NULL AND ip = %?%) OR %(serial IS NOT NULL AND serial = %?%)",
            access.BAN_SQL
        )
        assert.matches("active = 1 AND %(expires_at IS NULL OR expires_at > NOW%(%)%)", access.BAN_SQL)
        assert.matches("ORDER BY created_at DESC LIMIT 1", access.BAN_SQL)
    end)
    it("explains a ban in three lines, with Never for permanent bans", function()
        local lines =
            access.banLines({ created = "2026-10-23 09:00", by_name = "Mod", reason = "cheats", expires = false })
        assert.equals(3, #lines)
        assert.matches("since 2026%-10%-23 09:00 by Mod", lines[1])
        assert.equals("Reason: cheats", lines[2])
        assert.equals("Unban: Never", lines[3])
        local timed = access.banLines({ created = "x", by_name = "Mod", reason = "r", expires = "2026-11-01 00:00" })
        assert.equals("Unban: 2026-11-01 00:00", timed[3])
    end)
    it("lets everyone in while the whitelist is off, and listed names or staff while it is on", function()
        assert.is_true(access.whitelistAllows(false, false, 0))
        assert.is_false(access.whitelistAllows(true, false, 0))
        assert.is_true(access.whitelistAllows(true, true, 0))
        assert.is_true(access.whitelistAllows(true, false, 1))
        assert.is_true(access.whitelistAllows(true, false, "3"))
    end)
    it("reads the whitelist switch from the settings row", function()
        assert.is_true(access.whitelistEnabledFromSetting("1"))
        assert.is_true(access.whitelistEnabledFromSetting("on"))
        assert.is_false(access.whitelistEnabledFromSetting("0"))
        assert.is_false(access.whitelistEnabledFromSetting(nil))
    end)
end)

describe("auth whitelist auto mode and auto-login", function()
    it("turns the whitelist off while level 2+ staff are on and back on when they leave", function()
        assert.is_nil(access.autoWhitelist(false, true, 3))
        assert.is_false(access.autoWhitelist(true, true, 1))
        assert.is_true(access.autoWhitelist(true, false, 0))
        assert.is_nil(access.autoWhitelist(true, false, 2))
        assert.is_nil(access.autoWhitelist(true, true, 0))
    end)
    it("auto-logs in only with the setting on and both the last IP and serial matching", function()
        local row = { last_ip = "1.2.3.4", last_serial = "ABC" }
        assert.is_true(access.autoLoginAllowed(true, row, "1.2.3.4", "ABC"))
        assert.is_false(access.autoLoginAllowed(false, row, "1.2.3.4", "ABC"))
        assert.is_false(access.autoLoginAllowed(true, row, "1.2.3.4", "DEF"))
        assert.is_false(access.autoLoginAllowed(true, row, "5.6.7.8", "ABC"))
        assert.is_false(access.autoLoginAllowed(true, { last_ip = false, last_serial = false }, "", ""))
        assert.is_false(access.autoLoginAllowed(true, nil, "1.2.3.4", "ABC"))
    end)
    it("gives players who are neither staff nor listed the whitelist countdown", function()
        local candidates = {
            { key = "a", name = "Alice", adminLevel = 0 },
            { key = "b", name = "Bob", adminLevel = 0 },
            { key = "m", name = "Mod", adminLevel = 1 },
        }
        local targets = access.countdownTargets(candidates, { alice = true })
        assert.same({ "b" }, targets)
        assert.same({ "a", "b" }, access.countdownTargets(candidates, {}))
    end)
    it("reads the countdown length, falling back to upstream's 300 s", function()
        assert.equals(120, access.whitelistKickSeconds("120"))
        assert.equals(300, access.whitelistKickSeconds(nil))
        assert.equals(300, access.whitelistKickSeconds("0"))
        assert.equals(300, access.whitelistKickSeconds("x"))
    end)
    it("binds one placeholder per candidate name and formats the textdraw text", function()
        assert.equals("SELECT name FROM whitelist WHERE name IN (?, ?, ?)", access.listedSql(3))
        assert.equals("Not whitelisted\nTime remaining: 05:00", access.countdownText(300))
        assert.equals("Not whitelisted\nTime remaining: 00:09", access.countdownText(9))
        assert.equals("Not whitelisted\nTime remaining: 00:00", access.countdownText(-2))
    end)
end)
