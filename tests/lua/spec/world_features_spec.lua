local F = dofile("resources/[scavengesurvive]/world/shared/logic/features.lua")

local ladder = { 100.0, 200.0, 10.0, 40.0, 90.0, "fc" } -- x, y, base, top, angle
local zip = { 0.0, 0.0, 50.0, 0.0, 100.0, 20.0, "ls" } -- start -> end, 100 m north and 30 m down

describe("ladders", function()
    it("finds a ladder from its 1 m base circle within the usable height", function()
        assert.equals(1, F.ladderAt({ ladder }, 100.5, 200.0, 10.0))
        assert.is_nil(F.ladderAt({ ladder }, 102.0, 200.0, 10.0))
        assert.is_nil(F.ladderAt({ ladder }, 100.0, 200.0, 8.5)) -- below base - 1
        assert.equals(1, F.ladderAt({ ladder }, 100.0, 200.0, 41.5)) -- up to top + 2
        assert.is_nil(F.ladderAt({ ladder }, 100.0, 200.0, 42.5))
    end)
    it("snaps the entry height near the ends and keeps it in the middle", function()
        assert.near(40.0 - 2.0926, F.ladderEnterZ(ladder, 41.0), 1e-6)
        assert.near(11.5, F.ladderEnterZ(ladder, 9.5), 1e-6)
        assert.equals(25.0, F.ladderEnterZ(ladder, 25.0))
    end)
    it("climbs, descends and holds with upstream speeds", function()
        assert.equals(0.1, F.ladderVelocity("up"))
        assert.near(-0.07, F.ladderVelocity("down"), 1e-9)
        assert.equals(0.01, F.ladderVelocity(nil))
    end)
    it("exits past the ends only after a second", function()
        assert.is_false(F.ladderShouldExit(ladder, 39.8, 500))
        assert.is_true(F.ladderShouldExit(ladder, 39.8, 1500))
        assert.is_true(F.ladderShouldExit(ladder, 10.2, 1500))
        assert.is_false(F.ladderShouldExit(ladder, 25.0, 5000))
    end)
    it("steps off forward along the facing angle", function()
        local vx, vy, vz = F.ladderExitVelocity(0)
        assert.near(0, vx, 1e-9)
        assert.near(0.1, vy, 1e-9)
        assert.equals(0.1, vz)
        vx = F.ladderExitVelocity(90)
        assert.near(-0.1, vx, 1e-9)
    end)
end)

describe("ziplines", function()
    it("projects a point onto the rope", function()
        local t, d = F.ziplineProject(zip, 0, 50, 35)
        assert.near(0.5, t, 1e-9)
        assert.near(0, d, 1e-9)
        t, d = F.ziplineProject(zip, 3, 50, 35)
        assert.near(3, d, 1e-9)
        t = F.ziplineProject(zip, 0, -50, 100)
        assert.equals(0, t) -- clamped before the start
    end)
    it("grabs from the start sphere or near the rope, not past its end", function()
        assert.equals(1, F.ziplineAt({ zip }, 0.5, 0.5, 49.0)) -- 1 m below the start anchor
        assert.equals(1, F.ziplineAt({ zip }, 0.5, 50, 35 - F.ZIP_HANG_BELOW)) -- hanging under the middle
        assert.is_nil(F.ziplineAt({ zip }, 0, 99, 20 - F.ZIP_HANG_BELOW)) -- t > 0.95
        assert.is_nil(F.ziplineAt({ zip }, 10, 50, 35))
    end)
    it("places the rider under the rope facing along it", function()
        local x, y, z, angle = F.ziplineRiderPos(zip, 0.5)
        assert.near(0, x, 1e-9)
        assert.near(50, y, 1e-9)
        assert.near(35 - 1.2, z, 1e-9)
        assert.near(0, angle, 1e-6) -- north in SA-MP degrees
    end)
    it("ramps the speed from 0.2 to 0.5 by 0.01 per tick", function()
        local mult, vx, vy, vz = F.ziplineStep(zip, nil)
        assert.near(0.21, mult, 1e-9)
        assert.near(0, vx, 1e-9)
        assert.is_true(vy > 0 and vz < 0)
        for _ = 1, 100 do
            mult = F.ziplineStep(zip, mult)
        end
        assert.near(0.5, mult, 1e-9)
    end)
    it("lets go at the end sphere or 5 m off the rope", function()
        assert.same({ true, "end" }, { F.ziplineShouldExit(zip, 0, 96, 21) })
        assert.same({ true, "drift" }, { F.ziplineShouldExit(zip, 6, 50, 35 - 1.2) })
        assert.is_false(F.ziplineShouldExit(zip, 1, 50, 35 - 1.2))
    end)
end)
