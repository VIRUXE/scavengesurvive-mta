local chat = dofile("resources/[scavengesurvive]/chat/shared/logic/chat.lua")

describe("chat frequencies", function()
    it("clamps and rounds to the 87.5-108.0 band", function()
        assert.equals(98.12, chat.clampFreq(nil))
        assert.equals(87.5, chat.clampFreq(80))
        assert.equals(108.0, chat.clampFreq(120))
        assert.equals(101.3, chat.clampFreq(101.299))
    end)
    it("parses typed frequencies and refuses ones outside the band", function()
        assert.equals(101.3, chat.parseFreq("101.3"))
        assert.is_nil(chat.parseFreq("87.4"))
        assert.is_nil(chat.parseFreq("108.5"))
        assert.is_nil(chat.parseFreq("loud"))
    end)
    it("treats frequencies within 0.05 as one channel", function()
        assert.is_true(chat.sameFrequency(98.12, 98.15))
        assert.is_false(chat.sameFrequency(98.12, 98.18))
    end)
end)

describe("chat flood guard", function()
    it("mutes on the third message within a second and relaxes over quiet seconds", function()
        local st = { streak = 0, lastTick = 0 }
        assert.is_false(chat.flood(st, 5000))
        assert.is_false(chat.flood(st, 5300))
        assert.is_false(chat.flood(st, 5600))
        assert.is_true(chat.flood(st, 5900)) -- streak 3
        assert.equals(0, st.streak)
        assert.is_false(chat.flood(st, 9000))
        assert.is_false(chat.flood(st, 9200))
        assert.equals(1, st.streak)
        assert.is_false(chat.flood(st, 12000)) -- a calm second lowers the streak
        assert.equals(0, st.streak)
    end)
end)

describe("chat lines", function()
    it("formats each mode like upstream (without SA-MP player ids)", function()
        assert.equals("[Local] Bob#FFFFFF: hi", chat.format(0, "Bob", "hi"))
        assert.equals("[Global] Bob#FFFFFF: hi", chat.format(1, "Bob", "hi"))
        assert.equals("[101.30] Bob#FFFFFF: hi", chat.format(2, "Bob", "hi", 101.3))
        assert.equals("#FF0000[Admin] Bob#FFFFFF: hi", chat.format(3, "Bob", "hi", nil, "#FF0000"))
        assert.equals("[Local] Bob waves", chat.format("me", "Bob", "waves"))
    end)
    it("splits long lines at a space near 128 characters", function()
        local words = {}
        for i = 1, 40 do
            words[i] = "word" .. i
        end
        local text = table.concat(words, " ")
        local a, b = chat.split(text)
        assert.is_true(#a <= 128)
        assert.is_truthy(b)
        assert.equals(text, a .. " " .. b)
        assert.same({ "short", nil }, { chat.split("short") })
    end)
end)

describe("radio panel", function()
    it("labels power and mode like radio.pwn and toggles between global and freq", function()
        assert.equals("off", chat.powerLabel(0))
        assert.equals("on", chat.powerLabel(2))
        assert.equals("global", chat.modeLabel(1, 2))
        assert.equals("freq", chat.modeLabel(2, 1))
        assert.equals("global", chat.modeLabel(0, 1)) -- off, last used global
        assert.equals(2, chat.toggleMode(1))
        assert.equals(1, chat.toggleMode(2))
        assert.equals(0, chat.toggleMode(0))
    end)
    it("power off remembers the transmitting mode", function()
        local mode, old = chat.togglePower(2, 1)
        assert.same({ 0, 2 }, { mode, old })
        mode, old = chat.togglePower(0, 2)
        assert.same({ 2, 2 }, { mode, old })
        mode = chat.togglePower(0, 1)
        assert.equals(1, mode)
    end)
    it("hit-tests the hotspots in canvas units", function()
        assert.equals("knobL", chat.hit(225, 210))
        assert.equals("knobR", chat.hit(400, 230))
        assert.equals("freq", chat.hit(320, 258))
        assert.equals("power", chat.hit(402, 255))
        assert.equals("close", chat.hit(320, 280))
        assert.is_nil(chat.hit(320, 240))
        assert.is_nil(chat.hit(10, 10))
    end)
end)

describe("chat join and quit lines", function()
    it("sends the copyright to the joiner, the join to everyone, and the MoTD only when set", function()
        local lines = chat.joinLines("Bob", "Stay safe")
        assert.equals(3, #lines)
        assert.matches("Southclaws", lines[1].text)
        assert.is_nil(lines[1].toAll)
        assert.equals(" >  #B8B8B8Bob#FFFFFF has joined", lines[2].text)
        assert.is_true(lines[2].toAll)
        assert.equals(" >  MoTD: #33CCFFStay safe", lines[3].text)
        assert.equals(2, #chat.joinLines("Bob", ""))
        assert.equals(2, #chat.joinLines("Bob", false))
    end)
    it("maps quit types to upstream's two lines and stays silent on kicks and bans", function()
        assert.equals(" >  Bob left the server.", chat.quitLine("Bob", "Quit"))
        assert.equals(" >  Bob lost connection.", chat.quitLine("Bob", "Timed out"))
        assert.equals(" >  Bob lost connection.", chat.quitLine("Bob", "Bad Connection"))
        assert.is_nil(chat.quitLine("Bob", "Kicked"))
        assert.is_nil(chat.quitLine("Bob", "Banned"))
    end)
end)

describe("chat info commands", function()
    it("expands tabs for the dx message box", function()
        assert.equals("    #E85454/rules\n\n    x", chat.dialogBody("\t#E85454/rules\n\n\tx"))
    end)
    it("splits the rules and staff settings on | and drops blanks", function()
        assert.same({ "No hacking", "Be nice" }, chat.listSetting(" No hacking | | Be nice|"))
        assert.same({}, chat.listSetting(""))
        assert.same({}, chat.listSetting(false))
    end)
    it("heads a list with its count", function()
        local want = { " >  Rules List (total: 1)", " >  #FFAA00No hacking" }
        assert.same(want, chat.listLines("Rules List", { "No hacking" }))
        assert.same({ " >  Staff List (total: 0)" }, chat.listLines("Staff List", {}))
    end)
end)
