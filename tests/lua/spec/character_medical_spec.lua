local medical = dofile("resources/[scavengesurvive]/character/shared/logic/medical.lua")

local function seq(values)
    local i = 0
    return function()
        i = i + 1
        return values[((i - 1) % #values) + 1]
    end
end

local function never()
    error("rng must not be called")
end

local function recorder(result)
    local calls = {}
    local fn = function(a, b)
        calls[#calls + 1] = { a, b }
        return result
    end
    return fn, calls
end

local function patient(bleed, wound, knockedOut)
    return { bleed = bleed, wounds = 1, infection = { food = false, wound = wound }, knockedOut = knockedOut }
end

describe("character medical", function()
    it("gives each treatment its hold and the Medical skill", function()
        local ms, skill = medical.holdFor("Bandage", false)
        assert.equals(4000, ms)
        assert.equals("Medical", skill)
        ms, skill = medical.holdFor("DoctorBag", true)
        assert.equals(6000, ms)
        assert.equals("Medical", skill)
        ms, skill = medical.holdFor("Pills", false)
        assert.equals(1000, ms)
        assert.is_nil(skill)
        assert.equals(1000, medical.holdFor("AutoInjec", true))
        assert.is_nil(medical.holdFor("Hammer", false))
        assert.is_false(medical.canTreatOthers("Pills"))
        assert.is_true(medical.canTreatOthers("Medkit"))
    end)

    it("reduces bleed by the upstream formula and snaps tiny values to 0", function()
        assert.equals(0, medical.reduceBleed(0))
        assert.equals(0, medical.reduceBleed(false))
        local expected = 0.5 - 0.5 * (1.0091 - 0.5) ^ 2.1
        assert.is_true(math.abs(medical.reduceBleed(0.5) - expected) < 1e-12)
        assert.equals(0, medical.reduceBleed(0.000001))
        assert.equals(0, medical.reduceBleed(0.004))
    end)

    it("rolls loot data for the three data items only", function()
        local high = function(_, b)
            return b
        end
        local low = function(a)
            return a
        end
        assert.equals('{"charges":3,"drug":"Adrenaline"}', medical.lootData("DoctorBag", high))
        assert.equals('{"charges":1,"drug":"Antibiotic"}', medical.lootData("DoctorBag", low))
        assert.equals('{"pill":"LSD"}', medical.lootData("Pills", high))
        assert.equals('{"inject":"Morphine"}', medical.lootData("AutoInjec", low))
        assert.equals('{"inject":"Heroin"}', medical.lootData("AutoInjec", high))
        assert.is_nil(medical.lootData("Bandage", high))
    end)

    it("defaults pills to Antibiotics and injectors to Empty without data", function()
        assert.equals("Antibiotics", medical.pill(nil))
        assert.equals("Antibiotics", medical.pill({ pill = "Bogus" }))
        assert.equals("LSD", medical.pill({ pill = "LSD" }))
        assert.equals("Empty", medical.injection(nil))
        assert.equals("Empty", medical.injection({ inject = "Bogus" }))
        assert.equals("Heroin", medical.injection({ inject = "Heroin" }))
    end)

    it("labels pills, injectors and charged doctor's bags", function()
        assert.equals("Pills (LSD)", medical.label("Pills", "Pills", { pill = "LSD" }))
        assert.equals("Pills (Antibiotics)", medical.label("Pills", "Pills", nil))
        assert.equals("Injector (Empty)", medical.label("AutoInjec", "Injector", nil))
        local bag = { charges = 2, drug = "Morphine" }
        assert.equals("Doctor's Bag (2/3, Morphine)", medical.label("DoctorBag", "Doctor's Bag", bag))
        assert.equals("Doctor's Bag", medical.label("DoctorBag", "Doctor's Bag", { charges = 0 }))
        assert.equals("Bandage", medical.label("Bandage", "Bandage", nil))
    end)

    it("uses a bandage only on a bleeding patient and infects the wound a third of the time", function()
        local r = medical.treat("Bandage", nil, patient(0, false), true, never, never)
        assert.is_false(r.used)
        assert.is_false(r.consume)
        r = medical.treat("Bandage", nil, patient(0.5, false), true, seq({ 0.1 }), never)
        assert.is_true(r.used)
        assert.is_true(r.consume)
        assert.equals(medical.reduceBleed(0.5), r.bleed)
        assert.is_true(r.infect.wound)
        r = medical.treat("Bandage", nil, patient(0.5, false), false, seq({ 0.33 }), never)
        assert.is_true(r.used)
        assert.is_nil(r.infect.wound)
    end)

    it("cures the wound infection with an antiseptic bandage", function()
        local r = medical.treat("AntiSepBandage", nil, patient(0, true), false, never, never)
        assert.is_true(r.used)
        assert.is_true(r.consume)
        assert.is_false(r.infect.wound)
        assert.is_nil(r.bleed)
        r = medical.treat("AntiSepBandage", nil, patient(0.5, false), false, never, never)
        assert.is_true(r.used)
        assert.is_true(r.consume)
        assert.is_nil(r.infect.wound)
        r = medical.treat("AntiSepBandage", nil, patient(0, false), false, never, never)
        assert.is_false(r.used)
        assert.is_false(r.consume)
        r = medical.treat("AntiSepBandage", nil, { bleed = 0 }, false, never, never)
        assert.is_false(r.used)
    end)

    it("heals 1-2 wounds on yourself and 2-3 on another with a medkit", function()
        local rngInt, calls = recorder(2)
        local r = medical.treat("Medkit", nil, patient(0, false), true, never, rngInt)
        assert.same({ { 1, 2 } }, calls)
        assert.equals(2, r.removeWounds)
        assert.is_true(r.used)
        assert.is_true(r.consume)
        rngInt, calls = recorder(3)
        r = medical.treat("Medkit", nil, patient(0.5, false), false, never, rngInt)
        assert.same({ { 2, 3 } }, calls)
        assert.equals(3, r.removeWounds)
        assert.equals(medical.reduceBleed(0.5), r.bleed)
    end)

    it("stops bleeding, cures and doses with a doctor's bag, spending one charge", function()
        local rngInt, calls = recorder(4)
        local bag = { charges = 2, drug = "Morphine" }
        local r = medical.treat("DoctorBag", bag, patient(0.5, true), false, never, rngInt)
        assert.same({ { 3, 5 } }, calls)
        assert.equals(4, r.removeWounds)
        assert.equals(0, r.bleed)
        assert.is_false(r.infect.wound)
        assert.equals("Morphine", r.drug)
        assert.is_true(r.used)
        assert.is_false(r.consume)
        assert.same({ charges = 1, drug = "Morphine" }, r.data)
        rngInt, calls = recorder(1)
        r = medical.treat("DoctorBag", { charges = 1, drug = "Bogus" }, patient(0, false), true, never, rngInt)
        assert.same({ { 1, 2 } }, calls)
        assert.is_true(r.consume)
        assert.is_nil(r.data)
        assert.is_nil(r.drug)
    end)

    it("applies each pill", function()
        local r = medical.treat("Pills", { pill = "Antibiotics" }, patient(0, true), true, seq({ 0.1 }), never)
        assert.is_true(r.used)
        assert.is_true(r.consume)
        assert.is_false(r.infect.food)
        assert.is_false(r.infect.wound)
        assert.equals("Antibiotic", r.drug)
        r = medical.treat("Pills", nil, patient(0, true), true, seq({ 0.5 }), never)
        assert.is_false(r.infect.food)
        assert.is_nil(r.infect.wound)
        r = medical.treat("Pills", { pill = "Painkiller" }, patient(0, false), true, never, never)
        assert.equals(10, r.hp)
        assert.equals("Painkill", r.drug)
        r = medical.treat("Pills", { pill = "LSD" }, patient(0, false), true, never, never)
        assert.equals("Lsd", r.drug)
        assert.is_nil(r.hp)
    end)

    it("empties an injector into its drug and wakes only another knocked-out patient on adrenaline", function()
        local r = medical.treat("AutoInjec", { inject = "Morphine" }, patient(0, false), true, never, never)
        assert.is_true(r.used)
        assert.is_false(r.consume)
        assert.equals("Morphine", r.drug)
        assert.same({ inject = "Empty" }, r.data)
        assert.is_false(r.wake)
        r = medical.treat("AutoInjec", nil, patient(0, false), true, never, never)
        assert.equals("Air", r.drug)
        local adrenaline = { inject = "Adrenaline" }
        assert.is_true(medical.treat("AutoInjec", adrenaline, patient(0, false, true), false, never, never).wake)
        assert.is_false(medical.treat("AutoInjec", adrenaline, patient(0, false, true), true, never, never).wake)
        assert.is_false(medical.treat("AutoInjec", adrenaline, patient(0, false, false), false, never, never).wake)
        assert.is_false(medical.treat("AutoInjec", adrenaline, patient(0, false), false, never, never).wake)
    end)

    it("stacks drug durations and rejects unknown drugs", function()
        local drugs = {}
        assert.is_true(medical.applyDrug(drugs, "Morphine"))
        assert.equals(300000, drugs.Morphine)
        assert.is_true(medical.applyDrug(drugs, "Morphine", 1000))
        assert.equals(301000, drugs.Morphine)
        assert.is_false(medical.applyDrug(drugs, "Bogus"))
        assert.is_nil(drugs.Bogus)
    end)

    it("counts drugs down and returns the worn-off names in order", function()
        local drugs = { Heroin = 500, Lsd = 1000, Antibiotic = 200, Morphine = 5000 }
        local off = medical.tickDrugs(drugs, 1000)
        assert.same({ "Antibiotic", "Lsd", "Heroin" }, off)
        assert.same({ Morphine = 4000 }, drugs)
        assert.same({}, medical.tickDrugs(drugs, 1000))
        assert.equals(3000, drugs.Morphine)
    end)

    it("round-trips drugs through the column text", function()
        local text = medical.encodeDrugs({ Morphine = 245000.7, Air = 1000 })
        assert.equals('[["Air",1000],["Morphine",245000]]', text)
        assert.equals("[]", medical.encodeDrugs({}))
        local back = medical.decodeDrugs({ { "Air", 1000 }, { "Morphine", 245000 } })
        assert.same({ Air = 1000, Morphine = 245000 }, back)
        local list = { { "Bogus", 1000 }, { "Lsd", 0 }, { "Heroin", -5 }, { "Painkill", "2000" }, "x" }
        assert.same({ Painkill = 2000 }, medical.decodeDrugs(list))
        assert.same({}, medical.decodeDrugs(false))
        assert.same({ Lsd = 300000 * 12 }, medical.decodeDrugs({ { "Lsd", 1e9 } }))
    end)

    it("encodes infection as bits and decodes 0..3", function()
        for v = 0, 3 do
            assert.equals(v, medical.encodeInfection(medical.decodeInfection(v)))
        end
        assert.same({ food = false, wound = false }, medical.decodeInfection(0))
        assert.same({ food = true, wound = false }, medical.decodeInfection(1))
        assert.same({ food = false, wound = true }, medical.decodeInfection(2))
        assert.same({ food = true, wound = true }, medical.decodeInfection(3))
        assert.same({ food = false, wound = false }, medical.decodeInfection(false))
    end)

    it("shakes the camera from an infection unless a drug holds it off", function()
        local inf = { food = true, wound = false }
        assert.is_nil(medical.infectionShake({}, {}, 50, 0, 1e9))
        assert.is_nil(medical.infectionShake(inf, { Morphine = 1 }, 50, 0, 1e9))
        assert.is_nil(medical.infectionShake(inf, { Adrenaline = 1 }, 50, 0, 1e9))
        assert.is_nil(medical.infectionShake(inf, { Air = 1 }, 50, 0, 1e9))
        assert.is_nil(medical.infectionShake(inf, {}, 50, 0, 25000))
        assert.equals(5000, medical.infectionShake(inf, {}, 50, 0, 25001))
        assert.is_nil(medical.infectionShake(inf, {}, 50, 5000, 7000))
        assert.equals(0, medical.infectionShake(inf, {}, 50, 5000, 7001))
    end)

    it("maps drugs to drunk level, sky and darkness", function()
        assert.equals(100000, medical.drugDrunk({ Air = 1, Morphine = 1 }))
        assert.equals(2200, medical.drugDrunk({ Morphine = 1 }))
        assert.is_nil(medical.drugDrunk({ Lsd = 1 }))
        assert.same({ 22, 3, 33 }, medical.drugSky({ Lsd = 1, Heroin = 1 }))
        assert.same({ 22, 30, 33 }, medical.drugSky({ Heroin = 1 }))
        assert.is_nil(medical.drugSky({ Morphine = 1 }))
        assert.is_true(medical.hidesDarkness({ Painkill = 1 }))
        assert.is_true(medical.hidesDarkness({ Adrenaline = 1 }))
        assert.is_false(medical.hidesDarkness({ Morphine = 1 }))
    end)
end)
