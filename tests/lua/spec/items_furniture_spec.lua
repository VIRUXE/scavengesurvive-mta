-- Furniture (items/shared/logic/furniture.lua, upstream itemtype/furniture.pwn, #148).
local furniture = dofile("resources/[scavengesurvive]/items/shared/logic/furniture.lua")

describe("furniture", function()
    it("knows the six types and which two show an item", function()
        assert.are.same({ "Barstool", "Cupboard", "Desk", "GunCase", "SmallTable", "Table" }, furniture.unames())
        assert.is_true(furniture.is("Desk"))
        assert.is_false(furniture.is("Workbench"))
        assert.is_true(furniture.isDisplay("GunCase"))
        assert.is_true(furniture.isDisplay("Cupboard"))
        assert.is_false(furniture.isDisplay("Table"))
        assert.is_false(furniture.isDisplay(nil))
    end)

    it("puts an item on top at upstream's height, with the furniture's heading", function()
        local x, y, z, rz = furniture.onTop({ uname = "Desk", x = 10, y = 20, z = 3, rz = 45 })
        assert.are.same({ 10, 20, 3.8, 45 }, { x, y, z, rz })
        x, y, z, rz = furniture.onTop({ uname = "SmallTable", x = 1, y = 2, z = 0 })
        assert.are.same({ 1, 2, 0.45, 0 }, { x, y, z, rz })
    end)

    it("reads the shown item from either JSON shape", function()
        assert.is_nil(furniture.display(nil))
        assert.is_nil(furniture.display({}))
        assert.is_nil(furniture.display({ display = "" }))
        assert.are.equal("M9Pistol", furniture.display({ display = "M9Pistol" }))
        assert.are.equal("M9Pistol", furniture.display({ { display = "M9Pistol" } }))
    end)

    it("lays the shown item in the case, turned by the case's and its own rotation", function()
        local row = { uname = "Cupboard", x = 5, y = 6, z = 1, rz = 300 }
        local x, y, z, rx, ry, rz = furniture.displayPose(row, { rotz = 90 }, { rotx = 0, roty = 10, rotz = 20 })
        assert.are.same({ 5, 6, 1.35, -90, -80 }, { x, y, z, rx, ry })
        assert.are.equal(50, rz)
    end)
end)
