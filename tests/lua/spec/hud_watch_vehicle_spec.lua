local watch = dofile("resources/[scavengesurvive]/hud/shared/logic/watch.lua")
local panel = dofile("resources/[scavengesurvive]/hud/shared/logic/vehiclepanel.lua")
local bars = dofile("resources/[scavengesurvive]/hud/shared/logic/bars.lua")
describe("hud watch", function()
    it("formats bearing, clock and frequency like the footage", function()
        assert.equals("216 DEG", watch.bearing(144))
        assert.equals("0 DEG", watch.bearing(0))
        assert.equals("90 DEG", watch.bearing(270))
        assert.equals("23:25", watch.clock(23, 25))
        assert.equals("07:05", watch.clock(7, 5))
        assert.equals("107.00", watch.frequency(107))
        assert.equals("98.12", watch.frequency(nil))
    end)
    it("turns red while combat-logging", function()
        assert.same({ 255, 255, 255 }, { watch.colour(false) })
        assert.same({ 0xE8, 0x54, 0x54 }, { watch.colour(true) })
    end)
end)
describe("hud vehicle panel", function()
    it("colours damage by upstream's chunks", function()
        assert.same({ 0xFF, 0, 0 }, panel.damageColour(250))
        assert.same({ 0xFF, 0x77, 0 }, panel.damageColour(450))
        assert.same({ 0xFF, 0xFF, 0 }, panel.damageColour(600))
        assert.same({ 0x80, 0x80, 0 }, panel.damageColour(990))
    end)
    it("formats fuel and speed", function()
        assert.equals("16.41L/58.79", panel.fuelText(16.41, 58.79))
        assert.equals("0km/h", panel.speedText(0, 0, 0))
        assert.equals("150km/h", panel.speedText(1, 0, 0))
    end)
    it("has the six rows at upstream's y positions", function()
        assert.same({ 341, 356, 371, 386, 401, 415 }, { panel.ROWS.doors, panel.ROWS.engine, panel.ROWS.damage, panel.ROWS.fuel, panel.ROWS.speed, panel.ROWS.name })
    end)
end)
describe("hud bars", function()
    it("clamps the hunger fill", function()
        assert.equals(1, bars.fill(150, 100))
        assert.equals(0, bars.fill(-5, 100))
        assert.equals(0.5, bars.fill(50, 100))
    end)
    it("darkens the screen below 40 hp and fades 4 per step", function()
        assert.equals(0, bars.brightness(100))
        assert.equals(0, bars.brightness(40))
        assert.equals(44, bars.brightness(30))
        assert.equals(176, bars.brightness(0))
        assert.equals(44, bars.brightnessStep(0, 44))
        assert.equals(40, bars.brightnessStep(44, 0))
        assert.equals(0, bars.brightnessStep(3, 0))
    end)
end)
