local placement = dofile("resources/[scavengesurvive]/maps/shared/logic/placement.lua")
local function row(model, x, y, world, interior)
    return { model, x, y, 10, 0, 0, 0, world or -1, interior or -1, 350 }
end

describe("maps placement", function()
    it("maps SA-MP world/interior (-1 = any) to MTA dimension/interior", function()
        assert.same({ 0, 0 }, { placement.where(-1, -1) })
        assert.same({ 0, 0 }, { placement.where(0, 0) })
        assert.same({ 3, 1 }, { placement.where(3, 1) })
        assert.same({ 0, 0 }, { placement.where(nil, nil) })
    end)
    it("places vanilla main-world objects as buildings", function()
        assert.equals("building", placement.kind(row(3168, 100, 200), nil))
        assert.equals("building", placement.kind(row(3168, 2999.9, -2999.9, 0, 0), nil))
    end)
    it("uses objects beyond the building limit, in interiors or other worlds, and for default.ide models", function()
        assert.equals("object", placement.kind(row(3168, 3000.1, 0), nil))
        assert.equals("object", placement.kind(row(3168, 0, -3000.1), nil))
        assert.equals("object", placement.kind(row(3168, 0, 0, -1, 1), nil))
        assert.equals("object", placement.kind(row(3168, 0, 0, 7, 0), nil))
        assert.equals("object", placement.kind(row(342, 0, 0), nil)) -- grenade model
        assert.equals("object", placement.kind(row(397, 0, 0), nil))
        assert.equals("building", placement.kind(row(398, 0, 0), nil))
    end)
    it("skips SA-MP models without a loaded replacement and never makes them buildings", function()
        assert.equals("skip", placement.kind(row(19312, 0, 0), nil))
        assert.equals("skip", placement.kind(row(11692, 0, 0), false))
        assert.equals("object", placement.kind(row(19312, 0, 0), 20001))
        assert.is_true(placement.isSampModel(18631))
        assert.is_false(placement.isSampModel(18630))
        assert.is_true(placement.isSampModel(11682))
        assert.is_false(placement.isSampModel(11754))
    end)
    it("asks for a building pool at least as large as the default", function()
        assert.equals(13000, placement.poolCapacity(100))
        assert.equals(13000, placement.poolCapacity(11999))
        assert.equals(16000, placement.poolCapacity(15000))
    end)
    it("tallies a zone", function()
        local objects = { row(3168, 0, 0), row(3168, 4000, 0), row(19312, 0, 0), row(11692, 0, 0) }
        local t = placement.tally(objects, function(model)
            return model == 19312 and 20001 or false
        end)
        assert.same({ building = 1, object = 2, skip = 1 }, t)
    end)
end)
