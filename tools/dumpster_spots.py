"""Every dumpster (model 1227, dump1) in GTA's map, as the spots of the `dumpsters` resource.

    python tools/dumpster_spots.py "<GTA SA folder>" [--out resources/[scavengesurvive]/dumpsters/shared/spots.lua]

Reads the binary streamed IPLs of models/gta3.img and the text IPLs of data/maps, and adds the three placed by this
project's own map files (maps/data/SF.lua, RC.lua; those lines are removed from there when they become spots).
Each spot is { x, y, floorZ, headingDegrees }: 1227's origin is its middle, 0.852 m above the floor.
"""

import glob
import math
import struct
import sys
from pathlib import Path

MODEL = 1227
HALF_HEIGHT = 0.852
CUSTOM = [  # x, y, z (middle), rz: the placements of maps/data/SF.lua and RC.lua
    (-2034.60168, -143.92188, 35.03702, -126.84),
    (-2759.92, 139.27, 6.88, -241.03),
    (2321.272216, 48.80772, 26.337678, -44.99999),
]


def heading(qz, qw):
    """IPL quaternions are the inverse of the object's rotation, so the MTA heading is minus twice the angle"""
    return (-2 * math.degrees(math.atan2(qz, qw))) % 360


def img_entries(path):
    f = open(path, "rb").read()
    assert f[:4] == b"VER2"
    for i in range(struct.unpack("<I", f[4:8])[0]):
        e = 8 + i * 32
        off = struct.unpack("<I", f[e : e + 4])[0]
        size = struct.unpack("<H", f[e + 4 : e + 6])[0]
        yield f[e + 8 : e + 32].split(b"\0")[0].decode().lower(), f[off * 2048 : (off + size) * 2048]


def spots(game):
    found = []
    for name, d in img_entries(Path(game) / "models/gta3.img"):
        if name.endswith(".ipl") and d[:4] == b"bnry":
            n, off = struct.unpack("<I", d[4:8])[0], struct.unpack("<I", d[28:32])[0]
            for i in range(n):
                x, y, z, qx, qy, qz, qw, mid = struct.unpack("<3f4fi", d[off + i * 40 : off + i * 40 + 32])
                if mid == MODEL:
                    found.append((x, y, z, heading(qz, qw)))
    for f in glob.glob(str(Path(game) / "data/maps/**/*.ipl"), recursive=True):
        inst = False
        for line in open(f, errors="ignore"):
            line = line.strip()
            if line == "inst":
                inst = True
            elif line == "end":
                inst = False
            elif inst:
                p = [s.strip() for s in line.split(",")]
                if p[0].isdigit() and int(p[0]) == MODEL and int(p[2]) == 0:
                    found.append((float(p[3]), float(p[4]), float(p[5]), heading(float(p[8]), float(p[9]))))
    found += CUSTOM
    return sorted((round(x, 3), round(y, 3), round(z - HALF_HEIGHT, 3), round(h, 1)) for x, y, z, h in found)


if __name__ == "__main__":
    game = sys.argv[1]
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else None
    rows = spots(game)
    text = "-- Generated by tools/dumpster_spots.py: every dumpster of GTA's map (model 1227) and of maps/data.\n"
    text += "-- { x, y, floor z, heading }\nreturn {\n"
    text += "".join(f"    {{ {x}, {y}, {z}, {h} }},\n" for x, y, z, h in rows) + "}\n"
    if out:
        out.write_text(text)
    print(len(rows), "spots")
