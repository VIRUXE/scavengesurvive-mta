"""Languages QA (issue #51): compares every generated language table with English and writes docs/languages-qa.md.

Usage: python -m tools.lang_qa [--check]
Checks per language: keys missing (t() falls back to English), keys not in English, untranslated values (equal to
English or the upstream "(REQUIRES TRANSLATION:…)" marker), leftover SA-MP tokens (~x~, {C_…}, %P) and printf
placeholders that do not match English (a translation with more or differently typed placeholders makes
string.format fail, and t() then shows the raw string). It also lists the display names (item types, ammo kinds,
calibres, liquids, seed kinds) each language lacks in tools/convert/lang_port/names/<code>.json. --check exits 1 when
the committed report is stale.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "resources" / "[scavengesurvive]" / "data" / "generated"
REPORT = ROOT / "docs" / "languages-qa.md"
RESOURCES = ROOT / "resources" / "[scavengesurvive]"
NAMES_DIR = ROOT / "tools" / "convert" / "lang_port" / "names"
# shown to players untranslated on purpose: placeholder types and bare calibre numbers
NAME_SKIP = {"NULL", "<null>", "VEHICLE_WEAPON", ""}
CALIBRE_RE = re.compile(r"[.\d]+(?:mm)?")
CODES = ["en", "es", "fr", "pt", "ptbr", "ru", "ro", "id", "bhs", "cs"]
NAMES = {"en": "English", "es": "Español", "fr": "Français", "pt": "Português", "ptbr": "Português do Brasil",
         "ru": "Russian", "ro": "Romanian", "id": "Indonesian", "bhs": "Bosanski-Hrvatski-Srpski", "cs": "Čeština"}
LINE_RE = re.compile(r'^\s{4}(?:([A-Za-z_][A-Za-z0-9_]*)|\["((?:[^"\\]|\\.)*)"\])\s*=\s*"((?:[^"\\]|\\.)*)",\s*$')
PLACEHOLDER_RE = re.compile(r"%(?:\d+\$)?[-+ #0]*\d*(?:\.\d+)?([a-zA-Z%])")
LEFTOVER_RE = re.compile(r"~[a-zA-Z]~|\{C_[A-Z]+\}|%P|~k~")
ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'"}


def unescape(s: str) -> str:
    out, i = [], 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s):
            nxt = s[i + 1]
            if nxt in ESCAPES:
                out.append(ESCAPES[nxt])
                i += 2
                continue
            m = re.match(r"\d{1,3}", s[i + 1:])
            if m:
                out.append(chr(int(m.group(0))))
                i += 1 + len(m.group(0))
                continue
        out.append(ch)
        i += 1
    return "".join(out)


def load(code: str) -> dict[str, str]:
    entries = {}
    for line in (GENERATED / f"lang_{code}.lua").read_text(encoding="utf-8").splitlines():
        m = LINE_RE.match(line)
        if m:
            entries[m.group(1) or unescape(m.group(2))] = unescape(m.group(3))
    return entries


def placeholders(s: str) -> list[str]:
    return [p for p in PLACEHOLDER_RE.findall(s) if p != "%"]


def compare(en: dict[str, str], other: dict[str, str]) -> dict:
    missing = sorted(k for k in en if k not in other)
    extra = sorted(k for k in other if k not in en)
    untranslated, leftovers, mismatched = [], [], []
    for k, v in sorted(other.items()):
        if k not in en:
            continue
        if v == en[k] or v.startswith("(REQUIRES TRANSLATION"):
            untranslated.append(k)
        if LEFTOVER_RE.search(v):
            leftovers.append(k)
        if placeholders(v) != placeholders(en[k]):
            mismatched.append((k, "".join("%" + p for p in placeholders(en[k])) or "-",
                               "".join("%" + p for p in placeholders(v)) or "-"))
    return {"keys": len(other), "missing": missing, "extra": extra, "untranslated": untranslated,
            "leftovers": leftovers, "mismatched": mismatched}


def render(results: dict[str, dict], en_count: int) -> str:
    out = ["# Languages QA", "",
           "Generated by `python -m tools.lang_qa` from `resources/[scavengesurvive]/data/generated/lang_*.lua` "
           "(issue #51). A key missing from a language falls back to English in `data`'s `t()`; a placeholder "
           "mismatch makes `string.format` fail and `t()` returns the raw template. Players pick a language with "
           "`/lang <code>` (stored on the account).", "",
           f"English has {en_count} keys.", "",
           "| Code | Language | Keys | Missing (fallback to English) | Untranslated | Placeholder mismatches | Leftover SA-MP tokens | Not in English |",
           "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for code in CODES[1:]:
        r = results[code]
        out.append(f"| `{code}` | {NAMES[code]} | {r['keys']} | {len(r['missing'])} | {len(r['untranslated'])} | "
                   f"{len(r['mismatched'])} | {len(r['leftovers'])} | {len(r['extra'])} |")
    out += ["", "## Placeholder mismatches", "",
            "The translation's placeholders differ from English (type or count). `t()` catches the failing format, "
            "so the player sees the template with its `%` codes instead of a crash; fixing them is a translation task.", ""]
    any_mismatch = False
    for code in CODES[1:]:
        for key, en_ph, ph in results[code]["mismatched"]:
            any_mismatch = True
            out.append(f"- `{code}` `{key}`: English `{en_ph}`, translation `{ph}`")
    if not any_mismatch:
        out.append("None.")
    out += ["", "## Leftover SA-MP tokens", ""]
    any_left = False
    for code in CODES[1:]:
        for key in results[code]["leftovers"]:
            any_left = True
            out.append(f"- `{code}` `{key}`")
    if not any_left:
        out.append("None: the converter replaced every `~x~`, `{C_*}`, `~k~` and `%P` token.")
    out += ["", "## Keys every translation lacks", ""]
    common = set(results[CODES[1]]["missing"])
    for code in CODES[2:]:
        common &= set(results[code]["missing"])
    out.append(f"{len(common)} keys exist only in English (added upstream after the translations were made): "
               + ", ".join(f"`{k}`" for k in sorted(common)[:40]) + (" …" if len(common) > 40 else ""))
    out.append("")
    return "\n".join(out)


def english_names() -> list[str]:
    """Every display name lib's lang module translates: item type and ammo kind names and calibre names from the
    generated item types, and the liquid and seed kind names of the items resource, plus the pitched tent labels."""
    out: list[str] = []

    def add(name: str) -> None:
        if name not in NAME_SKIP and not CALIBRE_RE.fullmatch(name) and name not in out:
            out.append(name)

    types = (GENERATED / "item_types.lua").read_text(encoding="utf-8")
    for line in types.splitlines():
        if line.startswith("M.byUname."):
            m = re.search(r', name = "((?:[^"\\]|\\.)*)", price', line)
            if m:
                add(unescape(m.group(1)))
            m = re.search(r'categoryData = \{[^}]*\bname = "([^"]*)"', line)
            if m:
                add(m.group(1))
    m = re.search(r"M\.calibreNames = \{(.*)\}", types)
    for v in re.findall(r'= "([^"]*)"', m.group(1) if m else ""):
        add(v)
    for rel in ("items/shared/logic/liquids.lua", "items/shared/logic/gardening.lua"):
        for v in re.findall(r'\{ name = "([^"]*)"', (RESOURCES / rel).read_text(encoding="utf-8")):
            add(v)
    for v in ("Pitched Tent", "Tent"):
        add(v)
    return out


def compare_names(english: list[str], code: str) -> dict:
    path = NAMES_DIR / f"{code}.json"
    names = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    missing = [n for n in english if not names.get(n)]
    same = [n for n in english if names.get(n) == n]
    extra = sorted(n for n in names if n not in english)
    return {"missing": missing, "same": same, "extra": extra}


def render_names(english: list[str], results: dict[str, dict]) -> str:
    out = ["## Display names", "",
           "Item type, ammo kind, calibre, liquid and seed kind names are English in the data; lib's `lang` module "
           "shows them in the player's language from `data/generated/names_<code>.lua`, generated from "
           "`tools/convert/lang_port/names/<code>.json` by `python -m tools.convert names`. A name a language "
           "lacks shows in English. Names kept identical to English are model names, brands and the like.", "",
           f"English has {len(english)} names.", "",
           "| Code | Language | Missing (shown in English) | Kept as in English | Not in English (stale) |",
           "| --- | --- | ---: | ---: | ---: |"]
    for code in CODES[1:]:
        r = results[code]
        out.append(f"| `{code}` | {NAMES[code]} | {len(r['missing'])} | {len(r['same'])} | {len(r['extra'])} |")
    out.append("")
    for code in CODES[1:]:
        r = results[code]
        if r["missing"]:
            out.append(f"- `{code}` lacks: " + ", ".join(f"`{n}`" for n in r["missing"][:40])
                       + (" …" if len(r["missing"]) > 40 else ""))
        if r["extra"]:
            out.append(f"- `{code}` has names no longer in English: " + ", ".join(f"`{n}`" for n in r["extra"][:40]))
    if out[-1] != "":
        out.append("")
    return "\n".join(out)


def build() -> tuple[str, dict[str, dict]]:
    en = load("en")
    results = {code: compare(en, load(code)) for code in CODES[1:]}
    english = english_names()
    names = {code: compare_names(english, code) for code in CODES[1:]}
    return render(results, len(en)) + "\n" + render_names(english, names), results


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text, _ = build()
    if "--check" in argv:
        current = REPORT.read_text(encoding="utf-8") if REPORT.exists() else ""
        if current != text:
            print("docs/languages-qa.md is stale; run python -m tools.lang_qa")
            return 1
        print("docs/languages-qa.md is current")
        return 0
    REPORT.write_text(text, encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
