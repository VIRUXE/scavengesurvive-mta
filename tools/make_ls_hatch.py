"""The Ganton ladder entrance's cast-iron hatch: a port model (id 20201) for the world resource's puzzles.

Upstream marks the entrance (world/puzzles/ranch.pwn "LS entrance (by Dogmeat)") with sw_well1, a fenced countryside
well, created in the ranch's own world, so the normal world showed bare grass; this lid stands there instead. It is a
1 m square plate, 4 cm thick, wearing pave_manhole1 (a square "BO-NESS IRON CO LTD / METER" cover from the game's
zombtest1.txd) on top and the cover's rim on its edges, with dim day/night prelight and one box of collision.

    python -m tools.make_ls_hatch [--gta DIR] [--blender EXE]

Outside Blender it writes prop_models/files/ls_hatch.txd (zombtest1.txd from gta3.img cut down to pave_manhole1, as
tools/extract_samp_models.py trims vanilla TXDs) and prop_models/props.lua, then runs itself in Blender (DragonFF) for
ls_hatch.dff and ls_hatch.col.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROP_MODELS = ROOT / "resources" / "[scavengesurvive]" / "prop_models"
FILES = PROP_MODELS / "files"
PROPS = PROP_MODELS / "props.lua"
NAME, MODEL_ID, TEXTURE, SOURCE_TXD = "ls_hatch", 20201, "pave_manhole1", "zombtest1.txd"
SIZE, THICK, RIM = 1.0, 0.04, 0.04  # metres; RIM: the share of the texture the edges show
DAY, NIGHT = (0.38, 0.38, 0.38, 1.0), (0.12, 0.12, 0.13, 1.0)


def render_props() -> str:
    return "\n".join([
        "-- Generated by tools/make_ls_hatch.py; do not edit. Port model id -> a prop the port adds to the world,",
        "-- in prop_models/files/ with its own TXD and collision.",
        "return {",
        f'    [{MODEL_ID}] = {{ dff = "{NAME}", txd = "{NAME}", dist = 150 }},',
        "}",
        "",
    ])


def render_meta(out_dir: Path) -> str:
    props_lua = out_dir / "props.lua"
    fort_lua = out_dir / "fort.lua"
    dffs = []
    if props_lua.is_file():
        dffs += [f"{name}.dff" for name in re.findall(r'dff = "([^"]+)"', props_lua.read_text(encoding="ascii"))]
    files = []
    for dff in sorted(dffs):
        stem = dff[:-4]
        files += [f"{stem}.col", f"{stem}.dff", f"{stem}.txd"]
    has_fort = fort_lua.is_file()
    if has_fort:
        fort_dffs = sorted(f"{name}.dff" for name in re.findall(r'dff = "([^"]+)"', fort_lua.read_text(encoding="ascii")))
        fort_txds = sorted({f"{n}.txd" for n in re.findall(r'txd = "([^"]+)"', fort_lua.read_text(encoding="ascii"))})
        files += sorted(fort_dffs + [name[:-4] + ".col" for name in fort_dffs]) + fort_txds
    lines = [
        "<meta>",
        '    <info author="scavengesurvive-mta" type="script" name="prop_models" '
        'description="Port prop models added to the world" version="0.1.0"/>',
        '    <min_mta_version server="1.6.0" client="1.6.0-9.21695"/>',
        "    <download_priority_group>90</download_priority_group>",
        '    <include resource="lib"/>',
        '    <script src="client/main.lua" type="client"/>',
        '    <file src="props.lua"/>',
    ]
    if has_fort:
        lines.append('    <file src="fort.lua"/>')
    lines += [f'    <file src="files/{name}"/>' for name in files]
    lines += [
        '    <export function="resolve" type="client"/>',
        '</meta>',
    ]
    return "\n".join(lines) + "\n"


def write_meta(out_dir: Path) -> None:
    (out_dir / "meta.xml").write_text(render_meta(out_dir), encoding="ascii", newline="\n")


def build_in_blender(out_dir: Path) -> None:
    import bmesh
    import bpy

    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.preferences.addon_enable(module="DragonFF")
    scene = bpy.context.scene
    model = bpy.data.collections.new(NAME)
    scene.collection.children.link(model)

    mesh = bpy.data.meshes.new(NAME)
    bm = bmesh.new()
    h = SIZE / 2
    corners = [(-h, -h), (h, -h), (h, h), (-h, h)]
    top = [bm.verts.new((x, y, THICK)) for x, y in corners]
    low = [bm.verts.new((x, y, 0.0)) for x, y in corners]
    uv = bm.loops.layers.uv.new("UVMap")
    day = bm.loops.layers.color.new("Day")
    night = bm.loops.layers.color.new("Night")
    faces = [(bm.faces.new(top), [(0, 0), (1, 0), (1, 1), (0, 1)])]
    for i in range(4):
        j = (i + 1) % 4
        faces.append((bm.faces.new((low[i], low[j], top[j], top[i])), [(0, 0), (1, 0), (1, RIM), (0, RIM)]))
    for face, uvs in faces:
        for loop, (u, v) in zip(face.loops, uvs):
            loop[uv].uv = (u, v)
            loop[day] = DAY
            loop[night] = NIGHT
    bm.normal_update()
    bm.to_mesh(mesh)
    bm.free()

    image = bpy.data.images.new(TEXTURE + ".png", 8, 8)  # DragonFF writes the name; the pixels are the TXD's
    material = bpy.data.materials.new(TEXTURE)
    material.use_nodes = True
    bsdf = next(n for n in material.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
    node = material.node_tree.nodes.new("ShaderNodeTexImage")
    node.image = image
    material.node_tree.links.new(node.outputs["Color"], bsdf.inputs["Base Color"])
    mesh.materials.append(material)

    plate = bpy.data.objects.new(NAME, mesh)
    plate.dff.type = "OBJ"
    plate.dff.day_cols = True
    plate.dff.night_cols = True
    model.objects.link(plate)

    box = bpy.data.objects.new(NAME + "_col", None)
    box.empty_display_type = "CUBE"
    box.location = (0.0, 0.0, THICK / 2)
    box.scale = (h, h, THICK / 2)
    box.dff.type = "COL"
    model.objects.link(box)

    dff_path, col_path = out_dir / f"{NAME}.dff", out_dir / f"{NAME}.col"
    bpy.ops.export_dff.scene(filepath=str(dff_path), export_coll=False, only_selected=False, export_version="0x36003")
    bpy.ops.export_col.scene(filepath=str(col_path), export_version="3", only_selected=False)
    print(f"make_ls_hatch: wrote {dff_path.name} and {col_path.name}")


def main(argv=None) -> int:
    import argparse
    import subprocess

    from tools.extract_ped_models import find_blender
    from tools.extract_samp_models import detect_gta, read_img_entry, read_img_index, trim_txd

    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gta", type=Path, help="GTA:SA folder (default: from the registry)")
    ap.add_argument("--blender", help="blender.exe (default: BLENDER or the newest install)")
    args = ap.parse_args(argv)
    gta = args.gta or detect_gta()
    img = gta / "models" / "gta3.img" if gta else None
    if not img or not img.is_file():
        print("make_ls_hatch: no GTA:SA models/gta3.img (pass --gta)", file=sys.stderr)
        return 2
    blender = find_blender(args.blender)
    if not blender:
        print("make_ls_hatch: no Blender found (pass --blender)", file=sys.stderr)
        return 2
    txd = trim_txd(read_img_entry(img, read_img_index(img)[SOURCE_TXD]), {TEXTURE})
    (FILES / f"{NAME}.txd").write_bytes(txd)
    PROPS.write_text(render_props(), encoding="ascii", newline="\n")
    write_meta(PROP_MODELS)
    cmd = [str(blender), "-b", "--python", __file__, "--", str(FILES)]
    res = subprocess.run(cmd, capture_output=True, text=True)
    out = res.stdout + res.stderr
    print("\n".join(line for line in out.splitlines() if "make_ls_hatch" in line or "Error" in line))
    return 0 if res.returncode == 0 and (FILES / f"{NAME}.dff").is_file() else 1


if __name__ == "__main__":
    if "bpy" in sys.modules or "--" in sys.argv:
        build_in_blender(Path(sys.argv[sys.argv.index("--") + 1]))
    else:
        sys.exit(main())
