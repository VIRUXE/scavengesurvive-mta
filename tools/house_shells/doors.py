"""Writes house_shell/houses.lua: per enterable house, the DFF/COL/TXD replacing the vanilla model, its door leaf,
where each of its leaves hangs in the model's frame (tools/trailer_shells/build/<name>_doors.json, written by the
house's Blender script in tools/house_shells) and every upright vanilla placement of the model in the world (the text
and binary IPLs), less the ones upstream's maps remove (RemoveBuildingForPlayer rows in maps/data/*.lua).

    python -m tools.house_shells.doors [--gta DIR]
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

from tools.extract_samp_models import detect_gta
from tools.ipl_natives import native_instances
from tools.trailer_shells.doors import OUT as TRAILERS_OUT
from tools.trailer_shells.doors import UPRIGHT, removals, removed
from tools.trailer_shells.prep import BUILD

HOUSES = {3303: "des_bighus03", 3304: "des_bighus02", 3305: "des_bighus01"}  # vanilla model -> shell
OUT = TRAILERS_OUT.with_name("houses.lua")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gta", type=Path, help="GTA:SA folder (default: from the registry)")
    args = ap.parse_args(argv)
    gta = args.gta or detect_gta()
    if not gta:
        print("house_shells.doors: no GTA:SA folder (pass --gta)", file=sys.stderr)
        return 2
    rows = removals()
    placed = {model: [] for model in HOUSES}
    for model, pos, rot in native_instances(gta):
        if model in HOUSES and rot[2][2] >= UPRIGHT and not removed(model, pos, rows):
            placed[model].append((pos[0], pos[1], pos[2], math.degrees(math.atan2(rot[1][0], rot[0][0])) % 360))
    lines = [
        "-- Generated by tools/house_shells/doors.py; do not edit. The enterable houses: per vanilla model, the DFF, COL",
        "-- and TXD replacing it (files/<dff>.*), its door leaf (files/<door>.*), each leaf's hinge as x, y, z, rz in the",
        "-- model's frame, then each upright vanilla placement the maps keep, as { x, y, z, rz }.",
        "return {",
    ]
    for model, name in sorted(HOUSES.items()):
        doors = json.loads((BUILD / f"{name}_doors.json").read_text())["doors"]
        lines += [
            "    {",
            f"        model = {model},",
            f'        dff = "{name}",',
            f'        door = "{name}_door",',
            "        hinges = {",
        ]
        lines += [f"            {{ {d['hinge'][0]:.3f}, {d['hinge'][1]:.3f}, {d['hinge'][2]:.3f}, {d['rz']:.1f} }}," for d in doors]
        lines += ["        },", "        placements = {"]
        lines += [f"            {{ {x:.3f}, {y:.3f}, {z:.3f}, {rz:.1f} }}," for x, y, z, rz in sorted(placed[model])]
        lines += ["        },", "    },"]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"house_shells.doors: {', '.join(f'{HOUSES[m]} {len(p)} placements' for m, p in placed.items())} -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
