"""Measures what each upstream fort structure rests on, so its custom replacement can be built to fit.

    python -m tools.fort_spans "LS/Fort Defiance.map" [--out FILE]

For every row of the structure models below (walkways, stairs, ramps, decks, the barn and hut, the dish and its mount) it
turns the prop's collision box into world space, walks the box's long axis in 0.5 m steps and asks the running Ariane editor
(tools/ariane_profile.py) for the first surface under each step that is not one of the fort's own props: the roof, the
wall, the ground. The profile is reported as runs of equal height, so a span reads as "roof 16.3 m for 3 m, then air,
then roof 14.9 m". Duplicated rows (same model, same place) are flagged.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import subprocess
import sys
from pathlib import Path

from tools.convert.maps import parse_map
from tools.fort_survey import DEFAULT_GTA, UPSTREAM, ide_names, matrix, model_box, world_box
from tools.model_bounds import load

ROOT = Path(__file__).resolve().parents[1]
VENV_PYTHON = Path(r"C:\dev\gta\sa\tools\ariane-agent\ariane-agent-windows-x64\.venv-agent\Scripts\python.exe")
PROFILE_TOOL = ROOT / "tools" / "ariane_profile.py"
STRUCTURES = {3406, 16502, 11496, 3361, 974, 1245, 1503, 3260, 3095, 11327, 17010, 16405, 1595, 2985, 8879, 8877, 2929}
STEP, MAX_SAMPLES, RUN_TOLERANCE = 0.5, 48, 0.25


def apply(rot, v, pos):
    return [sum(rot[i][k] * v[k] for k in range(3)) + pos[i] for i in range(3)]


def axis_line(row, box):
    """(start, end, length, width, rotation) of the box's local axis that runs longest along the ground once the row's
    rotation is applied (a prop tipped onto its side has its long axis in z or y), as world points through the centre."""
    rot = matrix(row[4], row[5], row[6])
    pos = (row[1], row[2], row[3])
    mid = [(box[i] + box[i + 3]) / 2 for i in range(3)]
    extent = [box[i + 3] - box[i] for i in range(3)]
    best = max(range(3), key=lambda i: extent[i] * math.hypot(rot[0][i], rot[1][i]))
    a, b = list(mid), list(mid)
    a[best], b[best] = box[best], box[best + 3]
    pa, pb = apply(rot, a, pos), apply(rot, b, pos)
    return pa, pb, math.hypot(pb[0] - pa[0], pb[1] - pa[1]), sorted(extent)[1]


def sample_points(a, b, length):
    n = min(MAX_SAMPLES, max(1, math.ceil(length / STEP)))
    return [(a[0] + (b[0] - a[0]) * i / n, a[1] + (b[1] - a[1]) * i / n) for i in range(n + 1)], length / n


def runs(profile, step):
    """Consecutive samples on the same surface height (within RUN_TOLERANCE) as (from m, to m, z, name); None = no surface."""
    out = []
    for i, p in enumerate(profile):
        s = i * step
        key = None if p is None else p["z"]
        last = out[-1] if out else None
        if last and ((key is None and last[2] is None) or (key is not None and last[2] is not None and abs(key - last[2]) <= RUN_TOLERANCE)):
            last[1] = s
        else:
            out.append([s, s, key, None if p is None else p["name"]])
    return out


def run_profile(points, skipped):
    token = (Path(os.environ["LOCALAPPDATA"]) / "ariane-agent" / "token").read_text().strip()
    env = {**os.environ, "ARIANE_ENGINE_TCP_PORT": "48731", "ARIANE_ENGINE_TOKEN": token}
    args = [str(VENV_PYTHON), str(PROFILE_TOOL), json.dumps([[round(x, 2), round(y, 2)] for x, y in points]), json.dumps(sorted(skipped))]
    res = subprocess.run(args, capture_output=True, text=True, env=env)
    if res.returncode:
        raise RuntimeError(f"ariane_profile.py failed (is Ariane running?): {res.stderr.strip()}")
    return json.loads(res.stdout)


def measure(rows, names, bounds, profile=run_profile):
    skipped = {r[0] for r in rows}
    out, seen = [], {}
    chosen = [r for r in rows if r[0] in STRUCTURES]
    plans = []
    for r in chosen:
        box = model_box(r[0], names, bounds)
        if box is None:
            continue
        a, b, length, width = axis_line(r, box)
        pts, step = sample_points(a, b, length)
        plans.append((r, box, a, b, length, width, pts, step))
    flat = [p for plan in plans for p in plan[6]]
    heights = profile(flat, skipped)
    at = 0
    for r, box, a, b, length, width, pts, step in plans:
        prof = heights[at : at + len(pts)]
        at += len(pts)
        top = world_box(box, matrix(r[4], r[5], r[6]), (r[1], r[2], r[3]))
        key = (r[0], round(r[1], 1), round(r[2], 1))
        seen[key] = seen.get(key, 0) + 1
        out.append({"row": r, "name": names[r[0]][0], "length": length, "width": width, "a": a, "b": b, "z": (top[2], top[5]), "runs": runs(prof, step), "dup": seen[key] > 1})
    return out


def render(name: str, spans: list[dict]) -> str:
    lines = [f"# {name}: spans", "", f"Generated by `python -m tools.fort_spans \"{name}\"`: the surface under each structure's long axis, "
             f"every {STEP} m, looking past the fort's own props (so a roof reads as a roof).", ""]
    for sp in spans:
        r = sp["row"]
        head = f"## {r[0]} `{sp['name']}` at {r[1]:.1f}, {r[2]:.1f}, {r[3]:.1f} (rot {r[4]:.0f}, {r[5]:.0f}, {r[6]:.0f})" + ("  DUPLICATE" if sp["dup"] else "")
        lines += [head, "", f"{sp['length']:.1f} x {sp['width']:.1f} m footprint, prop z {sp['z'][0]:.1f}..{sp['z'][1]:.1f}; axis "
                  f"({sp['a'][0]:.1f}, {sp['a'][1]:.1f}) -> ({sp['b'][0]:.1f}, {sp['b'][1]:.1f}).", "", "| along (m) | surface z | surface |", "| --- | ---: | --- |"]
        for start, end, z, label in sp["runs"]:
            lines.append(f"| {start:.1f} - {end:.1f} | {'none' if z is None else f'{z:.2f}'} | {label or 'nothing under it'} |")
        lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("map")
    ap.add_argument("--gta", type=Path, default=DEFAULT_GTA)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--cache", type=Path, default=ROOT / ".cache" / "model_bounds.json")
    args = ap.parse_args(argv)
    rows = parse_map((UPSTREAM / args.map).read_text(encoding="utf-8", errors="ignore"), args.map)["objects"]
    spans = measure(rows, ide_names(args.gta), load(args.gta, args.cache))
    text = render(args.map.removesuffix(".map"), spans)
    if args.out:
        args.out.write_text(text, encoding="utf-8", newline="\n")
        print(f"fort_spans: {len(spans)} structures -> {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
