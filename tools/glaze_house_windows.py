"""Glazes the window openings of the SA-MP house shells (lshouse1-4, lvhouse1-4, sfhouse1-4), which ship as bare
holes. Run inside Blender with the DragonFF addon enabled, after tools/extract_samp_models.py wrote the originals:

    blender -b --python tools/glaze_house_windows.py -- SRC_DIR OUT_DIR TEXTURE_DIR lshouse1 lshouse2 ...

SRC_DIR holds the extracted DFFs (and the baked <name>int.dff interiors, which light the room side), TEXTURE_DIR the house_window.PNG written by tools/make_house_window.py plus the curtain and blind PNGs named in
HANGINGS, decoded from the game's TXDs (gta-scout's TXDReader). Each opening is
a planar rectangular boundary loop in the wall, under 1.85 m tall, or up to 2.6 m when the maps put a window001 or
lsmall_window01 pane in it (a bay, a floor-to-ceiling window; other tall ones are doors and entrances); it gets a recessed translucent pane textured house_window in a modelled frame, and the house's curtains or blind. The shells' triangles all say material 0 and the real
split lives in the BinMesh chunk, which DragonFF ignores, so it is copied into the triangle records first.
models/client/main.lua imports files/house_window.txd into the shells' vanilla dictionaries.
"""
