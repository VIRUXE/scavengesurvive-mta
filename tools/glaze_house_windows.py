def shell_id(name):
    import re
    return int(re.search(r'\[(\d+)\] = \{ dff = "%s",' % name, open(os.path.join(RES,'models','manifest.lua')).read()).group(1))
def write_glazed(openings):
    """maps/shared/glazed_windows.lua: the openings each shell now glazes itself, so the maps drop the panes in them.
    Shells not in this run keep their line."""
    keep={}; cur=None
    if os.path.exists(GLAZED_LUA):
        for line in open(GLAZED_LUA).read().splitlines():
            if line.startswith('    ['): cur=int(line[5:line.index(']')]); keep[cur]=[]
            if cur is not None: keep[cur].append(line)
            if line=='    },': cur=None
    for sid,ops in openings.items():
        keep[sid]=['    [%d] = {' % sid]+['        { %s },' % ', '.join('%.3f' % v for v in o) for o in ops]+['    },']
    head=['-- Generated by tools/glaze_house_windows.py: the window openings each SA-MP house shell glazes itself, in the',
          "-- shell's frame, as { cx, cy, cz, nx, ny, halfWidth, halfHeight } (centre, outward normal). The maps drop the",
          '-- window001 and lsmall_window01 panes upstream put in them (shared/logic/placement.lua).','return {']
    open(GLAZED_LUA,'w',newline='\n').write('\n'.join(head+[l for k in sorted(keep) for l in keep[k]]+['}','']))
def map_panes(name):
    """Map pane positions in the frame of each placed copy of the shell `name`, from the maps' generated data."""
    import math, re
    sid=shell_id(name)
    rows={sid:[],**{p:[] for p in PANES}}
    datadir=os.path.join(RES,'maps','data')
    for f in os.listdir(datadir):
        for m in re.finditer(r'\{\s*(\d+),\s*([-\d.]+),\s*([-\d.]+),\s*([-\d.]+),\s*[-\d.]+,\s*[-\d.]+,\s*([-\d.]+)', open(os.path.join(datadir,f)).read()):
            if int(m[1]) in rows: rows[int(m[1])].append(tuple(map(float,m.groups()[1:])))
    out=[]
    for x,y,z,rz in rows[sid]:
        c,s_=math.cos(math.radians(-rz)),math.sin(math.radians(-rz))
        for px,py,pz,_ in [r for p in PANES for r in rows[p]]:
            dx,dy=px-x,py-y
            if dx*dx+dy*dy<15*15 and abs(pz-z)<8: out.append(Vector((dx*c-dy*s_,dx*s_+dy*c,pz-z)))
    return out
def loops_of(bm):
    seen=set(); out=[]
    for e in bm.edges:
        if not e.is_boundary or e in seen: continue
        st=[e]; comp=[]
        while st:
            x=st.pop()
            if x in seen: continue
            seen.add(x); comp.append(x)
            for v in x.verts:
                for y in v.link_edges:
                    if y.is_boundary and y not in seen: st.append(y)
        out.append(comp)
    return out
def ordered(comp):
    es=list(comp); v0=es[0].verts[0]; order=[v0]; cur=v0; used=set()
    while len(order)<len(es):
        for e in cur.link_edges:
            if e in comp and e not in used:
                used.add(e); cur=e.other_vert(cur); order.append(cur); break
        else: return None
    return order
glazed={}
for n in names:
    bpy.ops.wm.read_factory_settings(use_empty=True); bpy.ops.preferences.addon_enable(module="DragonFF")
    os.makedirs(dst, exist_ok=True)
    tmp = f"{dst}/{n}.materials.dff"
    apply_binmesh_materials(f"{src}/{n}.dff", tmp)
    bpy.ops.import_scene.dff(filepath=tmp)
    os.remove(tmp)
    o=[o for o in bpy.data.objects if o.type=='MESH'][0]; me=o.data
    # detection on a welded copy
    det=bmesh.new(); det.from_mesh(me); bmesh.ops.remove_doubles(det,verts=det.verts,dist=1e-4)
    wins=[]; panes=map_panes(n)
    allv=[v.co for v in det.verts]; ctr=Vector([(min(c[i] for c in allv)+max(c[i] for c in allv))/2 for i in range(3)])  # bounding box centre: a detailed porch dragged the vertex average past lshouse3's front wall
    for comp in loops_of(det):
        if len(comp)!=4: continue
        vs=ordered(comp)
        if not vs or len(vs)!=4: continue
        P=[v.co.copy() for v in vs]
        n_=(P[1]-P[0]).cross(P[2]-P[1]); 
        if n_.length<1e-6: continue
        n_.normalize()
        if abs(n_.z)>0.2: continue
        if max(abs((p-P[0]).dot(n_)) for p in P)>0.02: continue
        e0,e1=(P[1]-P[0]),(P[2]-P[1])
        if abs(e0.dot(e1))>0.05*e0.length*e1.length: continue
        zs=[p.z for p in P]; h=max(zs)-min(zs)
        w=max((e0 if abs(e0.z)<abs(e1.z) else e1).length,0)
        if h<0.4 or w<0.4 or h>2.6 or w>5.0: continue
        # outward = normal of the single face next to the loop
        out=n_.copy()
        cen=sum(P,Vector())/4
        if (cen-ctr).dot(out)<0: out=-out
        # taller than 1.85 m it is a door or an entrance, unless the maps glaze it (a bay, a picture window)
        if h>=1.85:
            ax=Vector((-out.y,out.x,0)).normalized(); us=[p.dot(ax) for p in P]
            if not any(abs((q-cen).dot(out))<0.4 and min(us)-0.1<=q.dot(ax)<=max(us)+0.1 and min(zs)-0.1<=q.z<=max(zs)+0.1 for q in panes): continue
        wins.append((P,out))
    glazed[shell_id(n)]=[]
    for P,out in wins:
        cen=sum(P,Vector())/4; ax=Vector((-out.y,out.x,0)).normalized(); us=[p.dot(ax) for p in P]; zs=[p.z for p in P]
        glazed[shell_id(n)].append((cen.x,cen.y,cen.z,out.x,out.y,(max(us)-min(us))/2,(max(zs)-min(zs))/2))
    print("WINDOWS",n,len(wins),[ (round(max(p.z for p in P)-min(p.z for p in P),2)) for P,_ in wins])
    # the room side of each window is lit like the interior wall around it, from the baked interior model next to the
    # shell in SRC_DIR; lit from the outside wall instead, a frame looked white in one room and brown in the next
    lit_in=[]
    if os.path.exists(f"{src}/{n}int.dff"):
        before=set(bpy.data.objects)
        bpy.ops.import_scene.dff(filepath=f"{src}/{n}int.dff")
        for io in [x for x in bpy.data.objects if x not in before]:
            if io.type=='MESH' and io.data.color_attributes:
                ib=bmesh.new(); ib.from_mesh(io.data); icols=list(ib.loops.layers.color)
                lit_in+=[(l.vert.co.copy(),f.normal.copy(),[tuple(l[c]) for c in icols]) for f in ib.faces for l in f.loops]
                ib.free()
            bpy.data.objects.remove(io,do_unlink=True)
    if not lit_in: print("no baked interior for",n,"- the room side takes the outside light")
    # material
    base=me.materials[0]; gm=base.copy(); gm.name=GLASS
    gm['dff']=dict(base['dff']) if 'dff' in base.keys() else {}
    try: gm.dff.tex_name=GLASS
    except Exception as ex: print("dffprop",ex)
    img=bpy.data.images.load(f"{texdir}/{GLASS}.PNG"); img.name=GLASS+'.PNG'
    for nd in gm.node_tree.nodes:
        if nd.type=='TEX_IMAGE': nd.image=img; nd.label=GLASS
    # frame, sill and mullions in the painted wood the vanilla SF houses frame their doors with (in the shells' TXDs)
    fi=next((i for i,m in enumerate(me.materials) if getattr(m.dff,'tex_name','').lower().startswith(FRAME_TEX)),None)
    if fi is None:
        fm=base.copy(); fm.name=FRAME_TEX
        try: fm.dff.tex_name=FRAME_TEX
        except Exception as ex: print("dffprop",ex)
        fimg=bpy.data.images.load(f"{texdir}/{FRAME_TEX}.PNG"); fimg.name=FRAME_TEX+'.PNG'
        for nd in fm.node_tree.nodes:
            if nd.type=='TEX_IMAGE': nd.image=fimg; nd.label=FRAME_TEX
        me.materials.append(fm); fi=len(me.materials)-1
    kind,cname=HANGINGS[n]
    cm=base.copy(); cm.name=cname
    cm['dff']=dict(base['dff']) if 'dff' in base.keys() else {}
    try: cm.dff.tex_name=cname
    except Exception as ex: print("dffprop",ex)
    cimg=bpy.data.images.load(f"{texdir}/{cname}.PNG"); cimg.name=cname+'.PNG'
    for nd in cm.node_tree.nodes:
        if nd.type=='TEX_IMAGE': nd.image=cimg; nd.label=cname
    me.materials.append(cm); ci=len(me.materials)-1
    # the glass after the curtains: a geometry draws its materials in order, and glass drawn first hid what is behind it
    me.materials.append(gm); mi=len(me.materials)-1
    bm=bmesh.new(); bm.from_mesh(me)
    uvl=bm.loops.layers.uv.active
    for f in [f for f in bm.faces if getattr(me.materials[f.material_index].dff,'tex_name','').lower().split('.')[0] in TWO_SIDED]:
        ls=list(reversed(f.loops)); g=bm.faces.new([bm.verts.new(l.vert.co) for l in ls]); g.material_index=f.material_index
        for gl,l in zip(g.loops,ls):
            gl[uvl].uv=l[uvl].uv
            for c in bm.loops.layers.color: gl[c]=l[c]
    uv=bm.loops.layers.uv.active
    cols=list(bm.loops.layers.color)  # prelight: day, then night
    # the shell's own prelight, sampled per window from the outward faces of the wall around the opening (new loops
    # default to white, which lit the windows at full brightness by day and night)
    lit=[(l.vert.co.copy(),f.normal.copy(),[tuple(l[c]) for c in cols]) for f in bm.faces for l in f.loops]
    def wall_light(P,outn):
        h_axis=Vector((-outn.y,outn.x,0)).normalized()
        us=[p.dot(h_axis) for p in P]; zs=[p.z for p in P]; m=0.6
        for depth in (0.3,1.0):  # some shells' outer wall face stands well proud of the opening's loop
            near=[c for co,nn,c in lit if nn.dot(outn)>0.7 and abs((co-P[0]).dot(outn))<depth and min(us)-m<=co.dot(h_axis)<=max(us)+m and min(zs)-m<=co.z<=max(zs)+m]
            if near: break
        if not near: print("no wall light near a window"); return [(0.2,0.2,0.2,1)]*len(cols)
        avg=[[sum(c[k][j] for c in near)/len(near) for j in range(4)] for k in range(len(cols))]
        return [tuple(max(v,min(2*v,LIGHT_LIFT)) if j<3 else v for j,v in enumerate(a)) for a in avg]
    def room_light(P,outn):
        h_axis=Vector((-outn.y,outn.x,0)).normalized()
        us=[p.dot(h_axis) for p in P]; zs=[p.z for p in P]; m=0.6
        near=[c for co,nn,c in lit_in if nn.dot(outn)<-0.7 and abs((co-P[0]).dot(outn))<0.6 and min(us)-m<=co.dot(h_axis)<=max(us)+m and min(zs)-m<=co.z<=max(zs)+m]
        if len(near)==0 or len(near[0])<len(cols): return None
        return [tuple(sum(c[k][j] for c in near)/len(near) for j in range(4)) for k in range(len(cols))]
    light=light_in=[(1,1,1,1)]*len(cols)
    def paint(l,dim=1.0,inside=False):
        for c,v in zip(cols,light_in if inside else light): l[c]=(v[0]*dim,v[1]*dim,v[2]*dim,v[3])
    def box(bm,c,h_axis,outn,su,sv,sn):
        """Axis-aligned box centred at c, su wide along the wall, sv tall, sn deep along the outward normal."""
        basis=Matrix((h_axis*su,Vector((0,0,sv)),outn*sn)).transposed()  # columns: along the wall, up, outward
        m=Matrix.Translation(c)@basis.to_4x4()
        r=bmesh.ops.create_cube(bm,size=1.0,matrix=m,calc_uvs=False)
        fs={f for v in r['verts'] for f in v.link_faces}
        bmesh.ops.recalc_face_normals(bm,faces=list(fs))
        for f in fs:
            f.material_index=fi
            for l in f.loops:
                l[uv].uv=FRAME_UV
                paint(l,inside=(l.vert.co-wall).dot(outn)<-0.01)  # the room side of the wall plane
    def panel(bm,pts,uvs,outn):
        """A curtain or blind face, visible from both sides."""
        for flip in (False,True):
            vv=[bm.verts.new(p) for p in pts]; f=bm.faces.new(vv); f.material_index=ci
            if (f.normal.dot(outn)>0)==flip: bmesh.ops.reverse_faces(bm,faces=[f])
            for l in f.loops:
                u,v=uvs[vv.index(l.vert)]; l[uv].uv=(1-u if flip else u,v)
                paint(l,inside=True)  # in the room
    for k,(P,outn) in enumerate(wins):
        light=wall_light(P,outn); light_in=room_light(P,outn) or light; wall=P[0]
        h_axis=Vector((-outn.y,outn.x,0)).normalized()
        us=[p.dot(h_axis) for p in P]; zs=[p.z for p in P]
        u0,u1,z0,z1=min(us),max(us),min(zs),max(zs)
        w,hh=u1-u0,z1-z0
        ref=P[0]; uc=(u0+u1)/2; zc=(z0+z1)/2
        def at(u,z,n=0.0): return h_axis*(u-ref.dot(h_axis))+Vector((ref.x,ref.y,z))+outn*n
        T,D=0.07,0.07  # frame bar width, frame depth (from 0.03 outside the wall to 0.04 inside)
        # frame: four bars, each overlapping the wall edge by a little
        box(bm,at(uc,z1-T/2,-0.005),h_axis,outn,w,T,D)
        box(bm,at(uc,z0+T/2,-0.005),h_axis,outn,w,T,D)
        box(bm,at(u0+T/2,zc,-0.005),h_axis,outn,T,hh-2*T,D)
        box(bm,at(u1-T/2,zc,-0.005),h_axis,outn,T,hh-2*T,D)
        # mullions: thinner, set back with the glass
        if w>1.1: box(bm,at(uc,zc,-0.02),h_axis,outn,0.035,hh-2*T,0.04)
        if hh>1.0: box(bm,at(uc,zc,-0.02),h_axis,outn,w-2*T,0.035,0.04)
        # sill below, head trim above, standing proud of the wall
        box(bm,at(uc,z0-0.03,0.04),h_axis,outn,w+0.18,0.06,0.16)
        box(bm,at(uc,z1+0.025,0.015),h_axis,outn,w+0.12,0.05,0.07)
        # a blind across the glass, its bottom rail at the drop and the slats cut off at the head, not stretched
        if kind=='blind':
            top=z1-T; d=BLIND_DROP[k%len(BLIND_DROP)]; bot=top-d*(hh-2*T)
            panel(bm,[at(u0+T,bot,-0.06),at(u1-T,bot,-0.06),at(u1-T,top,-0.06),at(u0+T,top,-0.06)],[(0,0),(1,0),(1,d),(0,d)],outn)
        # curtains: a gathered panel at each side, hung from the head and ending above the sill
        elif hh>0.7:
            top,bot=z1-T-0.01,z0+T+0.1
            pw=0.3*(w-2*T)
            for a,b in ((u0+T,u0+T+pw),(u1-T-pw,u1-T)):
                m_=(a+b)/2
                for ua,ub,na,nb,ta,tb in ((a,m_,-0.08,-0.14,0.0,0.5),(m_,b,-0.14,-0.08,0.5,1.0)):
                    panel(bm,[at(ua,bot,na),at(ub,bot,nb),at(ub,top,nb),at(ua,top,na)],[(ta,0.0),(tb,0.0),(tb,1.0),(ta,1.0)],outn)
        # glass, recessed behind the frame and visible from both sides
        gu0,gu1,gz0,gz1=u0+T,u1-T,z0+T,z1-T
        for flip in (False,True):
            vv=[bm.verts.new(at(gu,gz,-0.03)) for gu,gz in ((gu0,gz0),(gu1,gz0),(gu1,gz1),(gu0,gz1))]
            f=bm.faces.new(vv); f.material_index=mi
            if (f.normal.dot(outn)>0)==flip: bmesh.ops.reverse_faces(bm,faces=[f])
            for l in f.loops:
                i=vv.index(l.vert); u=(0.12,0.88,0.88,0.12)[i]; v=(0.12,0.12,0.88,0.88)[i]
                l[uv].uv=(1-u if flip else u,v)
                paint(l,inside=flip)
    bm.to_mesh(me); bm.free()
    os.makedirs(dst,exist_ok=True)
    bpy.ops.object.select_all(action='SELECT')
    r=bpy.ops.export_dff.scene(filepath=f"{dst}/{n}.dff",export_coll=False,only_selected=False,export_version='0x36003')
    print("EXPORT",n,r)
write_glazed(glazed)
