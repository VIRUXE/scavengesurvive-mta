"""Writes discordchat's item uname -> render file and wiki page maps for the Discord #spawns embeds.

    python -m tools.spawn_images

Reads docs/images/items/all/index.json (written by tools.render_item_models --all --set all) and the wiki's item pages
(the same uname -> page plan as tools.wiki_tables) into resources/[scavengesurvive]/discordchat/shared/spawn_images.lua.
nginx serves the renders at https://ss.flaviopereira.dev/reborn/images/items/.
"""
from __future__ import annotations

import json
import time
from pathlib import Path

from tools.wiki_tables import ITEM_TYPES, lua_rows, plan_pages, real, topic_pages

ROOT = Path(__file__).resolve().parents[1]
IMAGES = ROOT / "docs" / "images"
WIKI = ROOT / "wiki"
OUT = ROOT / "resources" / "[scavengesurvive]" / "discordchat" / "shared" / "spawn_images.lua"


def lua_table(index: dict[str, str]) -> str:
    return "\n".join(f'        {k} = "{v}",' for k, v in sorted(index.items()))


def wiki_pages() -> dict[str, str]:
    pages = plan_pages(real(lua_rows(ITEM_TYPES, "M.byUname.")), topic_pages(WIKI))
    return {u: p["link"] for u, p in pages.items() if (WIKI / f"{p['link']}.md").is_file()}


def main() -> int:
    items = json.loads((IMAGES / "items" / "all" / "index.json").read_text(encoding="utf8"))
    wiki = wiki_pages()
    OUT.write_text(
        "-- Generated by tools/spawn_images.py from docs/images/items/all/index.json and wiki/. Do not edit.\n"
        "return {\n"
        f'    version = "{int(time.time())}", -- appended as ?v= so Discord refetches re-rendered images\n'
        f"    items = {{\n{lua_table(items)}\n    }},\n"
        f"    wiki = {{\n{lua_table(wiki)}\n    }},\n"
        "}\n",
        encoding="utf8",
    )
    print(f"spawn_images: {len(items)} renders, {len(wiki)} wiki pages -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
