"""Writes house_shell/trailers.lua: which DFF/COL replaces each vanilla trailer (models 3167-3175), its door leaf and
where that leaf hangs in the model's frame (from tools/trailer_shells/build/<model>.json, written by each model's
Blender script), and every upright vanilla placement of a trailer in the world (the text and binary IPLs), less the
ones upstream's maps remove (RemoveBuildingForPlayer rows in maps/data/*.lua), so the client hangs a door in each.
Trailers the maps place themselves are found at run time (house_shell/client/main.lua, on mapsBuilt).

    python -m tools.trailer_shells.doors [--gta DIR]
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

from tools.extract_samp_models import detect_gta
from tools.fort_survey import native_instances
from tools.trailer_shells.prep import BUILD, ROOT, TRAILERS

RES = ROOT / "resources" / "[scavengesurvive]"
OUT = RES / "house_shell" / "trailers.lua"
META = RES / "house_shell" / "meta.xml"
MARK = "    <!-- trailers: generated by tools/trailer_shells/doors.py -->"
MAPS = RES / "maps" / "data"
REMOVAL = re.compile(r"\{\s*(\d+),\s*(-?[\d.]+),\s*(-?[\d.]+),\s*(-?[\d.]+),\s*([\d.]+)\s*\}")
UPRIGHT = 0.999  # the placement's up axis against world up: tipped-over trailers get no door


def removals() -> list[tuple[int, float, float, float, float]]:
    """(model, x, y, z, radius) of every RemoveBuildingForPlayer row of the maps."""
    rows = []
    for path in MAPS.glob("*.lua"):
        text = path.read_text(encoding="utf-8")
        start = text.find("removals = {")
        if start < 0:
            continue
        end = text.find("\n    },", start)
        rows += [(int(m[1]), float(m[2]), float(m[3]), float(m[4]), float(m[5])) for m in REMOVAL.finditer(text[start:end])]
    return rows


def removed(model: int, pos, rows) -> bool:
    return any(m in (model, -1) and math.dist(pos, (x, y, z)) <= r for m, x, y, z, r in rows)


def placements(gta: Path) -> list[tuple[int, float, float, float, float]]:
    """(model, x, y, z, yaw degrees) of each upright vanilla trailer the maps keep."""
    rows, out = removals(), []
    for model, pos, rot in native_instances(gta):
        if model not in TRAILERS or removed(model, pos, rows):
            continue
        if rot[2][2] < UPRIGHT:
            continue
        out.append((model, pos[0], pos[1], pos[2], math.degrees(math.atan2(rot[1][0], rot[0][0])) % 360))
    return sorted(out)


def render(models: dict[int, dict], placed) -> str:
    lines = [
        "-- Generated by tools/trailer_shells/doors.py; do not edit. The enterable trailers: per vanilla model, the",
        "-- DFF and COL replacing it (files/, TXD files/trailers.txd) and its door leaf, hinged at x, y, z, rz in the",
        "-- trailer's frame; then each upright vanilla placement the maps keep, as { model, x, y, z, rz }.",
        "return {",
        "    models = {",
    ]
    for model, m in sorted(models.items()):
        d = m["door"]
        x, y, z = d["hinge"]
        door = f'{{ dff = "{m["model"]}_door", x = {x:.3f}, y = {y:.3f}, z = {z:.3f}, rz = {d["rz"]:.1f} }}'
        lines += [f"        [{model}] = {{", f'            dff = "{m["model"]}",', f"            door = {door},", "        },"]
    lines += ["    },", "    placements = {"]
    lines += [f"        {{ {m}, {x:.3f}, {y:.3f}, {z:.3f}, {rz:.1f} }}," for m, x, y, z, rz in placed]
    lines += ["    },", "}", ""]
    return "\n".join(lines)


def write_meta(models: dict[int, dict]) -> None:
    """Lists every trailer's DFF/COL and its door's in house_shell/meta.xml, after the marker line."""
    text = META.read_text(encoding="utf-8")
    names = [n for m in sorted(models) for n in (models[m]["model"], models[m]["model"] + "_door")]
    files = [f'    <file src="files/{n}.{ext}"/>' for n in names for ext in ("col", "dff")]
    head = text.split(MARK)[0]
    body = "\n".join([head + MARK, *files, "</meta>", ""])
    META.write_text(body, encoding="utf-8", newline="\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gta", type=Path, help="GTA:SA folder (default: from the registry)")
    ap.add_argument("--only", nargs="+", metavar="NAME", help="ship only these trailers (default: every one built)")
    args = ap.parse_args(argv)
    gta = args.gta or detect_gta()
    if not gta:
        print("trailer_shells.doors: no GTA:SA folder (pass --gta)", file=sys.stderr)
        return 2
    models = {}
    for model, name in TRAILERS.items():
        path = BUILD / f"{name}.json"
        if path.is_file() and (not args.only or name in args.only):
            meta = json.loads(path.read_text())
            if meta.get("door"):
                models[model] = meta
    placed = [p for p in placements(gta) if p[0] in models]
    OUT.write_text(render(models, placed), encoding="utf-8", newline="\n")
    write_meta(models)
    print(f"trailer_shells.doors: {len(models)} models, {len(placed)} placements -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
