"""Load the schema and seeds into a MariaDB database, or dump its schema.

Usage: python -m tools.sqltool --db NAME [--host H --port P --user U --password PW] [--reset] apply|dump
apply: sql/schema.sql (tables: CREATE TABLE IF NOT EXISTS, so existing tables and their data are kept; procedures,
functions, triggers and events: CREATE OR REPLACE), then the seeds (idempotent); it can run again without --reset.
dump: rewrites sql/schema.sql from the database: every table, routine, trigger and event.
There are no migration or procedure files: change the live database directly (tables, procedures, triggers, events
alike), then `dump` to keep sql/schema.sql in step. Statements end with `;` at the end of a line; the routines,
triggers and events sit in a `DELIMITER //` block, as the mariadb client reads them (`mariadb DB < schema.sql`).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pymysql

ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / "sql"
SCHEMA = SQL / "schema.sql"
DELIMITER = "//"
SCHEMA_HEADER = (
    "-- Current schema of the scavengesurvive database: every table, procedure, function, trigger and event,\n"
    "-- generated by `python -m tools.sqltool --db scavengesurvive dump`. There are no migrations or procedure\n"
    "-- files: change the live database directly, then dump again. `apply` creates only the tables that are\n"
    "-- missing and replaces every routine, trigger and event.\n\n"
)
DEFINER = re.compile(r"^CREATE\s+DEFINER=\S+\s+")


def statements(text: str) -> list[str]:
    """Split on the current delimiter at the end of a line, honouring mysql-client `DELIMITER x` lines.
    Comment lines before a statement are dropped; inside one (a routine body) they are kept verbatim."""
    out, buf, delim = [], [], ";"
    for line in text.splitlines():
        stripped = line.strip()
        if not buf and (not stripped or stripped.startswith("--")):
            continue
        if not buf and stripped.upper().startswith("DELIMITER "):
            delim = stripped.split(None, 1)[1]
            continue
        if stripped.endswith(delim):
            buf.append(line.rstrip()[: -len(delim)])
            out.append("\n".join(buf).strip())
            buf = []
        else:
            buf.append(line)
    if "\n".join(buf).strip():
        out.append("\n".join(buf).strip())
    return out


def or_replace(ddl: str) -> str:
    return DEFINER.sub("CREATE ", ddl, 1).replace("CREATE ", "CREATE OR REPLACE ", 1)


def connect(args, database):
    return pymysql.connect(host=args.host, port=args.port, user=args.user, password=args.password,
                           database=database, autocommit=True, charset="utf8mb4")


def apply(args) -> None:
    if args.reset:
        with connect(args, None) as c, c.cursor() as cur:
            cur.execute(f"DROP DATABASE IF EXISTS `{args.db}`")
    with connect(args, None) as c, c.cursor() as cur:
        cur.execute(f"CREATE DATABASE IF NOT EXISTS `{args.db}` CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci")
    with connect(args, args.db) as c, c.cursor() as cur:
        for st in statements(SCHEMA.read_text(encoding="utf-8")):
            cur.execute(st)
        for f in sorted((SQL / "seed").glob("*.sql")):
            for st in statements(f.read_text(encoding="utf-8")):
                cur.execute(st)
    print(f"applied to {args.db}")


def render_schema(cur) -> str:
    cur.execute("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'")
    tables = sorted(r[0] for r in cur.fetchall())
    parts = [SCHEMA_HEADER, "SET FOREIGN_KEY_CHECKS = 0;\n"]
    for t in tables:
        cur.execute(f"SHOW CREATE TABLE `{t}`")
        ddl = cur.fetchone()[1]
        ddl = re.sub(r" AUTO_INCREMENT=\d+", "", ddl)
        ddl = ddl.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
        parts.append(f"\n{ddl};\n")
    parts.append("\nSET FOREIGN_KEY_CHECKS = 1;\n")
    code = []
    for kind in ("PROCEDURE", "FUNCTION"):
        cur.execute("SELECT ROUTINE_NAME FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA = DATABASE() "
                    "AND ROUTINE_TYPE = %s ORDER BY ROUTINE_NAME", (kind,))
        for (name,) in cur.fetchall():
            cur.execute(f"SHOW CREATE {kind} `{name}`")
            code.append(or_replace(cur.fetchone()[2]))
    cur.execute("SELECT TRIGGER_NAME FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = DATABASE() "
                "ORDER BY TRIGGER_NAME")
    for (name,) in cur.fetchall():
        cur.execute(f"SHOW CREATE TRIGGER `{name}`")
        code.append(or_replace(cur.fetchone()[2]))
    cur.execute("SELECT EVENT_NAME FROM information_schema.EVENTS WHERE EVENT_SCHEMA = DATABASE() ORDER BY EVENT_NAME")
    for (name,) in cur.fetchall():
        cur.execute(f"SHOW CREATE EVENT `{name}`")
        code.append(or_replace(cur.fetchone()[3]))
    if code:
        parts.append(f"\nDELIMITER {DELIMITER}\n")
        parts.extend(f"\n{c.strip()}{DELIMITER}\n" for c in code)
        parts.append("\nDELIMITER ;\n")
    return "".join(parts)


def dump(args) -> None:
    with connect(args, args.db) as c, c.cursor() as cur:
        text = render_schema(cur)
    SCHEMA.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {SCHEMA.relative_to(ROOT)} from {args.db}")


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--db", required=True)
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=3306)
    p.add_argument("--user", default="root")
    p.add_argument("--password", default="")
    p.add_argument("--reset", action="store_true")
    p.add_argument("command", choices=["apply", "dump"])
    args = p.parse_args(argv)
    apply(args) if args.command == "apply" else dump(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
