"""Load the schema, procedures, events and seeds into a MariaDB database, or dump its schema.

Usage: python -m tools.sqltool --db NAME [--host H --port P --user U --password PW] [--reset] apply|dump
apply: sql/schema.sql (CREATE TABLE IF NOT EXISTS, so existing tables and their data are kept), then
procedures and events (CREATE OR REPLACE) and seeds (idempotent); it can run again without --reset.
dump: rewrites sql/schema.sql from the database's tables (SHOW CREATE TABLE).
There are no migration files: change the live database directly, then `dump` to keep sql/schema.sql in step.
schema.sql and seeds are split on a semicolon that ends a line; procedure and event files are sent whole
(one CREATE OR REPLACE statement per file, no DELIMITER).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pymysql

ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / "sql"
SCHEMA = SQL / "schema.sql"
SPLIT = re.compile(r";[ \t]*\r?\n")
SCHEMA_HEADER = (
    "-- Current schema of the scavengesurvive database: every table, generated by\n"
    "-- `python -m tools.sqltool --db scavengesurvive dump`. There are no migrations: change the live database\n"
    "-- directly, then dump again. `apply` creates only the tables that are missing.\n\n"
)


def statements(text: str) -> list[str]:
    out = []
    for chunk in SPLIT.split(text):
        lines = [ln for ln in chunk.splitlines() if not ln.strip().startswith("--")]
        st = "\n".join(lines).strip()
        if st:
            out.append(st)
    return out


def connect(args, database):
    return pymysql.connect(host=args.host, port=args.port, user=args.user, password=args.password,
                           database=database, autocommit=True, charset="utf8mb4")


def apply(args) -> None:
    if args.reset:
        with connect(args, None) as c, c.cursor() as cur:
            cur.execute(f"DROP DATABASE IF EXISTS `{args.db}`")
    with connect(args, None) as c, c.cursor() as cur:
        cur.execute(f"CREATE DATABASE IF NOT EXISTS `{args.db}` CHARACTER SET utf8mb4 COLLATE utf8mb4_uca1400_ai_ci")
    with connect(args, args.db) as c, c.cursor() as cur:
        for st in statements(SCHEMA.read_text(encoding="utf-8")):
            cur.execute(st)
        for sub in ("procedures", "events"):
            for f in sorted((SQL / sub).glob("*.sql")):
                cur.execute(f.read_text(encoding="utf-8").strip().rstrip(";"))
        for f in sorted((SQL / "seed").glob("*.sql")):
            for st in statements(f.read_text(encoding="utf-8")):
                cur.execute(st)
    print(f"applied to {args.db}")


def render_schema(cur) -> str:
    cur.execute("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'")
    tables = sorted(r[0] for r in cur.fetchall())
    parts = [SCHEMA_HEADER, "SET FOREIGN_KEY_CHECKS = 0;\n"]
    for t in tables:
        cur.execute(f"SHOW CREATE TABLE `{t}`")
        ddl = cur.fetchone()[1]
        ddl = re.sub(r" AUTO_INCREMENT=\d+", "", ddl)
        ddl = ddl.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
        parts.append(f"\n{ddl};\n")
    parts.append("\nSET FOREIGN_KEY_CHECKS = 1;\n")
    return "".join(parts)


def dump(args) -> None:
    with connect(args, args.db) as c, c.cursor() as cur:
        text = render_schema(cur)
    SCHEMA.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {SCHEMA.relative_to(ROOT)} from {args.db}")


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--db", required=True)
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=3306)
    p.add_argument("--user", default="root")
    p.add_argument("--password", default="")
    p.add_argument("--reset", action="store_true")
    p.add_argument("command", choices=["apply", "dump"])
    args = p.parse_args(argv)
    apply(args) if args.command == "apply" else dump(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
