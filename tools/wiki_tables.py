"""Generates the Markdown data tables and the item pages of the GitHub wiki from the port's own data.

    python -m tools.wiki_tables --wiki ../scavengesurvive-mta.wiki [--images images/items] [--clean]

In every wiki page the text between `<!-- table:<name> -->` and `<!-- /table:<name> -->` is replaced by the table of
that name, so the pages can be rewritten by hand around them and the numbers follow the data (data/generated/
item_types.lua, vehicle_types.lua, loot_tables.lua, lang_en.lua, the sql/seed spawn files, craft.lua, machines.lua,
apparel.lua, liquids.lua, explosives.lua, world/data/boxes.lua and features.lua).

Every item type also gets a page of its own in the wiki root, <Display-Name>.md (`<Name>-<uname>.md` when several
items share a name, the uname split into words when the name is empty), marked on its second line as generated:
only files carrying that mark are ever overwritten, and `--clean` deletes marked pages whose item is gone. An item
whose name is already a hand-written page (Workbench, Radio) gets no page of its own; the tables link to that page
instead. Nothing else in the wiki is written.
"""
