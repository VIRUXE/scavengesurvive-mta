def world_spots() -> tuple[Counter, Counter]:
    """Box item spots per uname (world/data/boxes.lua) and built fixtures per (uname, zone) (features.lua)."""
    boxes = Counter(re.findall(r'^\s+\{ "(\w+)", ', BOXES.read_text(encoding="utf8"), re.M))
    fixtures = Counter(re.findall(r'\{ "(\w+)", [-\d.]+, [-\d.]+, [-\d.]+, [-\d.]+, "(\w+)" \}', FIXTURES.read_text(encoding="utf8")))
    return boxes, fixtures


def is_generated(path: Path) -> bool:
    with path.open(encoding="utf8") as f:
        f.readline()
        return f.readline().rstrip("\r\n") == GENERATED


def lang_of(path: Path) -> str:
    """The language of a wiki file: <Page>.md is English, <Page>.<code>.md that language."""
    parts = path.name.split(".")
    return parts[1] if len(parts) == 3 else "en"


def topic_pages(wiki: Path) -> dict:
    """stem -> text of every hand-written English page (generated pages, translations and _Sidebar/_Footer left out)."""
    return {p.stem: p.read_text(encoding="utf8") for p in sorted(wiki.glob("*.md")) if not p.name.startswith("_") and lang_of(p) == "en" and not is_generated(p)}


def plan_pages(items: dict, topics: dict) -> dict:
    """uname -> { link, file, dup }: the page the item's name links to and the file to generate (None: a topic page)."""
    by_stem = defaultdict(list)
    pages = {}
    for u, it in items.items():
        if it.get("partName"):  # vehicle salvage parts: one topic page lists them all
            pages[u] = {"link": SALVAGE_PAGE, "file": None, "dup": False}
            continue
        by_stem[page_stem(it["name"])].append(u)
    for stem, unames in by_stem.items():
        for u in unames:
            if stem in topics:
                pages[u] = {"link": stem, "file": None, "dup": len(unames) > 1}
            elif len(unames) == 1:
                pages[u] = {"link": stem, "file": stem, "dup": False}
            else:
                pages[u] = {"link": stem + "-" + u, "file": stem + "-" + u, "dup": True}
    return pages


def load(wiki: Path, img: str) -> SimpleNamespace:
    """Everything in English; for_lang() makes the copy another language writes from."""
    src = ITEM_TYPES.read_text(encoding="utf8")
    d = SimpleNamespace(wiki=wiki, img=img, lang="en", names={})
    d.items = real(lua_rows(ITEM_TYPES, "M.byUname."))
    d.cal_names = parse_table(tokens(re.search(r"M\.calibreNames = \{(.*)", src).group(1)))
    d.calibres = parse_table(tokens(re.search(r"M\.calibres = \{(.*)", src).group(1)))
    d.pictures = picture_index(ITEM_RENDERS)
    d.vehicle_pictures = picture_index(VEHICLE_RENDERS)
    d.vehicles = real(lua_rows(VEHICLE_TYPES, "M.byUname."))
    d.trunks = defaultdict(set)
    for v in d.vehicles.values():
        if v.get("lootTable"):
            d.trunks[v["lootTable"]].add(v["name"])
    d.tooltips = tooltips("en")
    d.loot = lua_rows(LOOT_TABLES, "M.")
    d.houses = spawn_points(HOUSE_LOOT)
    d.spawns = spawn_points(LOOT_SPAWNS) + d.houses
    d.drops, d.cache_table = drop_tables()
    d.drop_points, d.cache_points = drop_points()
    d.recipes = recipes()
    d.scrap = scrap_values()
    d.machines = machine_results()
    d.slots = apparel_slots()
    d.liquids = liquid_names()
    d.presets = explosive_presets()
    d.boxes, d.fixtures = world_spots()
    d.topics = topic_pages(wiki)
    d.pages = plan_pages(d.items, d.topics)
    d.see_also = {}
    d.base = d
    return d


def for_lang(en: SimpleNamespace, lang: str) -> SimpleNamespace:
    """A copy of the English data whose item names are in `lang`; page files and links stay those of the English."""
    if lang == "en":
        return en
    d = SimpleNamespace(**vars(en))
    d.lang = lang
    d.base = en
    d.names = game_strings(lang)
    d.items = {u: {**it, "name": local_name(d.names, it)} for u, it in en.items.items()}
    d.tooltips = tooltips(lang)
    return d


def local_name(names: dict, it: dict) -> str:
    """An item's name as the game shows it in a language: a salvage part's from its template (lib lang.lua)."""
    if it.get("partName"):
        try:
            return names.get(it["partName"], it["partName"]) % it["partVehicle"]
        except TypeError:
            return it["name"]
    return names.get(it["name"], it["name"])


def nm(d, english: str) -> str:
    """A name the game translates (calibre, liquid, ammo type, supply drop) in the language being written."""
    return d.names.get(english, english)


def topic_title(d, stem: str) -> str:
    """The title of a hand-written page in the language being written (its translation's, when there is one)."""
    page = d.wiki / f"{stem}.{d.lang}.md"
    text = page.read_text(encoding="utf8") if d.lang != "en" and page.exists() else d.topics[stem]
    m = re.match(r"# (.+)", text)
    return m.group(1).strip() if m else stem.replace("-", " ")


