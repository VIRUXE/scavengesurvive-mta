def table_sizes(d):
    by = defaultdict(list)
    for u, it in d.items.items():
        by[it["size"]].append(u)
    rows = []
    for size, unames in sorted(by.items()):
        unames.sort(key=lambda u: (d.items[u]["name"], u))
        names, examples = set(), []
        for u in unames:
            if d.items[u]["name"] not in names and len(examples) < 5 and not d.items[u].get("partName"):
                names.add(d.items[u]["name"])
                examples.append(link(d, u))
        rows.append([size, len(unames), ", ".join(examples)])
    intro = t("Five items of each size; the [Item Catalogue](Item-Catalogue) lists every item with its size.") + "\n\n"
    return intro + md(["Size", "Items", "Examples"], rows, "rrl")


