def picture_index(wiki: Path, folder: str) -> dict:
    idx = wiki / folder / "index.json"
    return json.loads(idx.read_text(encoding="utf8")) if idx.exists() else {}


def tooltips() -> dict:
    """lang_en.lua's item tooltips, keyed as the game keys them: the first nine characters of the uname."""
    return {m.group(1): m.group(2) for m in re.finditer(r'^    (\w{1,9})_T = "((?:[^"\\]|\\.)*)"', LANG.read_text(encoding="utf8"), re.M)}


SPAWN_ROW = re.compile(r"^\([-\d.]+,[-\d.]+,[-\d.]+,'(\w+)',[\d.]+,-?\d+,\d+,\d+,'(\w+)',POINT", re.M)


def spawn_points(path: Path) -> Counter:
    """(table_name, zone) -> rows of a loot_spawns seed file."""
    return Counter(SPAWN_ROW.findall(path.read_text(encoding="utf8")))


def drop_points() -> tuple[Counter, Counter]:
    """Supply drop points and weapon cache points per zone (0005_drop_points.sql)."""
    src = DROP_POINTS.read_text(encoding="utf8")
    cut = src.index("INSERT INTO weapon_cache_points")
    rows = re.compile(r"^\(.*'(\w+)'\)[,;]$", re.M)
    return Counter(rows.findall(src[:cut])), Counter(rows.findall(src[cut:]))


def drop_tables() -> tuple[dict, str]:
    """airdrop table -> the supply drop's name, and the table the weapon caches are filled from (loot/drops.lua)."""
    src = DROPS.read_text(encoding="utf8")
    names = {m.group(2): m.group(1) for m in re.finditer(r'name = "([^"]+)", table = "(\w+)"', src)}
    return names, re.search(r'CACHE_TABLE = "(\w+)"', src).group(1)


def recipes() -> list[dict]:
    """craft.lua's COMBINE, GROUND and WORKBENCH sets as { result, kind, tool, consumed, kept, build_ms, remove_ms }."""
    src = re.sub(r"--[^\n]*", "", CRAFT.read_text(encoding="utf8"))
    sets = {m.group(1): parse_table(tokens(m.group(2))) for m in re.finditer(r"^local ([A-Z]+) = \{([^\n]*\})$", src, re.M)}

    def resolve(v):
        return sets[v] if isinstance(v, str) and v in sets else (v or {})

    out = []
    for row in parse_table(tokens(lua_block(src, "local COMBINE = {"))):
        arr, named = positional(row)
        kept = resolve(arr[2]) if len(arr) > 2 else {}
        out.append({"result": arr[0], "kind": "combine", "tool": None, "consumed": resolve(arr[1]), "kept": kept, "build_ms": None, "remove_ms": None})
    for row in parse_table(tokens(lua_block(src, "local GROUND = {"))):
        arr, named = positional(row)
        kept = resolve(arr[4]) if len(arr) > 4 else {}
        out.append({"result": arr[0], "kind": "ground", "tool": arr[1], "consumed": resolve(arr[3]), "kept": kept, "build_ms": arr[2], "remove_ms": named.get("remove")})
    for row in parse_table(tokens(lua_block(src, "local WORKBENCH = {"))):
        arr, named = positional(row)
        out.append({"result": arr[0], "kind": "workbench", "tool": arr[1], "consumed": resolve(arr[2]), "kept": {}, "build_ms": None, "remove_ms": None})
    return out


def scrap_values() -> dict:
    blk = lua_block(MACHINES.read_text(encoding="utf8"), "M.SCRAP = {")
    return {u: int(v) for u, v in re.findall(r"(\w+) = (\d+),", blk)}


def machine_results() -> dict:
    """machines.lua M.RESULTS: machine kind -> the uname it turns its load into."""
    return parse_table(tokens(re.search(r"M\.RESULTS = \{(.*)", MACHINES.read_text(encoding="utf8")).group(1)))


def apparel_slots() -> dict:
    """uname -> wear slot, from apparel.lua's HATS, CUT_HATS, MASKS, ARMOUR, BAGS and HOLSTERS tables."""
    src = APPAREL.read_text(encoding="utf8")
    out = {}
    for table, slot in (("HATS", "hat"), ("CUT_HATS", "hat"), ("MASKS", "mask"), ("ARMOUR", "armour"), ("BAGS", "bag")):
        for u in re.findall(r"^    (\w+) = true,", lua_block(src, "local " + table + " = {"), re.M):
            out[u] = SLOTS[slot]
    for u, bone in re.findall(r"^    (\w+) = \{ bone = (\d)", lua_block(src, "local HOLSTERS = {"), re.M):
        out[u] = "Holster, on the back" if bone == "1" else "Holster, on the thigh"
    return out


def liquid_names() -> dict:
    return dict(re.findall(r'^    (\w+) = \{ name = "([^"]+)"', LIQUIDS.read_text(encoding="utf8"), re.M))


def explosive_presets():
    src = EXPLOSIVES.read_text(encoding="utf8")
    return {m.group(1): float(m.group(2)) for m in re.finditer(r"^    (\w+) = \{ anim = \d+, size = ([\d.]+)", src, re.M)}


def world_spots() -> tuple[Counter, Counter]:
    """Box item spots per uname (world/data/boxes.lua) and built fixtures per (uname, zone) (features.lua)."""
    boxes = Counter(re.findall(r'^\s+\{ "(\w+)", ', BOXES.read_text(encoding="utf8"), re.M))
    fixtures = Counter(re.findall(r'\{ "(\w+)", [-\d.]+, [-\d.]+, [-\d.]+, [-\d.]+, "(\w+)" \}', FIXTURES.read_text(encoding="utf8")))
    return boxes, fixtures


def is_generated(path: Path) -> bool:
    with path.open(encoding="utf8") as f:
        f.readline()
        return f.readline().rstrip("\r\n") == GENERATED


def topic_pages(wiki: Path) -> dict:
    """stem -> text of every hand-written page (generated pages and the _Sidebar/_Footer files left out)."""
    return {p.stem: p.read_text(encoding="utf8") for p in sorted(wiki.glob("*.md")) if not p.name.startswith("_") and not is_generated(p)}


def plan_pages(items: dict, topics: dict) -> dict:
    """uname -> { link, file, dup }: the page the item's name links to and the file to generate (None: a topic page)."""
    by_stem = defaultdict(list)
    for u, t in items.items():
        by_stem[page_stem(t["name"])].append(u)
    pages = {}
    for stem, unames in by_stem.items():
        for u in unames:
            if stem in topics:
                pages[u] = {"link": stem, "file": None, "dup": len(unames) > 1}
            elif len(unames) == 1:
                pages[u] = {"link": stem, "file": stem, "dup": False}
            else:
                pages[u] = {"link": stem + "-" + u, "file": stem + "-" + u, "dup": True}
    return pages


def load(wiki: Path, img: str) -> SimpleNamespace:
    src = ITEM_TYPES.read_text(encoding="utf8")
    d = SimpleNamespace(wiki=wiki, img=img)
    d.items = real(lua_rows(ITEM_TYPES, "M.byUname."))
    d.cal_names = parse_table(tokens(re.search(r"M\.calibreNames = \{(.*)", src).group(1)))
    d.calibres = parse_table(tokens(re.search(r"M\.calibres = \{(.*)", src).group(1)))
    d.pictures = picture_index(wiki, img)
    d.vehicle_pictures = picture_index(wiki, "images/vehicles")
    d.vehicles = real(lua_rows(VEHICLE_TYPES, "M.byUname."))
    d.trunks = defaultdict(set)
    for v in d.vehicles.values():
        if v.get("lootTable"):
            d.trunks[v["lootTable"]].add(v["name"])
    d.tooltips = tooltips()
    d.loot = lua_rows(LOOT_TABLES, "M.")
    d.houses = spawn_points(HOUSE_LOOT)
    d.spawns = spawn_points(LOOT_SPAWNS) + d.houses
    d.drops, d.cache_table = drop_tables()
    d.drop_points, d.cache_points = drop_points()
    d.recipes = recipes()
    d.scrap = scrap_values()
    d.machines = machine_results()
    d.slots = apparel_slots()
    d.liquids = liquid_names()
    d.presets = explosive_presets()
    d.boxes, d.fixtures = world_spots()
    d.topics = topic_pages(wiki)
    d.pages = plan_pages(d.items, d.topics)
    d.see_also = {}
    return d


