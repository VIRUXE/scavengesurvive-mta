def table_salvage(d):
    """One row per set of salvage parts: the vehicles it fits, its parts, its loot weight per part."""
    src = BODYPARTS.read_text(encoding="utf8")
    fits = defaultdict(set)
    for model, prefix in re.findall(r'\[(\d+)\] = \{\s*prefix = "(\w+)"', src):
        for v in d.vehicles.values():
            if int(v["model"]) == int(model):
                fits[prefix].add(v["name"])
    sets = defaultdict(list)
    for u, it in d.base.items.items():
        if it.get("partName"):
            sets[it["partVehicle"]].append(u)
    weights = {e["uname"]: e["weight"] for e in d.loot["world_industrial"]["entries"]}
    rows = []
    for vehicle, unames in sorted(sets.items()):
        prefix = unames[0][: -len("Good")] if unames[0].endswith("Good") else unames[0][: -len("Bad")]
        prefix = next(p for p in fits if unames[0].startswith(p)) if any(unames[0].startswith(p) for p in fits) else prefix
        labels = []
        for u in unames:
            label = re.sub(r"^%s | \((Good|Bad)\)$", "", d.base.items[u]["partName"])
            label = d.names.get(label, label)
            if label not in labels:
                labels.append(label)
        good = [weights.get(u, 0) for u in unames if u.endswith("Good")]
        bad = [weights.get(u, 0) for u in unames if u.endswith("Bad")]
        rows.append([vehicle, ", ".join(sorted(fits.get(prefix, {vehicle}))), ", ".join(labels), num(good[0]) + " / " + num(bad[0])])
    return md([t("Part set"), t("Fits"), t("Parts"), t("Loot weight (Good / Bad)")], rows, "lllr")


