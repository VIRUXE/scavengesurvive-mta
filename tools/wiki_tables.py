def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wiki", default=str(ROOT / "wiki"), help="the wiki checkout to write (default: the wiki/ folder of this repo, mirrored to GitHub by the pages workflow)")
    ap.add_argument("--images", default="images/items")
    ap.add_argument("--clean", action="store_true", help="delete generated item pages whose item no longer exists")
    a = ap.parse_args()
    wiki = Path(a.wiki)
    d = load(wiki, a.images)
    made = {name: fn(d) for name, fn in TABLES.items()}
    for page in sorted(wiki.glob("*.md")):
        if is_generated(page):
            continue
        text = page.read_text(encoding="utf8")
        new = text
        for name, body in made.items():
            pat = re.compile(r"(<!-- table:" + name + r" -->\n).*?(<!-- /table:" + name + r" -->)", re.S)
            new = pat.sub(lambda m: m.group(1) + body + m.group(2), new)
        if new != text:
            page.write_text(new, encoding="utf8", newline="\n")
            print("updated", page.name)
    written, files = 0, set()
    for u in sorted(d.items):
        if not d.pages[u]["file"]:
            continue
        path = wiki / (d.pages[u]["file"] + ".md")
        files.add(path.name)
        if path.exists() and not is_generated(path):
            print("kept", path.name, "(hand-written, not overwritten)")
            continue
        text = item_page(d, u)
        if not path.exists() or path.read_text(encoding="utf8") != text:
            path.write_text(text, encoding="utf8", newline="\n")
            written += 1
    for page in sorted(wiki.glob("*.md")):
        if page.name not in files and is_generated(page):
            if a.clean:
                page.unlink()
                print("deleted", page.name)
            else:
                print("stale", page.name, "(--clean deletes it)")
    looted = {e["uname"] for tbl in d.loot.values() for e in tbl["entries"]}
    unlooted = sorted(u for u in d.items if u not in looted)
    topics = sorted(u for u in d.items if not d.pages[u]["file"])
    dups = sorted(d.pages[u]["file"] + ".md" for u in d.items if d.pages[u]["dup"] and d.pages[u]["file"])
    prefixes = Counter(u[:9] for u in d.items)
    shared = sorted(u for u in d.items if prefixes[u[:9]] > 1)
    print("%d item types, %d tables, %d item pages (%d written now), %d names link to topic pages: %s" % (len(d.items), len(made), len(files), written, len(topics), ", ".join(topics)))
    print("%d items in no loot table: %s" % (len(unlooted), ", ".join(unlooted)))
    print("%d pages of items sharing a name: %s" % (len(dups), ", ".join(dups)))
    if shared:
        print("unames sharing a tooltip key (first nine characters):", ", ".join(shared))


if __name__ == "__main__":
    main()
