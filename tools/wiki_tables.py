def link(d, u: str, label: str | None = None) -> str:
    return "[" + (label or d.items[u]["name"]) + "](" + d.pages[u]["link"] + ")"


def tagged(d, u: str) -> str:
    """The display name, with the uname when other items share it."""
    name = d.items[u]["name"]
    return name + " (`" + u + "`)" if d.pages[u]["dup"] else name


def pct(share: float) -> str:
    text = "<0.1" if share < 0.05 else "%.1f" % share
    return (text.replace(".", ",") if LANG == "pt" else text) + " %"


def zone_text(counter: Counter) -> str:
    return ", ".join(t("%s in %s") % (thousands(n), ZONES.get(z, z)) for z, n in sorted(counter.items(), key=lambda kv: (-kv[1], kv[0])))


def facts(d, u: str, it: dict) -> list[list]:
    cd = it.get("categoryData") or {}
    cat = it["category"]
    label = t(CATEGORIES[cat])
    if cat == "weapon":
        label += t(" (firearm)") if cd.get("calibre") else t(" (melee)")
    elif it.get("explosive"):
        label = t("Explosive")
    elif it.get("defence"):
        label = t("Defence")
    rows = [[t("Size"), it["size"]], [t("Category"), label], [t("Hit points"), it["maxHitpoints"]]]
    if it.get("useCarryAnim"):
        rows.append([t("Carried in both hands"), t("yes")])
    if it.get("longPickup"):
        rows.append([t("Long pick-up"), t("yes")])
    if u in d.slots:
        rows.append([t("Wear slot"), t(d.slots[u])])
    if cat == "weapon":
        if cd.get("liquid"):
            rows.append([t("Fuel"), nm(d, d.liquids.get(cd["liquid"], cd["liquid"]))])
        elif cd.get("calibre"):
            cal = nm(d, d.cal_names.get(cd["calibre"], cd["calibre"]))
            rows += [[t("Calibre"), cal], [t("Magazine"), t("%s rounds") % cd["magSize"]], [t("Spare magazines"), cd["maxReserveMags"]]]
            rows.append([t("Muzzle velocity"), num(cd["muzzleVelocity"]) + " m/s"])
        else:
            rows.append([t("Melee"), t("yes")])
    elif cat == "ammo":
        cal = nm(d, d.cal_names.get(cd["calibre"], cd["calibre"]))
        rows += [[t("Type"), nm(d, cd["name"])], [t("Calibre"), cal], [t("Rounds"), cd["rounds"]], [t("Bleed x"), num(cd["bleedMult"])]]
        rows += [[t("Knockout x"), num(cd["koMult"])], [t("Penetration"), num(cd["penetration"])], [t("Transferable"), yesno(not cd.get("noTransfer"))]]
    elif cat == "food":
        rows += [[t("Bites"), cd["maxBites"]], [t("Food per bite"), num(cd["biteValue"])], [t("Can be cooked"), yesno(cd["canCook"])], [t("Infects when raw"), yesno(cd["canRawInfect"])]]
    elif cat == "liquid":
        held = ", ".join(nm(d, d.liquids.get(lq[0], lq[0])) for lq in cd.get("liquids") or [])
        rows += [[t("Capacity"), num(cd["capacity"]) + " L"], [t("Can hold"), held or t("nothing")], [t("Reusable"), yesno(cd.get("reusable"))]]
    elif cat == "bag":
        rows.append([t("Slots when worn"), cd["bag_size"]])
    elif cat == "safebox":
        rows.append([t("Slots"), cd["size"]])
    e = it.get("explosive")
    if e:
        rows += [[t("Charge"), charge(e)], [t("Trigger"), trigger(e)], [t("Blast radius"), num(d.presets.get(e["preset"], 0)) + " m"]]
    if it.get("defence"):
        rows.append([t("Movable after placing"), yesno(it["defence"].get("movable"))])
    return rows


def charge(e: dict) -> str:
    return t(CHARGES.get(e["preset"], e["preset"].title()))


def trigger(e: dict) -> str:
    return t(TRIGGERS.get(e["trigger"], e["trigger"].replace("_", " ").title()))


def source_label(d, table: str) -> str:
    kind, _, rest = table.partition("_")
    if kind == "world":
        return t("World loot, %s") % t(rest.replace("_", " "))
    if kind == "vehicle":
        return t("Vehicle trunks, %s") % t(rest.replace("_", " "))
    return t('Supply drop "%s"') % nm(d, d.drops.get(table, rest))


def source_where(d, table: str) -> str:
    kind = table.partition("_")[0]
    parts = []
    if kind == "world":
        zones = Counter({z: n for (tb, z), n in d.spawns.items() if tb == table})
        houses = sum(n for (tb, z), n in d.houses.items() if tb == table)
        text = t("%s spawn points: %s") % (thousands(sum(zones.values())), zone_text(zones))
        parts.append(text + (t(" (%d of them inside houses)") % houses if houses else ""))
    if kind == "airdrop":
        parts.append(t("%d drop points") % sum(d.drop_points.values()))
        if table == d.cache_table:
            parts.append(t("the weapon caches (%s)") % zone_text(d.cache_points))
    if table in d.trunks:
        names = sorted(d.trunks[table])
        shown = ", ".join(names[:5]) + (t(" and %d more") % (len(names) - 5) if len(names) > 5 else "")
        parts.append(t("the trunk of the %s") % shown if len(names) == 1 else t("the trunks of %d vehicle types (%s)") % (len(names), shown))
    text = t("; also ").join(parts) if parts else t("nowhere yet")
    return text[0].upper() + text[1:]


def where(d, u: str) -> str:
    found = []
    for table, tbl in d.loot.items():
        total = sum(e["weight"] for e in tbl["entries"])
        mine = sum(e["weight"] for e in tbl["entries"] if e["uname"] == u)
        kind = table.partition("_")[0]
        if mine and kind in KINDS:
            found.append((KINDS.index(kind), -mine / total * 100, table))
    rows = [[source_label(d, table), source_where(d, table), pct(-share)] for _, share, table in sorted(found)]
    out = [md(["Source", "Where", "Share of the table"], rows, "llr") if rows else t("Not found as loot.") + "\n"]
    extras = []
    if u in d.boxes:
        extras.append(t("Lies at %s fixed spots in the world (GTA's own boxes, crates and bags), put back a while after it is taken.") % thousands(d.boxes[u]))
    fixtures = Counter({z: n for (fu, z), n in d.fixtures.items() if fu == u})
    if fixtures:
        extras.append(t("Already built in the world: %d (%s).") % (sum(fixtures.values()), zone_text(fixtures)))
    if u == d.machines.get("scrap"):
        extras.append(t("Made by the Scrap Machine out of anything with a scrap value, see [Scrap](Scrap)."))
    if u == d.machines.get("refine"):
        extras.append(t("Made by the Refining Machine out of %s, see [Machines](Machines).") % link(d, d.machines["scrap"]))
    if u == d.machines.get("water"):
        extras.append(t("A Water Purifier turns one holding Sea Water into one holding Water, see [Machines](Machines)."))
    if any(r["result"] == u for r in d.recipes):
        extras.append(t("Crafted, see below."))
    if extras:
        out.append("\n" + "\n".join("- " + x for x in extras) + "\n")
    return "".join(out)


def count_text(d, u: str, n: int) -> str:
    return ("%d× " % n if n > 1 else "") + link(d, u)


def recipe_text(d, r: dict) -> str:
    kept = t(" (kept)")
    ing = [count_text(d, u, n) for u, n in sorted(r["consumed"].items())] + [count_text(d, u, n) + kept for u, n in sorted(r["kept"].items())]
    ing = " + ".join(ing)
    if r["kind"] == "combine":
        return t("By hand: %s") % ing
    tool = link(d, r["tool"]) + kept
    if r["kind"] == "workbench":
        return t("At a [Workbench](Workbench) with a %s: %s") % (tool, ing)
    text = t("On the ground with a %s, %s: %s") % (tool, secs(r["build_ms"]), ing)
    if r["remove_ms"]:
        text += t("; taken down again with a %s in %s, which gives the parts back") % (link(d, "Crowbar"), secs(r["remove_ms"]))
    return text


def crafting(d, u: str) -> str:
    made = [recipe_text(d, r) for r in d.recipes if r["result"] == u]
    used = []
    for r in d.recipes:
        roles = []
        if u in r["consumed"]:
            roles.append(t("%d used up") % r["consumed"][u])
        if u in r["kept"]:
            roles.append(t("%d kept") % r["kept"][u])
        if r["tool"] == u:
            roles.append(t("the tool, kept"))
        if roles:
            used.append("%s (%s)" % (link(d, r["result"]), ", ".join(roles)))
    if u == "Crowbar":
        used.append(t("taking down %d kinds of built item (kept)") % sum(1 for r in d.recipes if r["remove_ms"]))
    out = []
    if made:
        out.append("**" + t("Made by") + "**\n\n" + "\n".join("- " + x for x in made) + "\n")
    if used:
        out.append("**" + t("Used in") + "**\n\n" + "\n".join("- " + x for x in used) + "\n")
    if not out:
        return t("No recipe makes or uses it.") + "\n"
    return "\n".join(out)


def scrap_text(d, u: str) -> str:
    scrap = d.machines.get("scrap", "ScrapMetal")
    v = d.scrap.get(u)
    if v:
        text = t("Worth %d %s in a Scrap Machine, see [Scrap](Scrap).") % (v, link(d, scrap))
    else:
        text = t("Cannot be scrapped: a Scrap Machine destroys it, see [Scrap](Scrap).")
    if u == scrap and "refine" in d.machines:
        text += t(" A Refining Machine turns it into %s.") % link(d, d.machines["refine"])
    return text


def whole_word(name: str):
    return re.compile(r"(?<![A-Za-z0-9])" + re.escape(name) + r"(?![A-Za-z0-9])")


def see_also_stems(en, name: str) -> list[str]:
    """The hand-written pages that mention an English item name, not counting it inside a longer one (Burger Hat)."""
    if name not in en.see_also:
        pat = whole_word(name)
        longer = [whole_word(n) for n in {it["name"] for it in en.items.values()} if n != name and pat.search(n)]
        found = []
        for stem, text in en.topics.items():
            for lp in longer:
                text = lp.sub("", text)
            if stem not in NOT_SEE_ALSO and pat.search(text):
                found.append(stem)
        en.see_also[name] = found
    return en.see_also[name]


def item_page(d, u: str) -> str:
    it = d.items[u]
    name = it["name"]
    out = ["# " + name, GENERATED, ""]
    if u in d.pictures:
        out += ["![" + name + "](" + d.img + "/" + d.pictures[u] + ")", ""]
    tip = (TOOLTIPS_FOR[d.lang].get(u) if u in TOOLTIPS else None) or d.tooltips.get(u[:9])
    if tip:
        tip = tip.replace("[", "\\[").replace("]", "\\]")
        out += ["*" + tip + ("" if tip[-1] in ".!?" else ".") + "*", ""]
    others = sorted(v for v in d.items if v != u and d.base.items[v]["name"] == d.base.items[u]["name"])
    if others:
        out += [t("Other items called %s: %s.") % (name, ", ".join(link(d, v, tagged(d, v)) for v in others)), ""]
    out += [md(["Property", "Value"], facts(d, u, it), "ll")]
    out += ["## " + t("Where to find it"), "", where(d, u)]
    out += ["## " + t("Crafting"), "", crafting(d, u)]
    out += ["## " + t("Scrap"), "", scrap_text(d, u), ""]
    also = see_also_stems(d.base, d.base.items[u]["name"])
    if also:
        out += ["## " + t("See also"), "", ", ".join("[" + topic_title(d, s) + "](" + s + ")" for s in also), ""]
    return "\n".join(out)


