def write_lang(d, clean: bool) -> tuple[int, int, set]:
    """Fills the tables of every hand-written page of d.lang and writes its item pages; returns (tables, written, files)."""
    global LANG, TEXTS
    LANG, TEXTS = d.lang, wiki_lang.TEXTS.get(d.lang, {})
    suffix = ".md" if d.lang == "en" else "." + d.lang + ".md"
    made = {name: fn(d) for name, fn in TABLES.items()}
    for page in sorted(d.wiki.glob("*.md")):
        if lang_of(page) != d.lang or is_generated(page):
            continue
        text = page.read_text(encoding="utf8")
        new = text
        for name, body in made.items():
            pat = re.compile(r"(<!-- table:" + name + r" -->\n).*?(<!-- /table:" + name + r" -->)", re.S)
            new = pat.sub(lambda m: m.group(1) + body + m.group(2), new)
        if new != text:
            page.write_text(new, encoding="utf8", newline="\n")
            print("updated", page.name)
    written, files = 0, set()
    for u in sorted(d.items):
        if not d.pages[u]["file"]:
            continue
        path = d.wiki / (d.pages[u]["file"] + suffix)
        files.add(path.name)
        if path.exists() and not is_generated(path):
            print("kept", path.name, "(hand-written, not overwritten)")
            continue
        text = item_page(d, u)
        if not path.exists() or path.read_text(encoding="utf8") != text:
            path.write_text(text, encoding="utf8", newline="\n")
            written += 1
    for page in sorted(d.wiki.glob("*.md")):
        if lang_of(page) == d.lang and page.name not in files and is_generated(page):
            if clean:
                page.unlink()
                print("deleted", page.name)
            else:
                print("stale", page.name, "(--clean deletes it)")
    return len(made), written, files


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wiki", default=str(ROOT / "wiki"), help="the wiki folder to write (default: the wiki/ folder of this repo)")
    ap.add_argument("--images", default="images/items", help="the path pages show item renders under (docs/images/items/all in the wiki build)")
    ap.add_argument("--clean", action="store_true", help="delete generated item pages whose item no longer exists")
    a = ap.parse_args()
    en = load(Path(a.wiki), a.images)
    for lang in LANGS:
        d = for_lang(en, lang)
        tables, written, files = write_lang(d, a.clean)
        print("[%s] %d tables, %d item pages (%d written now)" % (lang, tables, len(files), written))
    d = en
    looted = {e["uname"] for tbl in d.loot.values() for e in tbl["entries"]}
    unlooted = sorted(u for u in d.items if u not in looted)
    topics = sorted(u for u in d.items if not d.pages[u]["file"])
    dups = sorted(d.pages[u]["file"] + ".md" for u in d.items if d.pages[u]["dup"] and d.pages[u]["file"])
    prefixes = Counter(u[:9] for u in d.items)
    shared = sorted(u for u in d.items if prefixes[u[:9]] > 1)
    print("%d item types, %d names link to topic pages: %s" % (len(d.items), len(topics), ", ".join(topics)))
    print("%d items in no loot table: %s" % (len(unlooted), ", ".join(unlooted)))
    print("%d pages of items sharing a name: %s" % (len(dups), ", ".join(dups)))
    if shared:
        print("unames sharing a tooltip key (first nine characters):", ", ".join(shared))
    untranslated = sorted(s for s in wiki_lang.used_texts() if s not in wiki_lang.TEXTS["pt"])
    if untranslated:
        print("tools/wiki_lang.py lacks the Portuguese of:", " | ".join(untranslated))


if __name__ == "__main__":
    main()
