def link(d, u: str, label: str | None = None) -> str:
    return "[" + (label or d.items[u]["name"]) + "](" + d.pages[u]["link"] + ")"


def tagged(d, u: str) -> str:
    """The display name, with the uname when other items share it."""
    name = d.items[u]["name"]
    return name + " (`" + u + "`)" if d.pages[u]["dup"] else name


def pct(share: float) -> str:
    return "<0.1 %" if share < 0.05 else "%.1f %%" % share


def zone_text(counter: Counter) -> str:
    return ", ".join("%s in %s" % (format(n, ","), ZONES.get(z, z)) for z, n in sorted(counter.items(), key=lambda kv: (-kv[1], kv[0])))


def facts(d, u: str, t: dict) -> list[list]:
    cd = t.get("categoryData") or {}
    cat = t["category"]
    label = CATEGORIES[cat]
    if cat == "weapon":
        label += " (firearm)" if cd.get("calibre") else " (melee)"
    elif t.get("explosive"):
        label = "Explosive"
    elif t.get("defence"):
        label = "Defence"
    rows = [["Size", t["size"]], ["Category", label], ["Hit points", t["maxHitpoints"]]]
    if t.get("useCarryAnim"):
        rows.append(["Carried in both hands", "yes"])
    if t.get("longPickup"):
        rows.append(["Long pick-up", "yes"])
    if u in d.slots:
        rows.append(["Wear slot", d.slots[u]])
    if cat == "weapon":
        if cd.get("liquid"):
            rows.append(["Fuel", d.liquids.get(cd["liquid"], cd["liquid"])])
        elif cd.get("calibre"):
            rows += [["Calibre", d.cal_names.get(cd["calibre"], cd["calibre"])], ["Magazine", str(cd["magSize"]) + " rounds"], ["Spare magazines", cd["maxReserveMags"]]]
            rows.append(["Muzzle velocity", num(cd["muzzleVelocity"]) + " m/s"])
        else:
            rows.append(["Melee", "yes"])
    elif cat == "ammo":
        rows += [["Type", cd["name"]], ["Calibre", d.cal_names.get(cd["calibre"], cd["calibre"])], ["Rounds", cd["rounds"]], ["Bleed x", num(cd["bleedMult"])]]
        rows += [["Knockout x", num(cd["koMult"])], ["Penetration", num(cd["penetration"])], ["Transferable", "no" if cd.get("noTransfer") else "yes"]]
    elif cat == "food":
        rows += [["Bites", cd["maxBites"]], ["Food per bite", num(cd["biteValue"])], ["Can be cooked", yesno(cd["canCook"])], ["Infects when raw", yesno(cd["canRawInfect"])]]
    elif cat == "liquid":
        held = ", ".join(d.liquids.get(l[0], l[0]) for l in cd.get("liquids") or [])
        rows += [["Capacity", num(cd["capacity"]) + " L"], ["Can hold", held or "nothing"], ["Reusable", yesno(cd.get("reusable"))]]
    elif cat == "bag":
        rows.append(["Slots when worn", cd["bag_size"]])
    elif cat == "safebox":
        rows.append(["Slots", cd["size"]])
    e = t.get("explosive")
    if e:
        rows += [["Charge", CHARGES.get(e["preset"], e["preset"].title())], ["Trigger", e["trigger"].replace("_", " ").title()], ["Blast radius", num(d.presets.get(e["preset"], 0)) + " m"]]
    if t.get("defence"):
        rows.append(["Movable after placing", yesno(t["defence"].get("movable"))])
    return rows


def source_label(d, table: str) -> str:
    kind, _, rest = table.partition("_")
    if kind == "world":
        return "World loot, " + rest.replace("_", " ")
    if kind == "vehicle":
        return "Vehicle trunks, " + rest.replace("_", " ")
    return 'Supply drop "' + d.drops.get(table, rest) + '"'


def source_where(d, table: str) -> str:
    kind = table.partition("_")[0]
    parts = []
    if kind == "world":
        zones = Counter({z: n for (tb, z), n in d.spawns.items() if tb == table})
        houses = sum(n for (tb, z), n in d.houses.items() if tb == table)
        text = "%s spawn points: %s" % (format(sum(zones.values()), ","), zone_text(zones))
        parts.append(text + (" (%d of them inside houses)" % houses if houses else ""))
    if kind == "airdrop":
        parts.append("%d drop points" % sum(d.drop_points.values()))
        if table == d.cache_table:
            parts.append("the weapon caches (%s)" % zone_text(d.cache_points))
    if table in d.trunks:
        names = sorted(d.trunks[table])
        shown = ", ".join(names[:5]) + (" and %d more" % (len(names) - 5) if len(names) > 5 else "")
        parts.append("the trunk of the %s" % shown if len(names) == 1 else "the trunks of %d vehicle types (%s)" % (len(names), shown))
    text = "; also ".join(parts) if parts else "nowhere yet"
    return text[0].upper() + text[1:]


def where(d, u: str) -> str:
    found = []
    for table, tbl in d.loot.items():
        total = sum(e["weight"] for e in tbl["entries"])
        mine = sum(e["weight"] for e in tbl["entries"] if e["uname"] == u)
        if mine:
            found.append((KINDS.index(table.partition("_")[0]), -mine / total * 100, table))
    rows = [[source_label(d, table), source_where(d, table), pct(-share)] for _, share, table in sorted(found)]
    out = [md(["Source", "Where", "Share of the table"], rows, "llr") if rows else "Not found as loot.\n"]
    extras = []
    if u in d.boxes:
        extras.append("Lies at %s fixed spots in the world (GTA's own boxes, crates and bags), put back a while after it is taken." % format(d.boxes[u], ","))
    fixtures = Counter({z: n for (fu, z), n in d.fixtures.items() if fu == u})
    if fixtures:
        extras.append("Already built in the world: %d (%s)." % (sum(fixtures.values()), zone_text(fixtures)))
    if u == d.machines.get("scrap"):
        extras.append("Made by the Scrap Machine out of anything with a scrap value, see [Scrap](Scrap).")
    if u == d.machines.get("refine"):
        extras.append("Made by the Refining Machine out of %s, see [Machines](Machines)." % link(d, d.machines["scrap"]))
    if u == d.machines.get("water"):
        extras.append("A Water Purifier turns one holding Sea Water into one holding Water, see [Machines](Machines).")
    if any(r["result"] == u for r in d.recipes):
        extras.append("Crafted, see below.")
    if extras:
        out.append("\n" + "\n".join("- " + x for x in extras) + "\n")
    return "".join(out)


def count_text(d, u: str, n: int) -> str:
    return ("%d× " % n if n > 1 else "") + link(d, u)


def recipe_text(d, r: dict) -> str:
    ing = [count_text(d, u, n) for u, n in sorted(r["consumed"].items())] + [count_text(d, u, n) + " (kept)" for u, n in sorted(r["kept"].items())]
    ing = " + ".join(ing)
    if r["kind"] == "combine":
        return "By hand: " + ing
    tool = link(d, r["tool"]) + " (kept)"
    if r["kind"] == "workbench":
        return "At a [Workbench](Workbench) with a %s: %s" % (tool, ing)
    text = "On the ground with a %s, %s: %s" % (tool, secs(r["build_ms"]), ing)
    if r["remove_ms"]:
        text += "; taken down again with a %s in %s, which gives the parts back" % (link(d, "Crowbar"), secs(r["remove_ms"]))
    return text


def crafting(d, u: str) -> str:
    made = [recipe_text(d, r) for r in d.recipes if r["result"] == u]
    used = []
    for r in d.recipes:
        roles = []
        if u in r["consumed"]:
            roles.append("%d used up" % r["consumed"][u])
        if u in r["kept"]:
            roles.append("%d kept" % r["kept"][u])
        if r["tool"] == u:
            roles.append("the tool, kept")
        if roles:
            used.append("%s (%s)" % (link(d, r["result"]), ", ".join(roles)))
    if u == "Crowbar":
        used.append("taking down %d kinds of built item (kept)" % sum(1 for r in d.recipes if r["remove_ms"]))
    out = []
    if made:
        out.append("**Made by**\n\n" + "\n".join("- " + x for x in made) + "\n")
    if used:
        out.append("**Used in**\n\n" + "\n".join("- " + x for x in used) + "\n")
    if not out:
        return "No recipe makes or uses it.\n"
    return "\n".join(out)


def scrap_text(d, u: str) -> str:
    scrap = d.machines.get("scrap", "ScrapMetal")
    v = d.scrap.get(u)
    if v:
        text = "Worth %d %s in a Scrap Machine, see [Scrap](Scrap)." % (v, link(d, scrap))
    else:
        text = "Cannot be scrapped: a Scrap Machine destroys it, see [Scrap](Scrap)."
    if u == scrap and "refine" in d.machines:
        text += " A Refining Machine turns it into %s." % link(d, d.machines["refine"])
    return text


def whole_word(name: str):
    return re.compile(r"(?<![A-Za-z0-9])" + re.escape(name) + r"(?![A-Za-z0-9])")


def see_also(d, name: str) -> str:
    """Links to the hand-written pages that mention the name, not counting it inside a longer item name (Burger Hat)."""
    if name not in d.see_also:
        pat = whole_word(name)
        longer = [whole_word(n) for n in {t["name"] for t in d.items.values()} if n != name and pat.search(n)]
        found = []
        for stem, text in d.topics.items():
            for lp in longer:
                text = lp.sub("", text)
            if stem not in NOT_SEE_ALSO and pat.search(text):
                m = re.match(r"# (.+)", text)
                found.append("[" + (m.group(1).strip() if m else stem.replace("-", " ")) + "](" + stem + ")")
        d.see_also[name] = ", ".join(found)
    return d.see_also[name]


def item_page(d, u: str) -> str:
    t = d.items[u]
    name = t["name"]
    out = ["# " + name, GENERATED, ""]
    if u in d.pictures:
        out += ["![" + name + "](" + d.img + "/" + d.pictures[u] + ")", ""]
    tip = TOOLTIPS.get(u) or d.tooltips.get(u[:9])
    if tip:
        tip = tip.replace("[", "\\[").replace("]", "\\]")
        out += ["*" + tip + ("" if tip[-1] in ".!?" else ".") + "*", ""]
    others = sorted(v for v in d.items if v != u and d.items[v]["name"] == name)
    if others:
        out += ["Other items called %s: %s." % (name, ", ".join(link(d, v, tagged(d, v)) for v in others)), ""]
    out += [md(["Property", "Value"], facts(d, u, t), "ll")]
    out += ["## Where to find it", "", where(d, u)]
    out += ["## Crafting", "", crafting(d, u)]
    out += ["## Scrap", "", scrap_text(d, u), ""]
    also = see_also(d, name)
    if also:
        out += ["## See also", "", also, ""]
    return "\n".join(out)


