TOKEN = re.compile(r'\s*(?:(--[^\n]*)|("(?:[^"\\]|\\.)*")|(-?\d+(?:\.\d+)?(?:e[+-]?\d+)?)|(\[)|(\])|([{}=,])|([A-Za-z_][\w.]*))')


def tokens(text: str):
    pos = 0
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m or m.end() == pos:
            if text[pos:].strip():
                raise ValueError("lua parse error near " + repr(text[pos : pos + 30]))
            return
        pos = m.end()
        if m.group(1):
            continue
        yield m.lastindex, m.group(m.lastindex)


def parse_table(toks, first=None):
    """Parses a Lua table constructor whose `{` was already consumed; returns a dict (keyed rows) or a list.

    A constructor mixing both kinds of field returns a dict with the positional values under the keys 1..n."""
    out = {}
    arr = []
    while True:
        kind, tok = next(toks)
        if tok == "}":
            break
        if tok == ",":
            continue
        key = None
        if kind == 4:
            _, key = next(toks)
            key = key.strip('"')
            next(toks)
            next(toks)
            kind, tok = next(toks)
        elif kind == 7:
            peek = next(toks)
            if peek[1] == "=":
                key = tok
                kind, tok = next(toks)
            else:
                value = convert(kind, tok, toks)
                arr.append(value)
                if peek[1] == "}":
                    break
                continue
        value = convert(kind, tok, toks)
        if key is None:
            arr.append(value)
        else:
            out[key] = value
    if out and arr:
        for i, v in enumerate(arr, 1):
            out[i] = v
    return out if out or not arr else arr


def convert(kind, tok, toks):
    if tok == "{":
        return parse_table(toks)
    if kind == 2:
        return tok[1:-1].replace('\\"', '"')
    if kind == 3:
        return float(tok) if re.search(r"[.e]", tok) else int(tok)
    if tok == "true":
        return True
    if tok == "false":
        return False
    if tok == "nil":
        return None
    return tok


def lua_rows(path: Path, prefix: str) -> dict[str, dict]:
    rows = {}
    for line in path.read_text(encoding="utf8").splitlines():
        m = re.match(re.escape(prefix) + r"(\w+) = \{", line)
        if m:
            toks = tokens(line[m.end() :])
            rows[m.group(1)] = parse_table(toks)
    return rows


def lua_block(src: str, start: str) -> str:
    """The text of the table constructor `start` opens (`start` ends with its `{`): up to and with the matching brace."""
    i = src.index(start) + len(start)
    depth, j = 1, i
    while depth:
        depth += {"{": 1, "}": -1}.get(src[j], 0)
        j += 1
    return src[i:j]


def positional(row):
    """A parsed Lua row as (positional values, named fields)."""
    if isinstance(row, dict):
        arr = [row[k] for k in sorted(k for k in row if isinstance(k, int))]
        return arr, {k: v for k, v in row.items() if isinstance(k, str)}
    return list(row), {}


def md(headers: list[str], rows: list[list], align: str = "") -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(":--" if a == "l" else "--:" for a in (align or "l" * len(headers))) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def num(v) -> str:
    if isinstance(v, float) and v == int(v):
        return str(int(v))
    return str(v)


def yesno(v) -> str:
    return "yes" if v else "no"


def secs(ms) -> str:
    return num(ms / 1000) + " s"


def words(uname: str) -> str:
    """A uname as words: LargeFrame -> Large Frame."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", uname)


def real(items: dict) -> dict:
    out = {}
    for u, t in items.items():
        if not u.startswith("NULL") and u.lower().replace("_", "") not in ("vehicleweapon", "unknown"):
            t["name"] = t["name"] or words(u)
            out[u] = t
    return out


def page_stem(name: str) -> str:
    """The wiki page name of a display name: words hyphenated, anything but letters and digits dropped."""
    return "-".join(w for w in (re.sub(r"[^A-Za-z0-9]", "", w) for w in name.split()) if w)


