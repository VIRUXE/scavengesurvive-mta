"""Build the SA-MP model pack for the `models` resource from a locally installed GTA:SA + SA-MP client.

SA-MP's custom objects (ids 11682-11753 and 18631-19999) do not exist in MTA. For every such model the gamemode's
item types or the converted maps (`maps/data/*.lua`) use, this copies the .dff (and the .txd when SA-MP ships its
own) out of SAMP.img and splits the matching single-model .col out of SAMPCOL.img's `allsampcols.col` into
`models/files/`, then writes `models/manifest.lua` + `models/meta.xml`. All of it is
committed; rerun this only when item types or maps start using SA-MP models that are not in the pack yet (see
`--check`). Models whose
texture dictionary is a vanilla one that some vanilla model already owns are bound to that model's TXD at runtime
(no file copied); the few vanilla TXDs no model owns (cutscene props, special peds) are copied from the game's own
archives. Provenance: THIRD_PARTY_NOTICES.md.

    python -m tools.extract_samp_models [--gta DIR] [--check]
"""
from __future__ import annotations

import argparse
import glob
import os
import re
import struct
import sys
from pathlib import Path

from tools.port_hats import PORT_MODEL_MIN

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / "resources" / "[scavengesurvive]"
IDE = ROOT / "tools" / "data" / "samp.ide"
ITEM_TYPES = RESOURCES / "data" / "generated" / "item_types.lua"
MAPS_DATA = RESOURCES / "maps" / "data"
MODELS = RESOURCES / "models"
HEADER = "-- Generated by tools/extract_samp_models.py; do not edit. SA-MP model -> files in models/files/."
SECTOR = 2048
COL_FOURCCS = (b"COLL", b"COL2", b"COL3", b"COL4")


def is_samp_model(model: int) -> bool:
    """SA-MP's own object ids; the port's hat models (tools/port_hats.py, 20001+) are above them."""
    return 18631 <= model < PORT_MODEL_MIN or 11682 <= model <= 11753


def parse_col_library(data: bytes) -> dict[str, bytes]:
    """Single-model COL chunks from a multi-model .col archive: lowercase model name -> raw COL chunk."""
    cols: dict[str, bytes] = {}
    pos = 0
    while pos + 32 <= len(data):
        fourcc, size = struct.unpack_from("<4sI", data, pos)
        if fourcc not in COL_FOURCCS:
            break
        end = pos + 8 + size
        name = data[pos + 8 : pos + 30].split(b"\0", 1)[0].decode("latin1").lower()
        cols[name] = data[pos:end]
        pos = end
    return cols


def read_img_index(path: Path) -> dict[str, tuple[int, int]]:
    """VER2 IMG directory: lowercase entry name -> (offset, size) in bytes."""
    with open(path, "rb") as f:
        magic, count = struct.unpack("<4sI", f.read(8))
        if magic != b"VER2":
            raise ValueError(f"{path}: not a VER2 IMG archive")
        index = {}
        for _ in range(count):
            offset, streaming, _archive, name = struct.unpack("<IHH24s", f.read(32))
            index[name.split(b"\0")[0].decode("latin1").lower()] = (offset * SECTOR, streaming * SECTOR)
    return index


def read_img_entry(path: Path, entry: tuple[int, int]) -> bytes:
    with open(path, "rb") as f:
        f.seek(entry[0])
        return f.read(entry[1])


def parse_ide(text: str) -> dict[int, tuple[str, str, int]]:
    """Object definition lines (objs): id -> (dff, txd, draw distance)."""
    out = {}
    for line in text.splitlines():
        parts = [p.strip() for p in line.split(",")]
        # 5 fields = static object; animated objects carry an extra name field and are not items
        if len(parts) == 5 and parts[0].isdigit() and parts[3].replace(".", "", 1).isdigit():
            out[int(parts[0])] = (parts[1], parts[2], int(float(parts[3])))
    return out


def vanilla_txd_owners(gta: Path) -> dict[str, int]:
    """lowercase txd name -> lowest vanilla model id (object or ped) whose model uses it."""
    owners: dict[str, int] = {}
    paths = sorted(glob.glob(str(gta / "data" / "maps" / "**" / "*.ide"), recursive=True))
    paths += [str(gta / "data" / "default.ide"), str(gta / "data" / "peds.ide")]
    for p in paths:
        if not os.path.exists(p):
            continue
        section = None
        with open(p, encoding="latin1", errors="replace") as f:
            for line in f:
                s = line.strip()
                if not s or s.startswith("#"):
                    continue
                if "," not in s:
                    section = s if s in ("objs", "tobj", "peds") else None
                    continue
                if section is None:
                    continue
                parts = [x.strip() for x in s.split(",")]
                if len(parts) >= 3 and parts[0].isdigit():
                    txd = parts[2].lower()
                    model = int(parts[0])
                    if txd not in owners or model < owners[txd]:
                        owners[txd] = model
    return owners


def models_used(lua_text: str) -> list[int]:
    return sorted({int(m) for m in re.findall(r"\bmodel = (\d+)", lua_text)})


# maps/data/<ZONE>.lua object rows start "        { <model>, " (tools/convert/maps.py); removals and materials
# are indented the same but a removal's model is a vanilla id and a material row starts with a key, not a number
MAP_ROW_RE = re.compile(r"^\s+\{ (\d+), ", re.M)


def map_models_used(lua_text: str) -> list[int]:
    return sorted({int(m) for m in MAP_ROW_RE.findall(lua_text)})


# SA-MP models that clients build structures from rather than item types or maps: the pitched tent's camo
# panels and poles (items/shared/logic/tent.lua, upstream core/item/tent.pwn) and the open Locker the closed one
# swaps to (items/shared/logic/smallitems.lua, upstream core/item/locker.pwn), and the blood pool a bleeding
# player leaves behind (character/client/blood.lua, upstream core/char/bleed.pwn); the puzzles' spark under Mt Chiliad's
# keypad and the ranch PC's screen (world/shared/logic/puzzles.lua, upstream world/puzzles/mtchill.pwn, ranch.pwn), and
# Area 69's main and airstrip gates (world/shared/logic/area69.lua)
STRUCTURE_MODELS = [19477, 19087, 11730, 19836, 18724, 19475, 19313]


def all_models_used(items_path: Path, maps_dir: Path | None) -> list[int]:
    used = set(models_used(items_path.read_text(encoding="utf-8")))
    used.update(STRUCTURE_MODELS)
    if maps_dir and maps_dir.is_dir():
        for p in sorted(maps_dir.glob("*.lua")):
            if p.name != "index.lua":
                used.update(map_models_used(p.read_text(encoding="utf-8")))
    return sorted(used)


def trim_txd(data: bytes, keep: set[str]) -> bytes:
    """A texture dictionary with only the textures named in `keep` (lowercase), for the loose vanilla TXDs SA-MP
    models borrow a texture or two from (particle.txd is 650 KB for one 64x64 blood pool)."""
    _kind, _size, version = struct.unpack_from("<III", data, 0)
    pos, end, natives, ext = 12, 12 + struct.unpack_from("<I", data, 4)[0], [], b""
    device = 0
    while pos < end:
        kind, size, _v = struct.unpack_from("<III", data, pos)
        chunk = data[pos : pos + 12 + size]
        if kind == 0x01:
            device = struct.unpack_from("<H", chunk, 14)[0]
        elif kind == 0x15:
            name = chunk[12 + 12 + 8 : 12 + 12 + 40].split(b"\0", 1)[0].decode("latin1").lower()
            if name in keep:
                natives.append(chunk)
        elif kind == 0x03:
            ext = chunk
        pos += 12 + size
    body = struct.pack("<IIIHH", 0x01, 4, version, len(natives), device) + b"".join(natives) + ext
    return struct.pack("<III", 0x16, len(body), version) + body


def dff_strings(data: bytes) -> set[str]:
    """Lowercase NUL-terminated names in a DFF, a superset of the texture names its materials use."""
    return {m.decode("latin1").lower() for m in re.findall(rb"([\w-]{1,31})\0", data)}


def plan(ide, used, samp_index, owners, vanilla_indexes, samp_cols=None, loose_txds=()):
    """Per SA-MP model: how the client gets its dff, col and txd. Returns (entries, problems). `loose_txds` are the
    vanilla TXDs that sit loose in models/ rather than in an archive (particle.txd), copied trimmed to the textures
    the model uses."""
    entries, problems = {}, []
    for model in used:
        if not is_samp_model(model):
            continue
        if model not in ide:
            problems.append(f"{model}: not in samp.ide")
            continue
        dff, txd, dist = ide[model]
        dff_l, txd_l = dff.lower(), txd.lower()
        if dff_l + ".dff" not in samp_index:
            problems.append(f"{model}: {dff}.dff not in SAMP.img")
            continue
        if samp_cols is not None and dff_l not in samp_cols:
            problems.append(f"{model}: {dff}.col not in SAMPCOL.img")
            continue
        e = {"dff": dff_l, "dist": dist, "src": {"dff": ("samp", dff_l + ".dff"), "col": ("col", dff_l + ".col")}}
        if txd_l + ".txd" in samp_index:
            e["txd"] = txd_l
            e["src"]["txd"] = ("samp", txd_l + ".txd")
        elif txd_l in owners:
            e["txdModel"] = owners[txd_l]
        else:
            for name, index in vanilla_indexes.items():
                if txd_l + ".txd" in index:
                    e["txd"] = txd_l
                    e["src"]["txd"] = (name, txd_l + ".txd")
                    break
            else:
                if txd_l not in loose_txds:
                    problems.append(f"{model}: texture dictionary {txd} not found anywhere")
                    continue
                e["txd"] = txd_l
                e["src"]["txd"] = ("loose", txd_l + ".txd")
        entries[model] = e
    return entries, problems


def render_manifest(entries) -> str:
    lines = [HEADER, "return {"]
    for model in sorted(entries):
        e = entries[model]
        fields = [f'dff = "{e["dff"]}"']
        if "txd" in e:
            fields.append(f'txd = "{e["txd"]}"')
        if "txdModel" in e:
            fields.append(f"txdModel = {e['txdModel']}")
        fields.append(f"dist = {e['dist']}")
        lines.append(f"    [{model}] = {{ {', '.join(fields)} }},")
    lines.append("}")
    return "\n".join(lines) + "\n"


HOUSE_SHELL_RE = re.compile(r"^[a-z]{2}house\d$")


def files_needed(entries) -> list[str]:
    names = set()
    for e in entries.values():
        names.add(e["dff"] + ".col")
        names.add(e["dff"] + ".dff")
        if "txd" in e:
            names.add(e["txd"] + ".txd")
        if HOUSE_SHELL_RE.match(e["dff"]):
            names.add("house_window.txd")  # glass for the window panes, see tools/glaze_house_windows.py
    return sorted(names)


def ped_files(out_dir: Path) -> list[str]:
    """DFF and TXD files of the hatless ped variants listed in <out_dir>/peds.lua (tools/extract_ped_models.py)."""
    manifest = out_dir / "peds.lua"
    txds = re.findall(r'txd = "([^"]+)"', manifest.read_text(encoding="ascii")) if manifest.is_file() else []
    return sorted(listed_dffs(manifest) + [f"{name}.txd" for name in txds])


def hat_files(out_dir: Path) -> list[str]:
    """DFF files of the cut hats listed in <out_dir>/hats.lua (tools/extract_ped_models.py --hats)."""
    return listed_dffs(out_dir / "hats.lua")


def door_files(out_dir: Path) -> list[str]:
    """DFF and COL files of the house shells' fitted doors listed in <out_dir>/doors.lua (tools/fit_house_doors.py)."""
    dffs = listed_dffs(out_dir / "doors.lua")
    return sorted(dffs + [name[:-4] + ".col" for name in dffs])


def prop_files(out_dir: Path) -> list[str]:
    """DFF, COL and TXD files of the props the port adds to the world, listed in <out_dir>/props.lua
    (tools/make_ls_hatch.py)."""
    dffs = listed_dffs(out_dir / "props.lua")
    return sorted(dffs + [name[:-4] + ext for name in dffs for ext in (".col", ".txd")])

def listed_dffs(manifest: Path) -> list[str]:
    if not manifest.is_file():
        return []
    return sorted(f"{name}.dff" for name in re.findall(r'dff = "([^"]+)"', manifest.read_text(encoding="ascii")))


def render_meta(entries, peds: list[str] = (), hats: list[str] = (), doors: list[str] = (), props: list[str] = ()) -> str:
    lines = [
        "<meta>",
        '    <info author="scavengesurvive-mta" type="script" name="models" '
        'description="SA-MP custom object models used by the item types and the maps" version="0.1.0"/>',
        '    <min_mta_version server="1.6.0" client="1.6.0-9.21695"/>',  # engineGetModelTXDID
        "    <download_priority_group>90</download_priority_group>",
        '    <script src="client/main.lua" type="client"/>',
        '    <file src="manifest.lua"/>',
    ]
    lines += [f'    <file src="files/{name}"/>' for name in files_needed(entries)]
    if peds:
        lines.append('    <file src="peds.lua"/>')
        lines += [f'    <file src="files/{name}"/>' for name in peds]
    if hats:
        lines.append('    <file src="hats.lua"/>')
        lines += [f'    <file src="files/{name}"/>' for name in hats]
    if doors:
        lines.append('    <file src="doors.lua"/>')
        lines += [f'    <file src="files/{name}"/>' for name in doors]
    if props:
        lines.append('    <file src="props.lua"/>')
        lines += [f'    <file src="files/{name}"/>' for name in props]
    lines += ['    <export function="resolve" type="client"/>', '    <export function="hatlessSkin" type="client"/>', '    <export function="bareSkin" type="client"/>']
    lines.append("</meta>")
    return "\n".join(lines) + "\n"


def write_meta(out_dir: Path) -> None:
    """Regenerates meta.xml from the manifests on disk (manifest.lua for objects, peds.lua for hatless peds, hats.lua
    for the hats cut off them, doors.lua for the house shells' fitted doors)."""
    entries = {}
    manifest = out_dir / "manifest.lua"
    if manifest.is_file():
        for dff, txd, txd_model in re.findall(
            r'dff = "([^"]+)"(?:, txd = "([^"]+)")?(?:, txdModel = (\d+))?', manifest.read_text(encoding="ascii")
        ):
            e = {"dff": dff}
            if txd:
                e["txd"] = txd
            if txd_model:
                e["txdModel"] = int(txd_model)
            entries[dff] = e
    meta = render_meta(entries, ped_files(out_dir), hat_files(out_dir), door_files(out_dir), props=prop_files(out_dir))
    (out_dir / "meta.xml").write_text(meta, encoding="ascii", newline="\n")


def detect_gta() -> Path | None:
    if sys.platform != "win32":
        return None
    import winreg

    for hive, key, value in [
        (winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\WOW6432Node\Rockstar Games\GTA San Andreas\Installation", "ExePath"),
        (winreg.HKEY_CURRENT_USER, r"Software\Multi Theft Auto: San Andreas All\Common", "GTA:SA Path"),
    ]:
        try:
            with winreg.OpenKey(hive, key) as k:
                raw = winreg.QueryValueEx(k, value)[0].strip('"')
        except OSError:
            continue
        p = Path(raw)
        if p.suffix.lower() == ".exe":
            p = p.parent
        if (p / "SAMP" / "SAMP.img").is_file():
            return p
    return None


def txd_natives(data: bytes) -> tuple[int, int, list[bytes]]:
    """(version, device, texture native chunks) of a TXD."""
    _kind, size, version = struct.unpack_from("<III", data, 0)
    pos, end, natives, device = 12, 12 + size, [], 0
    while pos < end:
        kind, csize, _v = struct.unpack_from("<III", data, pos)
        if kind == 0x01:
            device = struct.unpack_from("<H", data, pos + 14)[0]
        elif kind == 0x15:
            natives.append(data[pos : pos + 12 + csize])
        pos += 12 + csize
    return version, device, natives


def merge_txd(parts: list[bytes]) -> bytes:
    """One texture dictionary holding every texture of `parts` (already trimmed dictionaries)."""
    version, device, natives = 0, 0, []
    for data in parts:
        version, device, chunks = txd_natives(data)
        natives += chunks
    body = struct.pack("<IIIHH", 0x01, 4, version, len(natives), device) + b"".join(natives)
    body += struct.pack("<III", 0x03, 0, version)
    return struct.pack("<III", 0x16, len(body), version) + body


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gta", type=Path, help="GTA:SA folder with SAMP\\SAMP.img (default: from the registry)")
    ap.add_argument("--ide", type=Path, default=IDE)
    ap.add_argument("--items", type=Path, default=ITEM_TYPES)
    ap.add_argument("--maps", type=Path, default=MAPS_DATA, help="maps/data dir (pass an empty dir to skip)")
    ap.add_argument("--out", type=Path, default=MODELS)
    ap.add_argument("--check", action="store_true", help="only report what would be extracted")
    args = ap.parse_args(argv)
    gta = args.gta or detect_gta()
    if not gta or not (gta / "SAMP" / "SAMP.img").is_file():
        print("extract_samp_models: no GTA:SA + SA-MP client found (pass --gta)", file=sys.stderr)
        return 2
    samp_img = gta / "SAMP" / "SAMP.img"
    sampcol_img = gta / "SAMP" / "SAMPCOL.img"
    if not sampcol_img.is_file():
        print("extract_samp_models: no SAMPCOL.img found next to SAMP.img", file=sys.stderr)
        return 2
    vanilla = {n: gta / p for n, p in [("gta3", "models/gta3.img"), ("cutscene", "models/cutscene.img"),
                                       ("gta_int", "models/gta_int.img")] if (gta / p).is_file()}
    ide = parse_ide(args.ide.read_text(encoding="ascii"))
    used = all_models_used(args.items, args.maps)
    samp_index = read_img_index(samp_img)
    sampcol_index = read_img_index(sampcol_img)
    samp_cols = parse_col_library(read_img_entry(sampcol_img, sampcol_index["allsampcols.col"]))
    vanilla_indexes = {n: read_img_index(p) for n, p in vanilla.items()}
    loose = {p.stem.lower(): p for p in (gta / "models").glob("*.txd")}
    owners = vanilla_txd_owners(gta)
    entries, problems = plan(ide, used, samp_index, owners=owners, vanilla_indexes=vanilla_indexes, samp_cols=samp_cols, loose_txds=loose)
    for p in problems:
        print("warning:", p, file=sys.stderr)
    files = files_needed(entries)
    print(f"{len(entries)} SA-MP models, {len(files)} files from {samp_img}")
    if args.check:
        return 1 if problems else 0
    out_files = args.out / "files"
    out_files.mkdir(parents=True, exist_ok=True)
    archives = {"samp": (samp_img, samp_index), **{n: (vanilla[n], vanilla_indexes[n]) for n in vanilla}}
    for e in entries.values():
        for archive, name in e["src"].values():
            target = out_files / name
            if target.is_file():
                continue
            if archive == "col":
                target.write_bytes(samp_cols[e["dff"]])
            elif archive == "loose":
                dff = read_img_entry(samp_img, samp_index[e["dff"] + ".dff"])
                target.write_bytes(trim_txd(loose[name[:-4]].read_bytes(), dff_strings(dff)))
            else:
                path, index = archives[archive]
                target.write_bytes(read_img_entry(path, index[name]))
    (args.out / "manifest.lua").write_text(render_manifest(entries), encoding="ascii", newline="\n")
    meta = render_meta(entries, ped_files(args.out), hat_files(args.out), door_files(args.out), props=prop_files(args.out))
    (args.out / "meta.xml").write_text(meta, encoding="ascii", newline="\n")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
