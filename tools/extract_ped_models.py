"""Build the hatless ped variants for the `models` resource (#75).

Some GTA:SA skins carry their hat, cap or helmet in the mesh, so a worn hat pokes through it. For every skin in
HEADGEAR this pulls `<name>.dff` out of `models/gta3.img`, runs Blender headless with DragonFF
(tools/blender/cut_headgear.py) to delete the headgear faces, writes `files/<name>_nohat.dff` and lists the variant
in `peds.lua`; `meta.xml` is regenerated from both manifests. `items` swaps a player onto the variant on each
client while a hat is worn. The variant needs no TXD: it shares the base skin's.

    python -m tools.extract_ped_models            # every skin in HEADGEAR (skips files that exist)
    python -m tools.extract_ped_models 283 287    # only these, rebuilt
    python -m tools.extract_ped_models --check    # list what would be built

Blender comes from --blender, the BLENDER environment variable or the newest "Blender Foundation" install.
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

from tools.extract_samp_models import detect_gta, read_img_entry, read_img_index, write_meta

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "resources" / "[scavengesurvive]" / "models"
CUT_SCRIPT = ROOT / "tools" / "blender" / "cut_headgear.py"

# skin -> (dff name, texture, uv blocks or "auto", metres above the Head bone below which nothing is cut)
# Blocks are "col,row;col,row" of the 8x8 texture grid, row 0 at the top (cut_headgear.py prints the auto choice).
