"""Build the hatless ped variants for the `skin_models` resource (#75) and hat items for `hat_models` (#77).

Some GTA:SA skins carry their hat, cap or helmet in the mesh, so a worn hat pokes through it. For every skin in
HEADGEAR this pulls `<name>.dff` out of `models/gta3.img`, runs Blender headless with DragonFF
(tools/blender/cut_headgear.py) to delete the headgear faces, writes `skin_models/files/<name>_nohat.dff` and lists the variant
in `skin_models/peds.lua`; `meta.xml` is regenerated for skin_models. `items` swaps a player onto the variant on each
client while a hat is worn. The variant needs no TXD: it shares the base skin's.

    python -m tools.extract_ped_models            # every skin in HEADGEAR (skips files that exist)
    python -m tools.extract_ped_models 283 287    # only these, rebuilt
    python -m tools.extract_ped_models --check    # list what would be built
    python -m tools.extract_ped_models --hats     # the hat objects of tools/port_hats.py (#77), see below

With --hats the headgear itself is the product: for every row of tools/port_hats.py HATS the skin's `.dff` and
`.txd` come out of `gta3.img` and tools/blender/remodel_head.py (its HEADS rules, `--only hats`) exports the faces
it would delete as `hat_models/files/<ped>_hat.dff`, a static object with the Head bone at its origin; `hat_models/hats.lua` lists the
port's model ids for them (the base skin's TXD, a shared small collision file).

Blender comes from --blender, the BLENDER environment variable or the newest "Blender Foundation" install.
"""
