def write_meta_hats(out_dir: Path) -> None:
    (out_dir / "meta.xml").write_text(render_meta_hats(out_dir / "hats.lua"), encoding="ascii", newline="\n")


write_meta = write_meta_peds


def export_hat(blender: Path, work: Path, out: Path, hat: dict) -> str:
    blocks = ";".join(f"{c},{r}" for c, r in sorted(hat["blocks"]))
    cmd = [str(blender), "-b", "--python", str(REMODEL_SCRIPT), "--", str(work), str(out), "--only", "hats"]
    cmd += ["--blocks", blocks]
    if hat.get("above"):
        cmd += ["--above", ";".join(f"{c},{r},{h}" for (c, r), h in sorted(hat["above"].items()))]
    cmd.append(str(hat["skin"]))
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    notes = [line for line in res.stdout.splitlines() if ": hat of" in line]
    if res.returncode != 0 or "Traceback" in res.stdout + res.stderr:
        raise RuntimeError(f"blender failed exporting {hat['dff']}: {res.stderr[-800:]}")
    return "; ".join(notes)


def build_hats(img: Path, blender: Path, out_dir: Path, rows) -> int:
    """Dumps each hat skin's dff+txd, exports the hats through Blender and rewrites hats.lua; returns the failures."""
    index = {k.lower(): v for k, v in read_img_index(img).items()}
    files = out_dir / "files"
    files.mkdir(parents=True, exist_ok=True)
    work = out_dir / "work"
    work.mkdir(exist_ok=True)
    todo = []
    for h in rows:
        missing = [f for f in (h["ped"] + ".dff", h["ped"] + ".txd") if f not in index]
        if missing:
            print(f"warning: {missing} not in {img}", file=sys.stderr)
            continue
        for f in (h["ped"] + ".dff", h["ped"] + ".txd"):
            (work / f).write_bytes(read_img_entry(img, index[f]))
        todo.append(h)
    for h in todo:
        print(export_hat(blender, work, files, h))
    failures = len(rows) - len(todo)
    for h in todo:
        if not (files / f"{h['dff']}.dff").is_file():
            print(f"warning: {h['dff']}.dff was not written", file=sys.stderr)
            failures += 1
    for f in work.iterdir():
        f.unlink()
    work.rmdir()
    listed = [h for h in HATS if (files / f"{h['dff']}.dff").is_file()]
    (out_dir / "hats.lua").write_text(render_hats(listed), encoding="ascii", newline="\n")
    write_meta_hats(out_dir)
    return failures


def cut(blender: Path, src: Path, out: Path, texture: str, blocks: str, above: float) -> str:
    cmd = [str(blender), "-b", "--python", str(CUT_SCRIPT), "--", str(src), str(out), texture, blocks, str(above)]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    notes = [line for line in res.stdout.splitlines() if line.startswith("cut_headgear:")]
    if res.returncode != 0 or not out.is_file():
        raise RuntimeError(f"blender failed for {src.name}: {res.stderr[-800:]}")
    return "; ".join(notes)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("skins", nargs="*", type=int, help="skins to (re)build; default: every missing one")
    ap.add_argument("--gta", type=Path, help="GTA:SA folder with models/gta3.img (default: from the registry)")
    ap.add_argument("--blender", help="blender.exe (default: $BLENDER or the newest install)")
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--check", action="store_true", help="only report what would be built")
    ap.add_argument("--hats", action="store_true", help="export the hats of tools/port_hats.py instead of the twins")
    args = ap.parse_args(argv)
    out_dir = args.out or (HAT_MODELS if args.hats else SKIN_MODELS)
    known = {h["skin"] for h in HATS} if args.hats else HEADGEAR
    unknown = [s for s in args.skins if s not in known]
    if unknown:
        print(f"extract_ped_models: not in {'HATS' if args.hats else 'HEADGEAR'}: {unknown}", file=sys.stderr)
        return 2
    gta = args.gta or detect_gta()
    img = gta / "models" / "gta3.img" if gta else None
    if not img or not img.is_file():
        print("extract_ped_models: no GTA:SA install found (pass --gta)", file=sys.stderr)
        return 2
    blender = find_blender(args.blender)
    if not blender and not args.check:
        print("extract_ped_models: no blender.exe found (pass --blender)", file=sys.stderr)
        return 2
    files = out_dir / "files"
    if args.hats:
        rows = [h for h in HATS if not args.skins or h["skin"] in args.skins]
        print(f"{len(rows)} hats to export with {blender}: {[h['uname'] for h in rows]}")
        if args.check:
            return 0
        return 1 if build_hats(img, blender, out_dir, rows) else 0
    peds = read_peds(out_dir / "peds.lua")
    todo = args.skins or [s for s in HEADGEAR if not (files / f"{HEADGEAR[s][0]}_nohat.dff").is_file()]
    print(f"{len(todo)} skins to build with {blender}: {todo}")
    if args.check:
        return 0
    index = {k.lower(): v for k, v in read_img_index(img).items()}
    files.mkdir(parents=True, exist_ok=True)
    work = out_dir / "work"
    work.mkdir(exist_ok=True)
    failures = 0
    for skin in todo:
        name, texture, blocks, above = HEADGEAR[skin]
        entry = index.get(f"{name}.dff")
        if not entry:
            print(f"warning: {name}.dff not in {img}", file=sys.stderr)
            failures += 1
            continue
        src = work / f"{name}.dff"
        src.write_bytes(read_img_entry(img, entry))
        out = files / f"{name}_nohat.dff"
        try:
            print(f"{skin} {name}: {cut(blender, src, out, texture, blocks, above)}")
        except RuntimeError as e:
            print(f"warning: {e}", file=sys.stderr)
            failures += 1
            continue
        peds[skin] = f"{name}_nohat"
        src.unlink()
    if not any(work.iterdir()):
        work.rmdir()
    txds = {d for d in peds.values() if (out_dir / "files" / f"{d}.txd").is_file()}
    (out_dir / "peds.lua").write_text(render_peds(peds, txds), encoding="ascii", newline="\n")
    write_meta_peds(out_dir)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
