def hull_2d(pts):
    pts = sorted(set(pts))
    if len(pts) < 3:
        return pts

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower, upper = [], []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return lower[:-1] + upper[:-1]


def footprint(pts):
    """Heading (degrees, 0-90) of the minimum-area rectangle around the points' x/y, its centre and its sides."""
    hull = hull_2d([(round(p[0], 4), round(p[1], 4)) for p in pts])
    best = None
    for step in range(0, 360):
        a = math.radians(step / 4)
        c, s = math.cos(a), math.sin(a)
        us = [x * c + y * s for x, y in hull]
        vs = [-x * s + y * c for x, y in hull]
        area = (max(us) - min(us)) * (max(vs) - min(vs))
        if best is None or area < best[0] - 1e-9:
            best = (area, step / 4, us, vs)
    _, yaw, us, vs = best
    a = math.radians(yaw)
    cu, cv = (max(us) + min(us)) / 2, (max(vs) + min(vs)) / 2
    centre = (cu * math.cos(a) - cv * math.sin(a), cu * math.sin(a) + cv * math.cos(a))
    return yaw, centre, (max(us) - min(us), max(vs) - min(vs))


def build_in_blender(gta: Path, survey: bool) -> None:
    import bmesh
    import bpy

    from tools.extract_samp_models import read_img_entry, read_img_index

    archives = [gta / "models" / "gta3.img", gta / "models" / "gta_int.img"]
    indexes = [(a, read_img_index(a)) for a in archives]

    def entry(name):
        for path, index in indexes:
            if name.lower() in index:
                return read_img_entry(path, index[name.lower()])
        raise SystemExit(f"extract_world_boxes: {name} in neither IMG")

    def fresh():
        bpy.ops.wm.read_factory_settings(use_empty=True)
        bpy.ops.preferences.addon_enable(module="DragonFF")


    def islands(src):
        """The source's loose parts as separate objects, its breakable debris and 2dfx dropped."""
        fresh()
        tmp = str(FILES / (src["dff"] + ".src.dff"))
        FILES.mkdir(parents=True, exist_ok=True)
        open(tmp, "wb").write(entry(src["dff"] + ".dff"))
        bpy.ops.import_scene.dff(filepath=tmp)
        os.remove(tmp)
        main = [o for o in bpy.data.objects if o.type == "MESH" and not o.name.endswith("_breakable") and not o.name.startswith("2dfx")]
        for o in list(bpy.data.objects):
            if o not in main:
                bpy.data.objects.remove(o, do_unlink=True)
        for o in main:
            o.dff.export_breakable = False
            o.data.transform(o.matrix_world)
            o.matrix_world.identity()
            o.parent = None
        bpy.ops.object.select_all(action="DESELECT")
        for o in main:
            o.select_set(True)
        bpy.context.view_layer.objects.active = main[0]
        if len(main) > 1:
            bpy.ops.object.join()
        obj = bpy.context.view_layer.objects.active
        bm = bmesh.new()
        bm.from_mesh(obj.data)
        bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=0.001)
        bm.to_mesh(obj.data)
        bm.free()
        if src.get("whole"):
            return [obj]
        bpy.ops.object.mode_set(mode="EDIT")
        bpy.ops.mesh.select_all(action="SELECT")
        bpy.ops.mesh.separate(type="LOOSE")
        bpy.ops.object.mode_set(mode="OBJECT")
        return sorted((o for o in bpy.data.objects if o.type == "MESH"), key=lambda o: tuple(round(c, 3) for c in centre3(o)))

    def centre3(o):
        pts = [v.co for v in o.data.vertices]
        return [(min(p[i] for p in pts) + max(p[i] for p in pts)) / 2 for i in range(3)]

    def hull_volume(o):
        bm = bmesh.new()
        for v in o.data.vertices:
            bm.verts.new(v.co)
        try:
            bmesh.ops.convex_hull(bm, input=bm.verts)
            vol = bm.calc_volume()
        except Exception:
            vol = 0.0
        bm.free()
        return abs(vol)

    def canonical(o, yaw, centre, base):
        """Vertices and texture set of the part turned by -yaw and moved base-down onto the origin, in each of the
        four quarter turns; the first is the part's own frame."""
        texs = textures(o)
        out = []
        for q in range(4):
            a = math.radians(-(yaw + 90 * q))
            c, s = math.cos(a), math.sin(a)
            pts = []
            for v in o.data.vertices:
                x, y = v.co.x - centre[0], v.co.y - centre[1]
                pts.append((round(x * c - y * s, 2) + 0.0, round(x * s + y * c, 2) + 0.0, round(v.co.z - base, 2) + 0.0))
            out.append((tuple(sorted(pts)), tuple(texs)))
        return out

    def signature(form):
        return hashlib.sha1(repr(form).encode()).hexdigest()[:10]

    parts = {}  # sig -> { forms, source, file object data }
    placed = {}
    remnants = {}
    for src in SOURCES:
        objs = islands(src)
        boxes, rest = [], []
        for o in objs:
            pts = [v.co for v in o.data.vertices]
            yaw, centre, sides = footprint(pts)
            base = min(p.z for p in pts)
            height = max(p.z for p in pts) - base
            fill = hull_volume(o) / max(sides[0] * sides[1] * height, 1e-6)
            is_box = src.get("whole") or (min(sides) >= MIN_SIDE and height >= MIN_HEIGHT and fill >= FILL)
            if not is_box:
                rest.append(o)
                continue
            forms = canonical(o, yaw, centre, base)
            if any(signature(f) in STATIC for f in forms):  # a box by shape that stays in the remnant
                rest.append(o)
                continue
            sig, turn = None, 0
            for s, p in parts.items():
                if forms[0] in p["forms"]:
                    sig, turn = s, p["forms"].index(forms[0])
                    break
            if sig is None:
                sig = signature(forms[0])
                parts[sig] = {"forms": forms, "source": src["model"], "sides": sides, "height": height, "textures": forms[0][1],
                              "obj": o.name, "yaw": yaw, "centre": centre, "base": base, "count": 0}
                o["wbox_sig"] = sig
            parts[sig]["count"] += 1
            # the part's own frame turned by `turn` quarters matches the first one seen
            boxes.append({"sig": sig, "x": round(centre[0], 4), "y": round(centre[1], 4), "z": round(base, 4),
                          "yaw": round((yaw - 90 * turn) % 360, 2), "fill": round(fill, 2)})
        placed[src["model"]] = boxes
        remnants[src["model"]] = len(rest)
        print(f"WBOX source {src['model']} {src['dff']}: {len(boxes)} boxes, {len(rest)} other parts")
        for b in boxes:
            print(f"WBOX   box {b['sig']} at {b['x']:.2f} {b['y']:.2f} {b['z']:.2f} yaw {b['yaw']:.1f} fill {b['fill']}")
        for o in rest:
            pts = [v.co for v in o.data.vertices]
            yaw, centre, sides = footprint(pts)
            height = max(p.z for p in pts) - min(p.z for p in pts)
            print(f"WBOX   rest {sides[0]:.2f} x {sides[1]:.2f} x {height:.2f} at {centre[0]:.2f} {centre[1]:.2f}")
        if not survey:
            export_source(src, objs, rest, parts)
        if bool(rest) != bool(src.get("remnant")) and not survey:
            raise SystemExit(f"extract_world_boxes: {src['model']} has {len(rest)} other parts, remnant {src.get('remnant')}")

    for sig, p in parts.items():
        print(f"WBOX part {sig} from {p['source']}: {p['sides'][0]:.2f} x {p['sides'][1]:.2f} x {p['height']:.2f} "
              f"{list(p['textures'])} x{p['count']}")
    if survey:
        return
    by_sig = {sig: p for p in PARTS for sig in p["sigs"]}
    missing = [s for s in parts if s not in by_sig]
    if missing:
        raise SystemExit(f"extract_world_boxes: parts not in tools/world_boxes.py PARTS: {missing}")
    out = {"parts": {}, "sources": {}}
    for sig, p in parts.items():
        row = by_sig[sig]
        if row["sigs"][0] == sig:
            out["parts"][row["uname"]] = {"sides": [round(v, 3) for v in sorted(p["sides"], reverse=True)], "height": round(p["height"], 3)}
    for src in SOURCES:
        out["sources"][str(src["model"])] = {
            "boxes": [{"uname": by_sig[b["sig"]]["uname"], "x": b["x"], "y": b["y"], "z": b["z"], "yaw": b["yaw"]} for b in placed[src["model"]]],
            "remnant": src.get("remnant"),
        }
    PLACEMENTS.parent.mkdir(parents=True, exist_ok=True)
    PLACEMENTS.write_text(json.dumps(out, indent=1, sort_keys=True) + "\n", encoding="ascii", newline="\n")
    (BOX_MODELS / "boxes.lua").write_text(render_lua(), encoding="ascii", newline="\n")
    (BOX_MODELS / "meta.xml").write_text(render_meta(), encoding="ascii", newline="\n")
    print(f"WBOX wrote {len(PARTS)} parts, {sum(1 for s in SOURCES if s.get('remnant'))} remnants")


def export_source(src, objs, rest, parts):
    """Writes the PARTS first seen in this source and the source's remnant (DFF, COL, TXD)."""
    import bpy

    by_sig = {sig: p for p in PARTS for sig in p["sigs"]}
    for o in objs:
        sig = o.get("wbox_sig")
        if not sig or sig not in by_sig or by_sig[sig]["sigs"][0] != sig:
            continue
        p = parts[sig]
        a = math.radians(-p["yaw"])
        c, s = math.cos(a), math.sin(a)
        for v in o.data.vertices:
            x, y = v.co.x - p["centre"][0], v.co.y - p["centre"][1]
            v.co.x, v.co.y, v.co.z = x * c - y * s, x * s + y * c, v.co.z - p["base"]
        o.data.update()
        write_model(o, part_file(by_sig[sig]), src)
    if rest:
        bpy.ops.object.select_all(action="DESELECT")
        for o in rest:
            o.select_set(True)
        bpy.context.view_layer.objects.active = rest[0]
        if len(rest) > 1:
            bpy.ops.object.join()
        write_model(bpy.context.view_layer.objects.active, remnant_file(src), src)


def write_model(obj, name, src):
    """obj alone in a fresh collection, with a box of collision over its bounds, exported as files/<name>.dff/.col,
    and the source TXD cut down to obj's textures as files/<name>.txd."""
    import bpy

    from tools.extract_samp_models import detect_gta, read_img_entry, read_img_index, trim_txd

    coll = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(coll)
    for c in list(obj.users_collection):
        c.objects.unlink(obj)
    coll.objects.link(obj)
    obj.name = name
    obj.dff.type = "OBJ"
    pts = [v.co for v in obj.data.vertices]
    lo = [min(p[i] for p in pts) for i in range(3)]
    hi = [max(p[i] for p in pts) for i in range(3)]
    box = bpy.data.objects.new(name + "_col", None)
    box.empty_display_type = "CUBE"
    box.location = [(lo[i] + hi[i]) / 2 for i in range(3)]
    box.scale = [max((hi[i] - lo[i]) / 2, 0.01) for i in range(3)]
    box.dff.type = "COL"
    coll.objects.link(box)
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    box.select_set(True)
    bpy.ops.export_dff.scene(filepath=str(FILES / f"{name}.dff"), export_coll=False, only_selected=True, export_version="0x36003")
    bpy.ops.export_col.scene(filepath=str(FILES / f"{name}.col"), export_version="3", only_selected=True)
    used = {t.lower() for t in textures(obj) if t}
    gta = Path(os.environ["WBOX_GTA"]) if os.environ.get("WBOX_GTA") else detect_gta()
    for img in (gta / "models" / "gta3.img", gta / "models" / "gta_int.img"):
        index = read_img_index(img)
        if src["txd"].lower() + ".txd" in index:
            (FILES / f"{name}.txd").write_bytes(trim_txd(read_img_entry(img, index[src["txd"].lower() + ".txd"]), used))
            break
    else:
        raise SystemExit(f"extract_world_boxes: {src['txd']}.txd in neither IMG")
    bpy.data.objects.remove(box, do_unlink=True)
    print(f"WBOX wrote {name} {sorted(used)}")


def main(argv=None) -> int:
    import argparse
    import subprocess

    from tools.extract_ped_models import find_blender
    from tools.extract_samp_models import detect_gta

    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--survey", action="store_true", help="print the parts and remnants, write nothing")
    ap.add_argument("--gta", type=Path, help="GTA:SA folder (default: from the registry)")
    ap.add_argument("--blender", help="blender.exe (default: BLENDER or the newest install)")
    args = ap.parse_args(argv)
    gta = args.gta or detect_gta()
    if not gta or not (gta / "models" / "gta3.img").is_file():
        print("extract_world_boxes: no GTA:SA models/gta3.img (pass --gta)", file=sys.stderr)
        return 2
    blender = find_blender(args.blender)
    if not blender:
        print("extract_world_boxes: no Blender found (pass --blender)", file=sys.stderr)
        return 2
    cmd = [str(blender), "-b", "--python", __file__, "--", str(gta)] + (["--survey"] if args.survey else [])
    res = subprocess.run(cmd, capture_output=True, text=True, env=dict(os.environ, WBOX_GTA=str(gta)))
    out = res.stdout + res.stderr
    print("\n".join(line[5:] if line.startswith("WBOX ") else line for line in out.splitlines()
                    if line.startswith("WBOX") or "Error" in line or "extract_world_boxes" in line))
    if res.returncode != 0 or args.survey:
        return res.returncode
    # the Rockstar placements of the sources, so tools/convert needs no game copy
    from tools.ipl_natives import native_placements

    data = json.loads(PLACEMENTS.read_text())
    rows = native_placements(gta, {s["model"] for s in SOURCES})
    natives = [[m, *(round(v, 4) for v in pos), interior, *(round(v, 6) for r in rot for v in r)] for m, pos, rot, interior in rows]
    data["natives"] = sorted(natives)
    PLACEMENTS.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n", encoding="ascii", newline="\n")
    print(f"{len(rows)} Rockstar placements of the sources -> {PLACEMENTS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    if "bpy" in sys.modules or "--" in sys.argv:
        rest = sys.argv[sys.argv.index("--") + 1 :]
        build_in_blender(Path(rest[0]), "--survey" in rest)
    else:
        sys.exit(main())
