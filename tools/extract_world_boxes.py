"""Cuts GTA's boxes, crates and bags (tools/world_boxes.py SOURCES) into port models for box_models.

    python -m tools.extract_world_boxes [--survey] [--gta DIR] [--blender EXE]

Outside Blender it runs itself in Blender (DragonFF). Each source DFF is imported without its breakable debris and
2dfx, welded, and split into loose parts. A part is a box when it fills its footprint (the minimum-area rectangle of
its convex hull, which also gives its heading) at least FILL of the way and stands at least MIN_SIDE wide and MIN_HEIGHT
tall; a `whole` source is one box as it is. Each box is turned onto its footprint and moved base-down onto the origin;
equal boxes (the same vertices and textures in one of four quarter turns) are one part, named by a signature.

--survey prints every part with its signature, size and textures, and every composite's remnant, and writes nothing.
Otherwise each PARTS row is written as box_models/files/<file>.dff/.col/.txd (a box of collision over its bounds, the
source TXD cut down to its textures), each remnant (the composite without its boxes, at the source's origin) the same
way, box_models/boxes.lua and meta.xml are rewritten, and tools/data/world_box_parts.json says where each source's
boxes lie in it: { parts: { uname: { sides, height } }, sources: { model: { boxes: [ { uname, x, y, z, yaw } ],
remnant: id } }, natives: [ [ model, x, y, z, interior, rotation matrix row by row ] ] }, the latter the Rockstar
placements of the sources (tools/ipl_natives.py native_placements), so tools/convert needs no game copy.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools.world_boxes import PARTS, SOURCES, STATIC  # noqa: E402

BOX_MODELS = ROOT / "resources" / "[scavengesurvive]" / "box_models"
FILES = BOX_MODELS / "files"
PLACEMENTS = ROOT / "tools" / "data" / "world_box_parts.json"
FILL, MIN_SIDE, MIN_HEIGHT = 0.4, 0.35, 0.35
DIST = 120


def textures(obj) -> list[str]:
    """The texture names obj's faces wear ("" for an untextured material), sorted."""
    out = set()
    for i in {p.material_index for p in obj.data.polygons}:
        m = obj.data.materials[i] if i < len(obj.data.materials) else None
        nodes = m.node_tree.nodes if m and m.node_tree else []
        node = next((n for n in nodes if n.type == "TEX_IMAGE" and n.image), None)
        out.add((node.label or node.image.name).split(".")[0] if node else "")
    return sorted(out)


def part_file(row: dict) -> str:
    return "wbox_" + row["uname"].lower()


def remnant_file(src: dict) -> str:
    return "wbox_" + src["dff"].lower() + "_rest"


def render_lua() -> str:
    lines = [
        "-- Generated by tools/extract_world_boxes.py; do not edit. Port model id -> a box cut out of GTA's map (an item)",
        "-- or what is left of the model it came from, in box_models/files/ with its own TXD and collision.",
        "return {",
    ]
    rows = [(p["model"], part_file(p)) for p in PARTS] + [(s["remnant"], remnant_file(s)) for s in SOURCES if s.get("remnant")]
    for model, name in sorted(rows):
        lines.append(f'    [{model}] = {{ dff = "{name}", txd = "{name}", dist = {DIST} }},')
    return "\n".join(lines + ["}", ""])


def render_meta() -> str:
    names = sorted([part_file(p) for p in PARTS] + [remnant_file(s) for s in SOURCES if s.get("remnant")])
    lines = [
        "<meta>",
        '    <info author="scavengesurvive-mta" type="script" name="box_models" '
        'description="GTA boxes, crates and bags cut into item models" version="0.1.0"/>',
        '    <min_mta_version server="1.6.0" client="1.6.0-9.21695"/>',
        "    <download_priority_group>90</download_priority_group>",
        '    <include resource="lib"/>',
        '    <script src="client/main.lua" type="client"/>',
        '    <file src="boxes.lua"/>',
    ]
    for n in names:
        lines += [f'    <file src="files/{n}.col"/>', f'    <file src="files/{n}.dff"/>', f'    <file src="files/{n}.txd"/>']
    lines += ['    <export function="resolve" type="client"/>', "</meta>"]
    return "\n".join(lines) + "\n"


