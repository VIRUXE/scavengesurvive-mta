"""Writes the re-pivoted copies of the hinged defence doors (tools/port_defences.py, #149). Run inside Blender with the
DragonFF addon enabled:

    blender -b --python tools/repivot_defences.py -- [GTA_DIR]

For each row: the vanilla DFF comes out of its IMG archive, its mesh is moved by -pivot in model space and exported
as samp_models/files/<name>_def.dff; the vanilla COL (from the archive's collision library) is moved the same way, every
section of it (bounds, spheres, boxes, face groups, mesh and shadow mesh vertices), and written as <name>_def.col.
The measured footprint centre must match the row's pivot to 1/256 m, else the run stops and prints the value to put
in the table. Then samp_models/defences.lua (port id -> files, the vanilla TXD and physical properties group) and
samp_models/meta.xml are rewritten.
"""
import os
import struct
import sys
from pathlib import Path

import bpy
from mathutils import Vector

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
from tools.extract_samp_models import detect_gta, parse_col_library, read_img_entry, read_img_index, write_meta  # noqa: E402
from tools.port_defences import DEFENCES  # noqa: E402

MODELS = os.path.join(ROOT, "resources", "[scavengesurvive]", "samp_models")
FILES = os.path.join(MODELS, "files")
DEFENCES_LUA = os.path.join(MODELS, "defences.lua")
DIST = 100


def fresh():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.preferences.addon_enable(module="DragonFF")


def mesh_bounds():
    pts = [o.matrix_world @ v.co for o in bpy.data.objects if o.type == "MESH" for v in o.data.vertices]
    return [min(p[i] for p in pts) for i in range(3)], [max(p[i] for p in pts) for i in range(3)]


def build_dff(src: bytes, pivot, out: str):
    """The vanilla mesh moved by -pivot in model space; returns the measured footprint centre (x, y) before the move."""
    fresh()
    tmp = out + ".src.dff"
    open(tmp, "wb").write(src)
    bpy.ops.import_scene.dff(filepath=tmp)
    os.remove(tmp)
    lo, hi = mesh_bounds()
    centre = ((lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2)
    shift = Vector(pivot)
    for o in bpy.data.objects:
        if o.type != "MESH":
            continue
        inv = o.matrix_world.inverted()
        for v in o.data.vertices:
            v.co = inv @ (o.matrix_world @ v.co - shift)
        o.data.update()
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.export_dff.scene(filepath=out, export_coll=False, only_selected=False, export_version="0x36003")
    return centre


def move_col(chunk: bytes, name: str, pivot) -> bytes:
    """A COL2/COL3 chunk moved by -pivot. pivot is in 1/128 m steps, so the fixed-point vertices shift exactly."""
    c = bytearray(chunk)
    version = c[:4]
    assert version in (b"COL2", b"COL3"), f"{name}: {version!r} not handled"
    c[8:30] = name.encode("ascii").ljust(22, b"\0")[:22]
    px, py, pz = pivot
    steps = [round(v * 128) for v in pivot]
    assert all(abs(s / 128 - v) < 1e-9 for s, v in zip(steps, pivot)), f"{name}: pivot not in 1/128 m steps"

    def move(off):
        x, y, z = struct.unpack_from("<3f", c, off)
        struct.pack_into("<3f", c, off, x - px, y - py, z - pz)

    def move_verts(at, count):
        for i in range(count):
            vx, vy, vz = struct.unpack_from("<3h", c, at + i * 6)
            struct.pack_into("<3h", c, at + i * 6, vx - steps[0], vy - steps[1], vz - steps[2])

    def faces_max(at, count):
        top = -1
        for i in range(count):
            top = max(top, *struct.unpack_from("<3H", c, at + i * 8))
        return top + 1

    move(32)  # bounds min
    move(44)  # bounds max
    move(56)  # bounding sphere centre
    spheres, boxes, faces = struct.unpack_from("<3H", c, 72)
    flags, sphere_at, box_at, _lines_at, verts_at, faces_at = struct.unpack_from("<6I", c, 80)
    for i in range(spheres):
        move(sphere_at + 4 + i * 20)
    for i in range(boxes):
        move(box_at + 4 + i * 28)
        move(box_at + 4 + i * 28 + 12)
    if faces:
        move_verts(verts_at + 4, faces_max(faces_at + 4, faces))
        if flags & 8:  # face groups: a count just before the faces, the groups before it
            groups = struct.unpack_from("<I", c, faces_at)[0]
            for i in range(groups):
                at = faces_at - groups * 28 + i * 28
                move(at)
                move(at + 12)
    if version == b"COL3":
        shadow_faces, shadow_verts_at, shadow_faces_at = struct.unpack_from("<3I", c, 108)
        if shadow_faces:
            move_verts(shadow_verts_at + 4, faces_max(shadow_faces_at + 4, shadow_faces))
    return bytes(c)


def lua(rows) -> str:
    head = [
        "-- Generated by tools/repivot_defences.py; do not edit. Port model id -> a hinged vanilla defence door moved onto",
        "-- the middle of its footprint (tools/port_defences.py), in samp_models/files/; parent lends its physical properties group.",
        "return {",
    ]
    body = [f'    [{d["model"]}] = {{ dff = "{d["name"]}_def", txdModel = {d["vanilla"]}, parent = {d["vanilla"]}, dist = {DIST} }},' for d in rows]
    return "\n".join(head + body + ["}", ""])


argv = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
gta = argv[0] if argv else str(detect_gta())
archives = {}
wrong = []
for d in DEFENCES:
    img = os.path.join(gta, "models", d["img"])
    if img not in archives:
        archives[img] = read_img_index(img)
    index = archives[img]
    out = d["name"] + "_def"
    centre = build_dff(read_img_entry(img, index[d["name"] + ".dff"]), d["pivot"], os.path.join(FILES, out + ".dff"))
    if any(abs(m - p) > 1 / 256 for m, p in zip(centre, d["pivot"][:2])):
        wrong.append(f"{d['uname']}: measured footprint centre {centre[0]:.4f}, {centre[1]:.4f} -> pivot ({round(centre[0] * 128) / 128}, {round(centre[1] * 128) / 128}, 0.0)")
        continue
    col = parse_col_library(read_img_entry(img, index[d["col"]]))[d["name"]]
    open(os.path.join(FILES, out + ".col"), "wb").write(move_col(col, out, d["pivot"]))
    print("DEFENCE", d["uname"], d["model"], out, "centre %.4f %.4f" % centre)
if wrong:
    print("PIVOT MISMATCH, fix tools/port_defences.py:\n" + "\n".join(wrong))
    sys.exit(1)
open(DEFENCES_LUA, "w", newline="\n").write(lua(DEFENCES))
write_meta(Path(MODELS))
