"""Writes the crafting resource's item icons for the /recipes window.

    python -m tools.recipe_icons

Reads docs/images/items/all/index.json and its 512px renders (written by tools.render_item_models --all --set all),
crops each render to its visible pixels, pads it square and scales it to SIZE px into
resources/[scavengesurvive]/crafting/client/icons/, then writes the uname -> file map (client/icons.lua) and the
meta.xml <file> lines between the icons markers. Run it again after re-rendering items.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RENDERS = ROOT / "docs" / "images" / "items" / "all"
RESOURCE = ROOT / "resources" / "[scavengesurvive]" / "crafting"
ICONS = RESOURCE / "client" / "icons"
MAP = RESOURCE / "client" / "icons.lua"
META = RESOURCE / "meta.xml"
SIZE = 64
PAD = 2  # transparent border so the scaled edge does not clip


def icon(src: Path, dst: Path) -> None:
    im = Image.open(src).convert("RGBA")
    box = im.getchannel("A").getbbox()
    if box:
        im = im.crop(box)
    side = max(im.size)
    square = Image.new("RGBA", (side, side))
    square.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    inner = SIZE - 2 * PAD
    out = Image.new("RGBA", (SIZE, SIZE))
    out.paste(square.resize((inner, inner), Image.LANCZOS), (PAD, PAD))
    out.save(dst, optimize=True)


def main() -> int:
    index: dict[str, str] = json.loads((RENDERS / "index.json").read_text(encoding="utf8"))
    index = {u: f for u, f in index.items() if (RENDERS / f).is_file()}
    files = sorted(set(index.values()))
    ICONS.mkdir(parents=True, exist_ok=True)
    for old in ICONS.glob("*.png"):
        if old.name not in files:
            old.unlink()
    for f in files:
        icon(RENDERS / f, ICONS / f)
    rows = "\n".join(f'    {u} = "{f}",' for u, f in sorted(index.items()))
    MAP.write_text(
        "-- Generated by tools/recipe_icons.py from docs/images/items/all/index.json. Do not edit.\n"
        f"return {{\n{rows}\n}}\n",
        encoding="utf8",
    )
    lines = "\n".join(f'    <file src="client/icons/{f}"/>' for f in files)
    meta = META.read_text(encoding="utf8")
    block = f"    <!-- icons:begin (tools/recipe_icons.py) -->\n{lines}\n    <!-- icons:end -->"
    pattern = re.compile(r"    <!-- icons:begin.*?<!-- icons:end -->", re.S)
    meta = pattern.sub(lambda _: block, meta) if pattern.search(meta) else meta.replace("</meta>", f"{block}\n</meta>")
    META.write_text(meta, encoding="utf8")
    size = sum((ICONS / f).stat().st_size for f in files)
    print(f"recipe_icons: {len(index)} items, {len(files)} icons, {size // 1024} KiB -> {ICONS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
