"""Writes the sfx resource's catalog of GTA:SA's sound effects (resources/[scavengesurvive]/sfx/data/catalog.lua).

    python -m tools.sfx_catalog [--gta DIR]

audio/CONFIG/PakFiles.dat names the SFX packs (FEET, GENRL, ...), BankLkup.dat lists every bank as (pack, offset,
size); a bank starts with a 4804-byte header, the count of its sounds then 400 slots of (offset, loop offset, sample
rate, headroom), mono 16-bit PCM after it. MTA's playSFX(container, bank, sound) counts banks within their pack from
0 and sounds within their bank from 0, as this catalog does. Each sound is its length in seconds (2 decimals),
negative when it loops. Only the game's lookup tables and sample counts are read; nothing of the audio is copied.
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "resources" / "[scavengesurvive]" / "sfx" / "data" / "catalog.lua"
HEADER = 4804


def read_catalog(gta: Path) -> dict[str, list[list[float]]]:
    config, sfx = gta / "audio" / "CONFIG", gta / "audio" / "SFX"
    paks = open(config / "PakFiles.dat", "rb").read()
    names = [paks[i : i + 52].split(b"\0")[0].decode().lower() for i in range(0, len(paks), 52)]
    lookup = open(config / "BankLkup.dat", "rb").read()
    banks = [struct.unpack_from("<BxxxII", lookup, i) for i in range(0, len(lookup), 12)]
    out: dict[str, list[list[float]]] = {n: [] for n in names}
    blobs = {}
    for pak, offset, size in banks:
        name = names[pak]
        if name not in blobs:
            blobs[name] = open(sfx / name.upper(), "rb").read()
        blob = blobs[name]
        count = struct.unpack_from("<H", blob, offset)[0]
        slots = [struct.unpack_from("<IiHH", blob, offset + 4 + i * 12) for i in range(count)]
        sounds = []
        for i, (start, loop, rate, _) in enumerate(slots):
            end = slots[i + 1][0] if i + 1 < count else size
            secs = round(max(0, end - start) / 2 / rate, 2) if rate else 0.0
            sounds.append(-secs if loop >= 0 else secs)
        out[name].append(sounds)
    return out


def render(catalog: dict[str, list[list[float]]]) -> str:
    lines = [
        "-- Generated by tools/sfx_catalog.py from the game's audio/CONFIG tables; do not edit. GTA:SA's sound effects as",
        "-- MTA's playSFX numbers them: container -> banks from 0 -> sounds from 0, each its length in seconds (negative",
        "-- when it loops).",
        "return {",
        "    order = { " + ", ".join(f'"{n}"' for n in catalog) + " },",
    ]
    for name, banks in catalog.items():
        lines.append(f"    {name} = {{")
        for sounds in banks:
            lines.append("        { " + ", ".join(f"{s:g}" for s in sounds) + " },")
        lines.append("    },")
    return "\n".join(lines + ["}", ""])


def main(argv=None) -> int:
    from tools.extract_samp_models import detect_gta

    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gta", type=Path, help="GTA:SA folder (default: from the registry)")
    args = ap.parse_args(argv)
    gta = args.gta or detect_gta()
    if not gta or not (gta / "audio" / "CONFIG" / "BankLkup.dat").is_file():
        print("sfx_catalog: no GTA:SA audio/CONFIG/BankLkup.dat (pass --gta)", file=sys.stderr)
        return 2
    catalog = read_catalog(gta)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(catalog), encoding="ascii", newline="\n")
    total = sum(len(s) for banks in catalog.values() for s in banks)
    print(f"sfx_catalog: {sum(len(b) for b in catalog.values())} banks, {total} sounds -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
