"""Writes house_shell/cabins.lua: the DFF/COL replacing the vanilla log cabin row (model 17067), its door leaf, where each
of the six cabins' leaves hangs in the model's frame (tools/trailer_shells/build/cw2_logcabins*.json, written by
tools/cabin_shells/cw2_logcabins.py) and every upright vanilla placement of the model in the world (the binary IPLs),
less the ones upstream's maps remove (RemoveBuildingForPlayer rows in maps/data/*.lua).

    python -m tools.cabin_shells.doors [--gta DIR]
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

from tools.extract_samp_models import detect_gta
from tools.ipl_natives import native_instances
from tools.trailer_shells.doors import OUT as TRAILERS_OUT
from tools.trailer_shells.doors import UPRIGHT, removals, removed
from tools.trailer_shells.prep import BUILD

MODEL, NAME = 17067, "cw2_logcabins"
OUT = TRAILERS_OUT.with_name("cabins.lua")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gta", type=Path, help="GTA:SA folder (default: from the registry)")
    args = ap.parse_args(argv)
    gta = args.gta or detect_gta()
    if not gta:
        print("cabin_shells.doors: no GTA:SA folder (pass --gta)", file=sys.stderr)
        return 2
    meta = json.loads((BUILD / f"{NAME}.json").read_text())
    cabins = json.loads((BUILD / f"{NAME}_cabins.json").read_text())["cabins"]
    rows = removals()
    placed = []
    for model, pos, rot in native_instances(gta):
        if model == MODEL and rot[2][2] >= UPRIGHT and not removed(model, pos, rows):
            placed.append((pos[0], pos[1], pos[2], math.degrees(math.atan2(rot[1][0], rot[0][0])) % 360))
    lines = [
        "-- Generated by tools/cabin_shells/doors.py; do not edit. The enterable log cabin row: the model's DFF and COL",
        "-- (files/, TXD files/cw2_logcabins.txd), its door leaf, hinged at x, y, z, rz in each cabin's frame (the model",
        "-- holds six cabins), then each upright vanilla placement the maps keep, as { x, y, z, rz }.",
        "return {",
        f"    model = {MODEL},",
        f'    dff = "{NAME}",',
        f'    door = {{ dff = "{NAME}_door", rz = {meta["door"]["rz"]:.1f} }},',
        "    hinges = {",
    ]
    lines += [f"        {{ {c['hinge'][0]:.3f}, {c['hinge'][1]:.3f}, {c['hinge'][2]:.3f} }}," for c in cabins]
    lines += ["    },", "    placements = {"]
    lines += [f"        {{ {x:.3f}, {y:.3f}, {z:.3f}, {rz:.1f} }}," for x, y, z, rz in placed]
    lines += ["    },", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"cabin_shells.doors: {len(cabins)} cabins, {len(placed)} placements -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
