"""Extract defence collision primitives for the building server.

Run from the repository root with python -m tools.defence_collision <GTA directory>.
Custom models use the same COL files the client loads, including re-pivoted doors.
"""
import argparse
import re
import struct
from pathlib import Path

from tools.extract_samp_models import (
    ITEM_TYPES,
    RESOURCES,
    SAMP_MODELS,
    parse_col_library,
    read_img_entry,
    read_img_index,
)

VANILLA = {
    2904: "warehouse_door1",
    5153: "stuntramp7_las2",
    16637: "ghostgardoor",
    18553: "count_ammundoor",
}
COVERING = 19908
DESTINATION = RESOURCES / "building" / "server" / "defence_collision_models.lua"


def vanilla_collision(models):
    missing = set(VANILLA.values())
    for archive in (models / "gta3.img", models / "gta_int.img"):
        for filename, entry in read_img_index(archive).items():
            if not filename.endswith(".col"):
                continue
            for name, chunk in parse_col_library(read_img_entry(archive, entry)).items():
                if name in missing:
                    yield name, chunk
                    missing.remove(name)
            if not missing:
                return
    raise ValueError(f"Missing vanilla collision models: {sorted(missing)}")


def extract_geometry(chunk):
    if chunk[:4] not in (b"COL2", b"COL3"):
        raise ValueError(f"Unsupported collision format: {chunk[:4]!r}")
    sphere_count, box_count, face_count = struct.unpack_from("<3H", chunk, 72)
    if sphere_count or not (box_count or face_count):
        raise ValueError("Expected defence collision made of boxes or triangles")

    _, _, box_offset, _, vertex_offset, face_offset = struct.unpack_from("<6I", chunk, 80)
    bounds = struct.unpack_from("<6f", chunk, 32)
    boxes = [struct.unpack_from("<6f", chunk, box_offset + 4 + i * 28) for i in range(box_count)]
    faces = [struct.unpack_from("<3H", chunk, face_offset + 4 + i * 8) for i in range(face_count)]
    vertex_count = max(map(max, faces), default=-1) + 1
    vertices = [
        tuple(coord / 128 for coord in struct.unpack_from("<3h", chunk, vertex_offset + 4 + i * 6))
        for i in range(vertex_count)
    ]
    return bounds, boxes, vertices, [tuple(idx + 1 for idx in face) for face in faces]


def lua_row(values):
    return "{ " + ", ".join(f"{number:.9g}" for number in values) + " }"


def render(models, vanilla, custom):
    lines = ["-- Generated by tools/defence_collision.py from the models' COL files.", "return {"]
    for model in sorted(models):
        if model in VANILLA:
            name = VANILLA[model]
            chunk = vanilla[name]
        else:
            name = custom[model]
            chunk = (SAMP_MODELS / "files" / f"{name}.col").read_bytes()
        bounds, boxes, vertices, faces = extract_geometry(chunk)
        lines.extend([f"    [{model}] = {{ -- {name}", f"        bounds = {lua_row(bounds)},"])
        for key, rows in (("boxes", boxes), ("vertices", vertices), ("faces", faces)):
            if rows:
                lines.append(f"        {key} = {{")
                lines.extend(f"            {lua_row(row)}," for row in rows)
                lines.append("        },")
        lines.append("    },")
    return "\n".join([*lines, "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("gta_directory", type=Path)
    args = parser.parse_args()
    models = {
        int(re.search(r"\bmodel = (\d+)", line)[1])
        for line in ITEM_TYPES.read_text(encoding="utf-8").splitlines()
        if "defence = {" in line
    } | {COVERING}
    custom = {
        int(model): name
        for file in ("manifest.lua", "defences.lua")
        for model, name in re.findall(r'\[(\d+)\] = \{ dff = "([^"]+)"', (SAMP_MODELS / file).read_text())
    }
    vanilla = dict(vanilla_collision(args.gta_directory / "models"))
    DESTINATION.write_text(render(models, vanilla, custom), encoding="ascii")


if __name__ == "__main__":
    main()
